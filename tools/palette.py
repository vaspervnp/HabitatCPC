"""Τα 27 χρώματα του firmware του CPC, σε RGB — μόνο για προεπισκόπηση.

Το υλικό δεν βλέπει ποτέ αυτόν τον πίνακα: ο `palette_fw` των assets κρατά
αριθμούς firmware και το hw.asm τους μεταφράζει σε τιμές υλικού. Εδώ είναι για
να μπορεί ένας άνθρωπος να κοιτάξει ό,τι σχεδιάστηκε.
"""

FW_RGB = [
    (0, 0, 0), (0, 0, 128), (0, 0, 255),
    (128, 0, 0), (128, 0, 128), (128, 0, 255),
    (255, 0, 0), (255, 0, 128), (255, 0, 255),
    (0, 128, 0), (0, 128, 128), (0, 128, 255),
    (128, 128, 0), (128, 128, 128), (128, 128, 255),
    (255, 128, 0), (255, 128, 128), (255, 128, 255),
    (0, 255, 0), (0, 255, 128), (0, 255, 255),
    (128, 255, 0), (128, 255, 128), (128, 255, 255),
    (255, 255, 0), (255, 255, 128), (255, 255, 255),
]


def pen_rgb(palette_fw):
    """16 firmware αριθμοί -> 16 RGB."""
    return [FW_RGB[c] for c in palette_fw]
