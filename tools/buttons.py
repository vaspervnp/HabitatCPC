ORDER = list(ART)


def pixels(name):
    """[[0/1] * 12] * 11"""
    rows = ART[name].strip("\n").split("\n")
    rows = [r.strip() for r in rows]
    assert len(rows) == H and all(len(r) == W for r in rows), name
    return [[1 if c == "#" else 0 for c in r] for r in rows]


def pack(px):
    lo = bytes(sum(px[y][x] << (7 - x) for x in range(8)) for y in range(H))
    nib = [sum(px[y][8 + x] << (3 - x) for x in range(4)) for y in range(H)] + [0]
    hi = bytes(nib[2 * k] << 4 | nib[2 * k + 1] for k in range(6))
    return lo + hi


def gfx():
    """Τα 34 σύμβολα (33 ως το βήμα 92), με τη σειρά, 17 bytes το καθένα."""
    return b"".join(pack(pixels(n)) for n in ORDER)


