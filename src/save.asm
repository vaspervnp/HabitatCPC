; save.asm — σώσιμο και φόρτωμα, τρία slots στον δίσκο (DESIGN §11)
;
; ΤΙ ΣΩΖΕΤΑΙ, ΚΑΙ ΓΙΑΤΙ ΤΟΣΟ ΛΙΓΟ. Τρία μπλοκ και μια κεφαλίδα:
;
;   κεφαλίδα     1 τομέας    μαγικό, έκδοση, seed, πλανήτης, κάμερα, κέρσορας
;   επίπεδο     32 τομείς    η τράπεζα 4 ολόκληρη — 16 KB, αυτούσια
;   οντότητες   13 τομείς    #6600-#7FFF της τράπεζας 6: seed, θόλοι, δομές,
;                            κατοχή θέσεων, σημάδια, πράκτορες (βήμα 172· ως
;                            τότε 9, #6C00-#7DFF, οι πράκτορες πρώτοι)
;   διάδρομοι    1 τομέας    G_corr_tbl στην τράπεζα 5 (βήμα 154· ως τότε στην
;                            6, μέσα στις οντότητες)
;   κατάσταση    4 τομείς    SV_STATE, τα 2 KB κάτω από το G_hud_shadow στην
;                            τράπεζα 2: οικονομία, εργασίες, γράφος κόμβων
;
; Το επίπεδο σώζεται ΟΛΟΚΛΗΡΟ (§5.10): η αναγέννηση από το seed κοστίζει 5
; δευτερόλεπτα (13,5 ως το βήμα 111) και θα ήθελε πίσω τη λίστα αλλαγών· τα
; 16 KB κοστίζουν λιγότερο από ένα στον εξομοιωτή.
;
; ΔΕΝ σώζεται τίποτε παράγωγο: ούτε το NEXTHOP (ξαναχτίζεται από τον τροχό),
; ούτε το dome_fig (ξαναχτίζεται από τους πράκτορες), ούτε η λίστα βρώμικων,
; ούτε η θέση του τροχού. Το φόρτωμα τα ξαναφτιάχνει ΟΛΑ, με την ίδια σειρά
; που τα φτιάχνει μια νέα παρτίδα — αλλιώς δύο ίδιες καταστάσεις θα έδιναν
; διαφορετική οθόνη.
;
; ΠΟΥ ΣΤΟΝ ΔΙΣΚΟ. Οι τομείς των slots δεν ανήκουν σε αρχείο AMSDOS: ο δίσκος
; είναι δικός μας και το tools/mkdsk.py αφήνει τα tracks 24-41 άδεια. Ενα slot
; είναι 6 tracks (54 τομείς) και χρησιμοποιεί 51 (47 ως το βήμα 171, 46 ως το 153).

SV_T0       equ 24                  ; πρώτος track του slot 0
SV_TRACKS   equ 6
SV_SLOTS    equ 3
SV_VER      equ 12                  ; 2 από το βήμα 33: άλλη διάταξη της τράπεζας 2·
                                    ; 3 από το 87: ίδια διάταξη, άλλα νοήματα — οι
                                    ; διάδρομοι προς εργοτάξιο δεν είναι ακμές, το
                                    ; F_INDOORS μετράει, το ST_JOINED των airlock.
                                    ; Ενα σώσιμο του 86 απορρίπτεται, δεν παρερμηνεύεται.
                                    ; 4 από το 90: το SV_STATE μετακινήθηκε μέσα στην
                                    ; τράπεζα 2 στο 89 (ΧΩΡΙΣ νέα έκδοση — λάθος) και
                                    ; ξανά στο 90, και το skill έγινε η στολή.
                                    ; 5 από το 91: η οικονομία 92 -> 97 (EC_LAND),
                                    ; και ό,τι ακολουθεί πέντε bytes πιο κάτω.
                                    ; 6 από το 92: ίδια διάταξη, άλλα νοήματα — οι
                                    ; θέσεις 80-95 είναι των ρομπότ, χωρίς ανάγκες,
                                    ; και ένα σώσιμο του 91 με πάνω από 80 αποίκους
                                    ; θα τους έδινε για ρομπότ.
                                    ; 7 από το 93: η οικονομία 97 -> 106 (ο
                                    ; έμπορος: κέρδος και φορτίο).
                                    ; 8 από το 94: η οικονομία 106 -> 107 (τα
                                    ; ορυχεία, EC_MINES), και το έβδομο byte ενός
                                    ; ορυχείου μετράει όσους σκάβουν (ST_OPS).
                                    ; 9 από το 111: η οικονομία 107 -> 108 (οι
                                    ; προσγειώσεις, EC_LANDS), οι θέσεις 96-99
                                    ; είναι των εισβολέων και το bit 7 των
                                    ; σημαιών το όπλο ενός φρουρού.
                                    ; 10 από το 154: τα LK_OWN στην τελευταία
                                    ; σελίδα του node_adj, με άλλη γραφή (η
                                    ; σύνδεση εδάφους χωρίς το bit 6, «τίποτα»
                                    ; το #3F): ένα 0 εκεί θα ήταν σύνδεση ως το
                                    ; σκάφος.
                                    ; 11 από το 159: 128 διάδρομοι, ο τομέας τους
                                    ; ολόκληρος· ένα σώσιμο της 10 έχει στις θέσεις
                                    ; 97-127 bytes του ευρετηρίου αντικειμένων.
                                    ; Απορρίπτεται (η επιλογή του χρήστη).
                                    ; 12 από το 172: ένα πεδίο ανά σελίδα, 13
                                    ; τομείς από το #6600 με άλλη σειρά, και ο
                                    ; χάρτης των εισβολέων και τα EC_X στο
                                    ; node_occ.
SV_HDR      equ GH_BUF              ; 512 δανεικά bytes από το ημερολόγιο του
                                    ; φαντάσματος: σώζουμε μόνο σε κατάσταση
                                    ; LOOK, όπου δεν υπάρχει φάντασμα
        assert  512 <= GH_LOG       ; το αρχείο μίκρυνε στο βήμα 41
        ; ΚΑΙ Ο ΚΩΔΙΚΑΣ ΑΜΕΣΩΣ ΜΕΤΑ (βήμα 103): αυτό το αρχείο και το src/fdc.asm
        ; τρέχουν από το SV_ORG, όπου τα φέρνει από τις τρύπες του DIST το sv_ovl
        ; (src/demolish.asm, src/main.asm). Εδώ μέσα οι είσοδοι είναι svo_save
        ; και svo_load· τα sv_save και sv_load είναι οι είσοδοι της τράπεζας 2.
        assert  SV_ORG == SV_HDR + 512

; ---------------------------------------------------------------------------
; svo_save — A = slot. Out: Z και A=0 αν πέτυχε. (Από το sv_save.)
; ---------------------------------------------------------------------------
svo_save:
        ld      (sv_slot),a
        ld      a,#45                   ; WRITE DATA
        ld      (sv_cmd),a
        call    sv_hdr_make
        call    sv_begin
        call    sv_hdr_io
        jr      nz,sv_stop
        call    sv_body
sv_stop:
        push    af
        call    fdc_off
        call    is_on                   ; οι λωρίδες ξαναγυρίζουν (src/isr.asm)
        call    hud_draw                ; ...και οι σειρές 0-2, που έσβησε το sv_begin
        pop     af                      ; Z αν A = 0 σε κάθε δρόμο ως εδώ
        ret

; ---------------------------------------------------------------------------
; svo_load — A = slot. Out: Z και A=0 αν πέτυχε· η οθόνη ξαναχτίζεται, και τον
; κέρσορα τον δείχνει το sv_load όταν γυρίσει (βήμα 103).
;
; Η ΚΕΦΑΛΙΔΑ ΕΛΕΓΧΕΤΑΙ ΠΡΙΝ γραφτεί οτιδήποτε πάνω στο παιχνίδι. Ενα άδειο
; slot είναι #E5 παντού, που δεν είναι έγκυρη κατάσταση αλλά είναι απολύτως
; έγκυρα bytes: χωρίς το μαγικό, ένα «φόρτωσε» σε άδειο slot θα γέμιζε τον
; κόσμο με σκουπίδια και θα κρεμούσε την προσομοίωση.
; ---------------------------------------------------------------------------
svo_load:
        ld      (sv_slot),a
        ld      a,#46                   ; READ DATA
        ld      (sv_cmd),a
        call    sv_begin
        call    sv_hdr_io
        jr      nz,sv_stop
        call    sv_hdr_ok
        jr      nz,sv_stop
        call    sv_body
        jr      nz,sv_stop
        call    fdc_off
        ; fall through: sv_after
; ---------------------------------------------------------------------------
; sv_after — ό,τι ΔΕΝ σώθηκε, ξαναφτιαγμένο.
;
; Η σειρά έχει σημασία: το NEXTHOP μηδενίζεται ΠΡΙΝ ξεκινήσει ο τροχός, γιατί
; ένας πράκτορας που διαβάζει παλιό «επόμενο κόμβο» δεν διαβάζει σκουπίδι —
; διαβάζει έγκυρο γείτονα ΑΛΛΟΥ κόσμου, και φεύγει προς τα εκεί.
; ---------------------------------------------------------------------------
sv_after:
        ld      a,(SV_HDR + 7)
        call    pal_planet              ; ο κόσμος που ήρθε μπορεί να είναι άλλος πλανήτης
        call    is_on                   ; ΜΕΤΑ την παλέτα: δύο out ανά pen (src/isr.asm)
        ; Η κάμερα μέσα στον κόσμο: μια θέση σωσμένη πριν από το βήμα 78 μπορεί
        ; να την έχει στο -65 ή και πέρα, και μια πλήρης σχεδίαση εκεί διαβάζει
        ; λάθος σειρές (DESIGN §15).
        ld      hl,(SV_HDR + 8)         ; L = cam_tx, H = cam_ty
        ld      a,l
        ld      b,CAM_XMAX + #80
        call    sv_cam
        ld      l,a
        ld      a,h
        ld      b,CAM_YMAX + #80
        call    sv_cam
        ld      h,a
        ld      (cam_tx),hl             ; cam_tx, cam_ty διπλανά (ui.asm)
        ld      hl,(SV_HDR + 10)
        ld      (cur_hx),hl             ; cur_hx, cur_hy διπλανά (ui.asm)
        ; Οι NODE_CAP στήλες κάθε γραμμής, όχι ολόκληρη η τράπεζα ως τις
        ; μηχανές (βήμα 155): στις στήλες NODE_CAP-127 είναι η κατεδάφιση
        ; (OV_R3, src/ov_inst.asm). Το ng_zero αφήνει το DE στο τέλος της
        ; στήλης NODE_CAP - 1, συν ένα.
        ld      bc,GA_PORT + PAGE_B5
        out     (c),c
        ld      hl,#4000
        ld      a,NODE_CAP
sva_nh:
        ld      bc,NODE_CAP - 1
        call    ng_zero
        ld      hl,128 - NODE_CAP
        add     hl,de                   ; η επόμενη γραμμή
        dec     a
        jr      nz,sva_nh
        call    dt_end
        call    wheel_load              ; και το σάρωμα των εργασιών (βήμα 115)
        call    rt_mark
        call    dirty_reset
        call    gh_reset
        xor     a
        ld      (ui_state),a
        ld      (ui_sel),a
        call    view_draw               ; κάνει και ob_touch και view_cam
        call    ui_hudall
        xor     a                       ; το ui_show στο sv_load (βήμα 103)
        ret

; sv_begin — μοτέρ, και η κεφαλή στον πρώτο track του slot.
sv_begin:
        ; Ο δίσκος κρατά τη μηχανή 35 frames με di: ό,τι ήχος έπαιζε θα έμενε
        ; να σφυρίζει όλη αυτή την ώρα, γιατί κανείς δεν προλαβαίνει να κάνει
        ; snd_tick (§9.5).
        call    snd_off
        ; ΚΑΙ ΤΩΡΑ ΚΛΕΙΝΟΥΝ ΣΤ' ΑΛΗΘΕΙΑ (βήμα 83). Ως τότε ήταν κλειστές σε όλο
        ; το παιχνίδι· τώρα τις χρειάζονται οι λωρίδες Mode 1 του HUD, και ο
        ; ελεγκτής δίνει ένα byte ανά 27 us ενώ η διακοπή κρατά ως 600. Οσο
        ; κρατά ο δίσκος η οθόνη μένει Mode 0 με τα χρώματα του κάδρου, και οι
        ; λωρίδες σβηστές — αλλιώς τα bytes τους φαίνονται ως θόρυβος Mode 0.
        call    hud_inval
        di
        call    is_flat
        call    fdc_on
        ld      a,(sv_slot)
        add     a,a                     ; x2
        ld      b,a
        add     a,a                     ; x4
        add     a,b                     ; x6
        add     a,SV_T0
        call    fdc_seek
        ld      a,#C1
        ld      (fd_sect),a
        ret

sv_hdr_io:
        ld      hl,SV_HDR
        ld      b,1
        ld      a,(sv_cmd)
        jp      fdc_stream

; ---------------------------------------------------------------------------
; sv_body — τα τρία μπλοκ, καθένα με τη δική του τράπεζα στο παράθυρο.
; ---------------------------------------------------------------------------
sv_body:
        ld      ix,sv_blocks
svb_lp:
        ld      a,(ix+0)
        cp      255
        jr      z,svb_done
        or      a
        jr      z,svb_nopage
        ld      c,a
        ld      b,GA_PORT/256
        out     (c),c
svb_nopage:
        ld      l,(ix+1)
        ld      h,(ix+2)
        ld      b,(ix+3)
        ld      a,(sv_cmd)
        call    fdc_stream              ; Z αν A = 0, και στο fst_bad (or a)
        call    dt_end                  ; η 1 (src/dirty.asm): A και F μένουν
        ret     nz
        ld      de,4
        add     ix,de
        jr      svb_lp
svb_done:
        xor     a
        ret

; τράπεζα · διεύθυνση · τομείς   (0 = χωρίς σελιδοποίηση)
sv_blocks:
        db      PAGE_B4
        dw      #4000
        db      32                      ; το επίπεδο κόσμου, 16 KB
        db      PAGE_B6
        dw      #6600
        db      13                      ; από το worldinfo ως το τέλος της τράπεζας
        db      PAGE_B5
        dw      G_corr_tbl
        db      1                       ; οι διάδρομοι (βήμα 154): 128 εγγραφές από
                                        ; το βήμα 159, ακριβώς ο τομέας (96 και μία
                                        ; άδεια ως τότε, και 124 bytes από πάνω τους
                                        ; χωρίς κατάσταση). Η άδεια μετά από αυτές
                                        ; δεν σώζεται: τη γράφει το game_new, και
                                        ; κανείς άλλος (cr_commit ως την 127).
        assert  G_worldinfo == #6600 && #6600 + 13 * 512 == #8000
        assert  MAX_CORR * CORR_REC <= 512
        db      0
        dw      SV_STATE
        db      SV_STATE_N              ; οικονομία, εργασίες, γράφος
        db      255

; ΤΟ ΜΠΛΟΚ ΤΗΣ ΚΑΤΑΣΤΑΣΗΣ ΒΓΑΙΝΕΙ ΑΠΟ ΤΗ ΔΙΑΤΑΞΗ, ΔΕΝ ΓΡΑΦΕΤΑΙ ΜΕ ΤΟ ΧΕΡΙ. Ως το
; βήμα 33 εδώ στεκόταν ένα `dw #A400`: σωστό όσο η αρένα της τράπεζας 2 δεν
; κουνιόταν. Το βήμα 33 την κατέβασε 1.792 bytes (η γραμματοσειρά έφυγε στην
; τράπεζα 7) και το econ_state βρέθηκε στο #9D7D — δηλαδή ΚΑΤΩ από το #A400. Ο
; δίσκος θα έσωζε κομμάτια του γράφου και του πίνακα εργασιών και ΚΑΘΟΛΟΥ
; αποθέματα, και το φόρτωμα θα «πετύχαινε».
;
; Το μπλοκ ΤΕΛΕΙΩΝΕΙ εκεί που αρχίζει η κρυφή μνήμη του HUD: από κάτω του είναι ο
; γράφος (node_adj), από πάνω μια κρυφή μνήμη που το φόρτωμα δεν πρέπει να
; γεμίσει με κωδικούς μιας άλλης οθόνης. Οι τομείς μετρούν προς τα ΠΙΣΩ, και ό,τι
; παραπάνω πιάνει στην αρχή είναι οι συνταγές — σταθερά δεδομένα του ίδιου build.
SV_STATE_N  equ 4
SV_STATE    equ G_hud_shadow - SV_STATE_N * 512
        assert  1 + 32 + 13 + 1 + SV_STATE_N <= SV_TRACKS * 9   ; 51 από 54
        assert  SV_STATE <= G_econ_state    ; η οικονομία ΟΛΗ μέσα στο μπλοκ

; ---------------------------------------------------------------------------
; sv_hdr_make / sv_hdr_ok — η κεφαλίδα.
; ---------------------------------------------------------------------------
sv_hdr_make:
        ld      hl,SV_HDR
        ld      bc,511
        call    ng_zero                 ; src/hw.asm
        ld      hl,sv_magic
        ld      de,SV_HDR
        ld      bc,5
        ldir
        call    ob_b6
        ld      hl,(G_worldinfo)
        ld      a,(G_worldinfo + 2)
        call    dt_end                  ; η 1· κρατά A, HL
        ld      (SV_HDR + 5),hl         ; seed
        ld      (SV_HDR + 7),a          ; πλανήτης
        ld      hl,(cam_tx)             ; και το cam_ty (βήμα 154: 12 bytes
        ld      (SV_HDR + 8),hl         ; για το μπλοκ των διαδρόμων)
        ld      hl,(cur_hx)             ; και το cur_hy
        ld      (SV_HDR + 10),hl
        ld      a,(sv_slot)
        ld      (SV_HDR + 12),a
        ret

sv_hdr_ok:
        ld      hl,SV_HDR
        ld      de,sv_magic
        ld      b,5
svo_lp:
        ld      a,(de)
        cp      (hl)
        jr      nz,svo_bad
        inc     hl
        inc     de
        djnz    svo_lp
        xor     a
        ret
svo_bad:
        or      #FF                     ; A = #FF, NZ
        ret

sv_magic:   db "HBT", SV_VER + '0', SV_VER

; sv_cam — A προσημασμένο -> στο [-64, B - #80]. Με το xor #80 η σειρά των
; προσημασμένων γίνεται σειρά ανυπόγραφων, και αρκούν δύο cp.
sv_cam:
        xor     #80
        cp      #40                     ; -64
        jr      nc,svc_hi
        ld      a,#40
svc_hi:
        cp      b
        jr      c,svc_ok
        ld      a,b
svc_ok:
        xor     #80
        ret

sv_slot:    db 0
sv_cmd:     db 0
