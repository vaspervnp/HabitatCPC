; install.asm — οι μηχανές κουβαλιούνται και στήνονται (βήμα 99, DESIGN §6.9).
;
; Ως το βήμα 98 μια μηχανή πληρωνόταν στο FIT και δούλευε αμέσως: το μόνο που
; έμενε από το «απλό» του βήματος 88. Οι αποφάσεις του παίκτη, όπως στο
; Planetbase:
;
;   - ΠΛΗΡΩΝΕΤΑΙ ΣΤΟ FIT, όπως τα εργοτάξια και ό,τι δίνεις στον έμπορο: τα
;     αποθέματα πέφτουν αμέσως, και τα φορτία κουβαλιούνται μετά.
;   - ΤΑ ΥΛΙΚΑ, ΜΕΤΑ Ο ΜΗΧΑΝΙΚΟΣ: μία Supply ανά υλικό (οποιοσδήποτε), και
;     όταν φτάσουν και τα δύο μια Build, που την παίρνει μόνο μηχανικός ή
;     ρομπότ κατασκευής, όπως το εργοτάξιο.
;   - ΦΑΙΝΕΤΑΙ ΑΜΕΣΩΣ, ΣΤΑΜΑΤΗΜΕΝΗ: η υποδοχή ζωγραφίζεται στο FIT και η
;     μηχανή δεν δουλεύει ως να στηθεί.
;   - ΤΑ ΦΥΤΑ ΜΕΝΟΥΝ ΑΜΕΣΑ (δύο μέταλλο το καθένα, src/fit.asm).
;
; ΤΑ ΧΡΕΗ ΣΤΗΝ ΥΓΕΙΑ ΤΗΣ ΜΗΧΑΝΗΣ, χωρίς νέο byte. Ως το 98 η υγεία ήταν μόνο
; 0 (σταματημένη) ή MACH_HP (200): η παραγωγή, ο χειριστής και η βλάβη
; κοιτάζουν πια μόνο το bit 7, και ό,τι είναι από κάτω είναι μια μηχανή που
; περιμένει:
;
;   0             χαλασμένη, μαραμένη, ή άδεια υποδοχή: θέλει Repair
;   MACH_OWED 7   καινούργια: χρωστά μέταλλο (bit 0) και βιοπλαστικό (bit 1)
;   4 + 32k       τα υλικά ήρθαν: τη στήνει μια Build, BUILD_STEP ανά επίσκεψη
;   MACH_HP 200   δουλεύει (bit 7)
;
; Κάθε μηχανή κοστίζει ως δέκα από το καθένα (fit_cost): ΕΝΑ φορτίο ανά
; υλικό, ένα bit. Το 4 είναι το MACH_READY, και τέσσερις επισκέψεις
; (4, 36, 68, 100) την ανεβάζουν πάνω από το 127, όπου γίνεται 200.
;
; Η ΙΔΙΑ SUPPLY ΓΙΑ ΤΟ ΕΡΓΟΤΑΞΙΟ ΚΑΙ ΤΙΣ ΜΗΧΑΝΕΣ ΤΟΥ: ένας θόλος έχει το πολύ
; μία ανά υλικό (το mc_order ψάχνει πριν δημοσιεύσει), και κάθε φορτίο πάει
; πρώτα στο εργοτάξιο αν το χρωστά, μετά στην πρώτη μηχανή που το χρωστά. Η
; εργασία ξανανοίγει όσο κάποιος από τους δύο το χρωστά ακόμη. Ενας θόλος σε
; λειτουργία δεν χρωστά τίποτα ο ίδιος: το D_POWER και το D_OPS του είναι
; πια ρεύμα και χειριστές (mc_live).
;
; Η BUILD ΤΗΣ ΜΗΧΑΝΗΣ: όταν μια μηχανή πάρει και τα δύο σε θόλο σε
; λειτουργία, μία Build στον κόμβο του αν δεν υπάρχει ήδη (sp_build, που
; μετρά και το EC_NBUILD για το NO ENGINEER). Σε εργοτάξιο καμία: όταν τελειώσει
; το κτίριο, ο ίδιος χτίστης συνεχίζει στις μηχανές του (ja_build,
; src/jobs.asm). Η Build στήνει την πρώτη έτοιμη υποδοχή, μένει όσο υπάρχει
; κάποια, και τελειώνει στην επίσκεψη που δεν βρίσκει καμία.
;
; ΑΝ Η ΜΗΧΑΝΗ ΒΓΕΙ ΠΡΙΝ ΦΤΑΣΟΥΝ ΤΑ ΥΛΙΚΑ, τα φορτία που έρχονται δεν βρίσκουν
; ποιον να πάνε και η εργασία τελειώνει: πληρώθηκαν στο FIT, και τα μισά
; γύρισαν όταν βγήκε, όπως για κάθε μηχανή.

; ---------------------------------------------------------------------------
; mc_arrive — A = ο κόμβος, (sp_mat) = το υλικό: το φορτίο πάει στην πρώτη
; μηχανή που το χρωστά. Αν εκείνη δεν χρωστά πια τίποτα και ο θόλος δουλεύει,
; μία Build για να στηθεί.
; mc_tail   — το ίδιο χωρίς φορτίο: το παρέδωσε ήδη (στο εργοτάξιο).
; Out, η σύμβαση του sp_arrive: NZ CY  κάποια μηχανή το χρωστά ακόμη
;                               NZ NC  καμία: η εργασία τελειώνει
; ---------------------------------------------------------------------------
mc_tail:
        ld      d,1                     ; χωρίς φορτίο
        jr      mca_go
mc_arrive:
        ld      d,0
mca_go:
        cp      MAX_DOME
        jr      nc,mca_done             ; δομή: δεν έχει μηχανές
        ld      c,a
        push    de
        call    mc_rec                  ; IX -> υποδοχή 0, B, HL -> D_STATE
        pop     de
        ld      a,(sp_mat)
        inc     a
        ld      e,a                     ; το bit του: 1 μέταλλο, 2 βιοπλαστικό
mca_lp:
        ld      a,(ix+D_HEALTH-D_MACH)
        and     e
        jr      nz,mca_got
mca_n:
        inc     ix
        djnz    mca_lp
mca_done:
        xor     a
        inc     a                       ; NZ, NC
        ret
mca_got:
        dec     d
        jr      z,mca_more              ; παραδόθηκε ήδη: κι άλλο ταξίδι
        ld      d,1                     ; παραδίδεται εδώ, και ψάχνει άλλη
        ld      a,(ix+D_HEALTH-D_MACH)
        xor     e
        ld      (ix+D_HEALTH-D_MACH),a
        cp      MACH_READY
        jr      nz,mca_n                ; χρωστά και το άλλο
        bit     1,(hl)                  ; DS_ACTIVE; εργοτάξιο: το ja_build
        jr      z,mca_n
        ; Σπάνια, μία φορά ανά μηχανή: το sp_find παίρνει τον IX και το B,
        ; και το mc_tail ξαναψάχνει από την αρχή — οι πρώτες δεν το χρωστούν.
        ld      a,c
        ld      c,J_BUILD
        call    sp_find                 ; κρατά το A
        call    nz,sp_build
        jr      mc_tail
mca_more:
        scf
        sbc     a,a                     ; A = #FF: NZ, CY
        ret

        assert  DS_ACTIVE == 2 && DS_BUILDING == 1 && DS_EMPTY == 0
        assert  J_SUPPLY == 7 && MACH_OWED == MACH_READY + 3
        assert  (MACH_HP & 128) && !(MACH_HP & 3) && MACH_READY < 128 && !(BUILD_STEP & 3)
