; b6out.asm — ό,τι χρειάζεται ο κώδικας του τροχού στην τράπεζα 6 (b6code) με
; ΑΛΛΗ τράπεζα στο παράθυρο (βήμα 110, DESIGN §8.4).
;
; Από το βήμα 110 οι ανάγκες (src/needs.asm) και οι μετεωρίτες (src/meteor.asm)
; ζουν στο b6code, στο &4000-&7FFF μαζί με την τράπεζα 6. Ως τότε ήταν στις
; τράπεζες 0 και 2, που φαίνονται πάντα, και δύο κομμάτια τους σελιδοποιούσαν
; άλλη τράπεζα: την 1 για το DIST, την 4 για τον κόσμο. Από το παράθυρο, η
; επόμενη εντολή θα ερχόταν από εκεί. Η πρώτη σουίτα του βήματος 110 το έδειξε:
; το test_needs έβρισκε το PC στο &DAF6. Εδώ, σε τράπεζα που φαίνεται πάντα, και
; γυρίζουν πάντα με την 6 μέσα: στη 2 ως το βήμα 151, στην 0 από το 152, για να
; μείνει στη 2 χώρος για τις αποστάσεις των 48 κτισμάτων.

; ---------------------------------------------------------------------------
; nd_nearest — A = είδος δωματίου, D = κόμβος. A = θόλος ή 255.
;
; Η τράπεζα 1 μπαίνει μία φορά για ως οκτώ υποψηφίους, όχι μία ανά υποψήφιο.
;
; ΔΥΟ ΒΡΟΧΟΙ ΑΠΟ ΤΟ ΒΗΜΑ 153. Από θόλο, η γραμμή του: το H μένει σε όλον τον
; βρόχο, και το κάτω byte της (0 ή 128) είναι το immediate ενός add — ως τότε
; push/pop του HL γύρω από κάθε ανάγνωση, 20 T περισσότερα ανά υποψήφιο. Από
; δομή, η στήλη της (το DIST με συμμετρία, rt_flush στο src/graph.asm): η
; γραμμή του υποψηφίου, #40 + t/2 και (t & 1) * 128 + κόμβος, με δύο rra — 1 T
; λιγότερο από τον παλιό βρόχο. Το B περνά το out μέσα από το A, όχι με
; push/pop: 13 T λιγότερα ανά κλήση, που πληρώνουν το διάλεγμα του βρόχου.
; ---------------------------------------------------------------------------
nd_nearest:
        ld      c,a
        add     a,G_room_n & 255
        ld      l,a
        ld      h,G_room_n >> 8
        ld      b,(hl)
        ld      a,255
        ld      (nd_best),a
        inc     b
        dec     b
        ret     z                       ; δεν υπάρχει κανένα τέτοιο δωμάτιο

        ld      l,d                     ; ο κόμβος
        ; DE = η λίστα υποψηφίων, σε μία σελίδα (το assert του src/needs.asm)
        ld      a,c
        add     a,a
        add     a,a
        add     a,a
        add     a,G_room_list & 255
        ld      e,a
        ld      d,G_room_list >> 8
        ld      a,b
        ld      bc,GA_PORT + PAGE_B1
        out     (c),c
        ld      b,a
        ld      c,255                   ; η καλύτερη απόσταση ως τώρα
        ld      a,l
        cp      MAX_DOME
        jr      nc,nds_go
        add     a,#80
        rra
        ld      h,a                     ; #40 + κόμβος/2: η γραμμή του
        sbc     a,a
        and     #80
        ld      (ndn_lo + 1),a          ; (κόμβος & 1) * 128
ndn_lp:
        ld      a,(de)                  ; υποψήφιος θόλος
        inc     e
ndn_lo: add     a,0                     ; ο θόλος είναι < 64: δεν κρατάει
        ld      l,a
        ld      a,(hl)                  ; απόσταση
        cp      c
        jr      nc,ndn_n
        ld      c,a
        dec     e
        ld      a,(de)
        inc     e
        ld      (nd_best),a
ndn_n:
        djnz    ndn_lp
ndn_out:
        ld      bc,GA_PORT + PAGE_B6
        out     (c),c
        ld      a,(nd_best)
        ret

nds_go:
        add     a,a
        ld      (nds_2s + 1),a          ; 2 x κόμβος: το rra βάζει μπροστά το t & 1
nds_lp:
        ld      a,(de)                  ; υποψήφιος θόλος t
        inc     e
        add     a,#80
        rra
        ld      h,a                     ; #40 + t/2, CY = t & 1
nds_2s: ld      a,0
        rra
        ld      l,a                     ; (t & 1) * 128 + κόμβος
        ld      a,(hl)                  ; DIST[t][κόμβος] = DIST[κόμβος][t]
        cp      c
        jr      nc,nds_n
        ld      c,a
        dec     e
        ld      a,(de)
        inc     e
        ld      (nd_best),a
nds_n:
        djnz    nds_lp
        jr      ndn_out

        assert  MAX_NODE <= 128                 ; 2 x κόμβος σε byte

; ---------------------------------------------------------------------------
; mt_crater — HL = ένα tile του κόσμου (τράπεζα 4), από το mt_ground: γίνεται
; κρατήρας αν είναι ελεύθερο έδαφος, σκόνη, βράχος ή θεμέλιο. Z αν ο χάρτης
; άλλαξε. Κρατά το BC· γυρίζει με την 6.
; ---------------------------------------------------------------------------
mt_crater:
        push    bc
        ld      bc,GA_PORT + PAGE_B4
        out     (c),c
        ld      a,(hl)
        and     W_OCC_MASK | 7          ; κατοχή και έδαφος
        cp      W_MOUNTAIN
        jr      c,mcr_yes               ; ελεύθερο έδαφος, σκόνη, βράχος
        cp      W_FOUNDATION
        jr      nz,mcr_back             ; διάδρομος, βουνό, νερό, ήδη κρατήρας
mcr_yes:
        ld      a,(hl)
        and     #C0                     ; το decor μένει
        or      W_CRATER
        ld      (hl),a
        xor     a                       ; Z: ο χάρτης άλλαξε
mcr_back:
        ld      bc,GA_PORT + PAGE_B6
        out     (c),c
        pop     bc
        ret

nd_best:    db 0
