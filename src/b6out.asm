; b6out.asm — ό,τι χρειάζεται ο κώδικας του τροχού στην τράπεζα 6 (b6code) με
; ΑΛΛΗ τράπεζα στο παράθυρο (βήμα 110, DESIGN §8.4).
;
; Από το βήμα 110 οι ανάγκες (src/needs.asm) και οι μετεωρίτες (src/meteor.asm)
; ζουν στο b6code, στο &4000-&7FFF μαζί με την τράπεζα 6. Ως τότε ήταν στις
; τράπεζες 0 και 2, που φαίνονται πάντα, και δύο κομμάτια τους σελιδοποιούσαν
; άλλη τράπεζα: την 1 για το DIST, την 4 για τον κόσμο. Από το παράθυρο, η
; επόμενη εντολή θα ερχόταν από εκεί. Η πρώτη σουίτα του βήματος 110 το έδειξε:
; το test_needs έβρισκε το PC στο &DAF6. Εδώ, στην τράπεζα 2, και γυρίζουν πάντα
; με την 6 μέσα.

; ---------------------------------------------------------------------------
; nd_nearest — A = είδος δωματίου, D = κόμβος. A = θόλος ή 255.
;
; Η τράπεζα 1 μπαίνει μία φορά για ως οκτώ υποψηφίους, όχι μία ανά υποψήφιο.
; ---------------------------------------------------------------------------
nd_nearest:
        ld      c,a
        add     a,G_room_n & 255
        ld      l,a
        ld      h,G_room_n >> 8
        ld      b,(hl)
        ld      a,255
        ld      (nd_best),a
        inc     b
        dec     b
        ret     z                       ; δεν υπάρχει κανένα τέτοιο δωμάτιο

        ; Η ΓΡΑΜΜΗ ΤΟΥ DIST ΥΠΟΛΟΓΙΖΕΤΑΙ ΜΙΑ ΦΟΡΑ. Ηταν μέσα στον βρόχο, και
        ; ο πολλαπλασιασμός x128 ανά υποψήφιο ήταν το μισό κόστος της
        ; αναζήτησης — που τρέχει για κάθε άποικο που του λείπει κάτι.
        ld      h,d
        ld      l,0
        srl     h
        rr      l
        set     6,h                     ; το DIST κάθεται στο &4000
        ; DE = η λίστα υποψηφίων
        ld      a,c
        add     a,a
        add     a,a
        add     a,a
        add     a,G_room_list & 255
        ld      e,a
        ld      d,G_room_list >> 8

        push    bc
        ld      bc,GA_PORT + PAGE_B1
        out     (c),c
        pop     bc
        ld      c,255                   ; η καλύτερη απόσταση ως τώρα
ndn_lp:
        ld      a,(de)                  ; υποψήφιος θόλος
        inc     de
        push    hl
        add     a,l                     ; ο θόλος είναι < 64: δεν κρατάει
        ld      l,a
        ld      a,(hl)                  ; απόσταση
        pop     hl
        cp      c
        jr      nc,ndn_n
        ld      c,a
        dec     de
        ld      a,(de)
        inc     de
        ld      (nd_best),a
ndn_n:
        djnz    ndn_lp

        ld      bc,GA_PORT + PAGE_B6
        out     (c),c
        ld      a,(nd_best)
        ret

; ---------------------------------------------------------------------------
; mt_crater — HL = ένα tile του κόσμου (τράπεζα 4), από το mt_ground: γίνεται
; κρατήρας αν είναι ελεύθερο έδαφος, σκόνη, βράχος ή θεμέλιο. Z αν ο χάρτης
; άλλαξε. Κρατά το BC· γυρίζει με την 6.
; ---------------------------------------------------------------------------
mt_crater:
        push    bc
        ld      bc,GA_PORT + PAGE_B4
        out     (c),c
        ld      a,(hl)
        and     W_OCC_MASK | 7          ; κατοχή και έδαφος
        cp      W_MOUNTAIN
        jr      c,mcr_yes               ; ελεύθερο έδαφος, σκόνη, βράχος
        cp      W_FOUNDATION
        jr      nz,mcr_back             ; διάδρομος, βουνό, νερό, ήδη κρατήρας
mcr_yes:
        ld      a,(hl)
        and     #C0                     ; το decor μένει
        or      W_CRATER
        ld      (hl),a
        xor     a                       ; Z: ο χάρτης άλλαξε
mcr_back:
        ld      bc,GA_PORT + PAGE_B6
        out     (c),c
        pop     bc
        ret

nd_best:    db 0
