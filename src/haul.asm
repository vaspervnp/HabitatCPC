; haul.asm — η μεταφορά (βήμα 95, DESIGN §6.7): το μετάλλευμα κουβαλιέται.
;
; Ως το βήμα 94 ο κύκλος ροής έβαζε το μετάλλευμα κάθε ορυχείου κατευθείαν στα
; αποθέματα, και η εργασία Haul υπήρχε μόνο στους πίνακες (job_roles #41:
; εργάτης και ρομπότ μεταφοράς). Οι αποφάσεις του παίκτη, όπως στο Planetbase:
;
;   - Ο ΣΩΡΟΣ. Ο,τι σκάβεται μένει στο ορυχείο, στο όγδοο byte της εγγραφής
;     (ST_OWED: ένα εργοτάξιο χρωστά εκεί υλικά, ένα έτοιμο ορυχείο δεν το
;     χρειαζόταν). Ως HAUL_CAP = 30, τρία φορτία· γεμάτος, το ορυχείο δεν
;     βγάζει τίποτα όσο κι αν σκάβουν, ως να κουβαλήσει κάποιος.
;   - ΤΟ ΦΟΡΤΙΟ. HAUL_LOAD = 10, όσο της τροφοδοσίας (src/supply.asm). Με
;     σωρό από 10 και πάνω δημοσιεύεται μία Haul για το ορυχείο, και το bit 6
;     του ST_OPS λέει ότι υπάρχει (το bit 7 είναι της Drill, τα κάτω δύο όσοι
;     σκάβουν — src/drill.asm).
;   - Ο ΠΡΟΟΡΙΣΜΟΣ. Η κοντινότερη αποθήκη σε λειτουργία, αλλιώς το σκάφος: οι
;     πηγές της τροφοδοσίας, που τις διαλέγει το ίδιο sp_take. Χωρίς καμία που
;     να φτάνεται, το φορτίο παραδίδεται εκεί που φορτώθηκε.
;
; ΔΥΟ ΣΚΕΛΗ, όπως η Supply αλλά ανάποδα: η εργασία ξεκινά στο ορυχείο (J_NODE
; = J_SITE = ο κόμβος του), και στο ορυχείο γίνεται J_NODE = ο προορισμός. Το
; J_SITE μένει το ορυχείο: έτσι η άφιξη ξέρει σε ποιο σκέλος είναι, και ένα
; φορτίο που κάποιος άφησε στη μέση το παραδίδει ο επόμενος (jb_reap, src/
; jobs.asm, που για τη Haul δεν γυρίζει το J_NODE πίσω).
;
; ΣΤΗΝ ΤΡΑΠΕΖΑ 0, που φαίνεται πάντα: το hl_pile το καλεί το σάρωμα της θέσης
; 12 από το b6code (src/flow.asm), το hl_arrive η θέση 13. Χώρεσε επειδή το
; πάτωμα των δοκιμών ανέβηκε από το #3D60 στο #3E00 (src/main.asm). Η
; δημοσίευση (st_post) είναι στην τράπεζα 2, με το dr_post που πέφτει μέσα της
; (src/drill.asm).

HAUL_LOAD   equ 10
HAUL_CAP    equ 30
ST_HAUL     equ 6                       ; το bit του ST_OPS: η Haul υπάρχει

        assert  ST_OPS == 6 && ST_OWED == 7 && STRUCT_REC == 8
        assert  (G_struct_tbl & 255) == 0 && MAX_STRUCT * STRUCT_REC == 256
        assert  HAUL_CAP + 4 < 128 && HAUL_LOAD <= HAUL_CAP
        assert  J_NODE == 1 && J_AGENT == 2 && J_SITE == 4

; ---------------------------------------------------------------------------
; hl_pile — από το σάρωμα του κύκλου ροής (src/flow.asm), για κάθε έτοιμο
; ορυχείο, μετά το dr_post: IX -> η εγγραφή. Με όλο το ρεύμα (P_ALL) και
; κάποιον που σκάβει, ο σωρός παίρνει όσα έβγαζε ως το 94 το ορυχείο στα
; αποθέματα — ένας 2, δύο 3, τρεις 4 — ως το HAUL_CAP. Και με ή χωρίς, ένας
; σωρός από HAUL_LOAD και πάνω χωρίς Haul παίρνει μία.
;
; ΤΟ ΡΕΥΜΑ ΤΟΥ ΤΕΛΕΥΤΑΙΟΥ ΙΣΟΖΥΓΙΟΥ, όχι αυτού που μετρά το σάρωμα: όπως οι
; μηχανές και οι κήποι της θέσης 11 (src/econ.asm), που διαβάζουν το ίδιο
; EC_POK. Η πρώτη εκδοχή περίμενε το ισοζύγιο του ίδιου κύκλου, όπως το
; μετάλλευμα ως το 94, και ξανάψαχνε μετά τον πίνακα των δομών για τα
; ορυχεία: 13 us για κάθε θέση ως το τελευταίο, ~400 με ένα ορυχείο στη θέση
; 31. Εδώ μόνο όσα ορυχεία υπάρχουν, ~55 us το καθένα.
; Χαλάει A, BC, DE, HL· κρατά τον IX.
; ---------------------------------------------------------------------------
hl_pile:
        ld      a,(EC_POK)
        cp      P_ALL
        jr      nz,hlp_pile             ; χωρίς ρεύμα δεν σκάβεται τίποτα
        ld      a,(ec_full)
        or      a
        jr      nz,hlp_pile             ; ούτε με γεμάτη αποθήκη (βήμα 122)
        ld      a,(ix+ST_OPS)
        and     MINE_OPS
        jr      z,hlp_pile              ; κανείς δεν σκάβει
        inc     a                       ; 2, 3, 4: MINE_OUT + όσοι - 1
        bit     ST_HALF,(ix+ST_OPS)     ; εκτός φλέβας (βήμα 123): τα μισά,
        jr      z,hlp_add               ; προς τα πάνω — 1, 2, 2
        inc     a
        srl     a
hlp_add:
        add     a,(ix+ST_OWED)
        cp      HAUL_CAP + 1
        jr      c,hlp_st
        ld      a,HAUL_CAP              ; γεμάτος: ό,τι περισσεύει χάνεται
hlp_st:
        ld      (ix+ST_OWED),a
        jr      hlp_chk
hlp_pile:
        ld      a,(ix+ST_OWED)
hlp_chk:
        cp      HAUL_LOAD
        ret     c
        bit     ST_HAUL,(ix+ST_OPS)
        ret     nz                      ; υπάρχει ήδη
        ld      a,J_HAUL
        ld      c,1 << ST_HAUL
        jp      st_post                 ; src/drill.asm

; ---------------------------------------------------------------------------
; hl_arrive — από το jb_arrive (src/jobs.asm): ο πράκτορας (jb_ag) μιας Haul
; στέκεται στο J_NODE της, C. HL -> η εργασία. Η 6 στο παράθυρο.
; Out: Z   φόρτωσε στο ορυχείο και πάει στον προορισμό: η εργασία μένει δική του
;      NZ  παρέδωσε, ή δεν βρήκε φορτίο: η εργασία τελείωσε
; ---------------------------------------------------------------------------
hl_arrive:
        inc     hl
        inc     hl
        inc     hl
        inc     hl                      ; J_SITE: το ορυχείο
        ld      a,(hl)
        cp      c
        jr      nz,hla_drop             ; στον προορισμό: παραδίδει
        ; --- στο ορυχείο: η Haul του φεύγει, και ένα φορτίο από τον σωρό ---
        sub     MAX_DOME
        add     a,a
        add     a,a
        add     a,a                     ; x STRUCT_REC: το 512 φεύγει από το byte
        add     a,ST_OPS
        ld      e,a
        ld      d,G_struct_tbl >> 8
        ex      de,hl                   ; HL -> ST_OPS, DE -> J_SITE
        res     ST_HAUL,(hl)
        inc     hl                      ; ST_OWED: ο σωρός
        ld      a,(hl)
        sub     HAUL_LOAD
        jr      c,hla_none              ; κάτω από φορτίο: τίποτα να πάρει
        ld      (hl),a
        ; Ο ΠΡΟΟΡΙΣΜΟΣ ΤΟΝ ΔΙΑΛΕΓΕΙ ΤΟ sp_take (src/supply.asm), όπως την πηγή
        ; μιας Supply: η κοντινότερη σε αυτόν — που στέκεται στο ορυχείο —
        ; αποθήκη ή το σκάφος. Γράφει J_NODE και dest, μηδενίζει το spare, και
        ; γυρίζει με το HL στο J_NODE.
        ex      de,hl
        dec     hl
        dec     hl                      ; J_AGENT
        ld      a,(jb_ag)
        ld      e,a
        call    sp_take
        ld      a,(hl)                  ; J_NODE
        inc     hl
        inc     hl
        inc     hl
        cp      (hl)                    ; ακόμη το ορυχείο: καμία πηγή δεν φτάνεται
        jr      z,hla_drop              ; το φορτίο παραδίδεται εδώ
        ld      a,S_ORE
        call    hla_sp                  ; spare: κουβαλά μετάλλευμα
        xor     a                       ; Z
        ret
hla_none:
        or      1                       ; NZ: ως το 94 δεν γινόταν (μία Haul ανά σωρό)
        ret
hla_drop:
        xor     a
        call    hla_sp                  ; spare = 0
        ld      a,S_ORE
        ld      de,HAUL_LOAD
        call    ec_make                 ; src/stock.asm: φτιάχτηκε εδώ, και στα αποθέματα
        or      1                       ; NZ
        ret
; hla_sp — A -> το spare του (jb_ag): το απόθεμα που κουβαλά, ή 0.
hla_sp:
        ld      hl,jb_ag
        ld      l,(hl)
        set     7,l
        ld      h,AG_PG + 7
        ld      (hl),a
        ret
