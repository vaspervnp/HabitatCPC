; Οι σταθερές του (TU_N, TU_YOURS, TU_STRUCT ...) στο src/tutor2.asm από το
; βήμα 201: εκείνο συναρμολογείται πρώτο, στην αρχή της εικόνας (src/main.asm).
        assert  SK_COLONIST == 0 && EC_SHKIND == EC_SHSTATE + 1
        assert  ST_STATE == ST_KIND + 2 && DS_EMPTY == 0     ; και M_OXYGEN == 0 (src/newgame.asm)
        assert  (G_struct_tbl & 7) == 0 && STRUCT_REC == 8

; tuo_go — από το tu_run, με την 1 στο παράθυρο. Γυρίζει με την 1.
;
; ΠΡΩΤΑ ΤΟ ΔΕΥΤΕΡΟ ΜΕΡΟΣ (βήμα 201, src/tutor2.asm): από τις στήλες 48-63
; των γραμμών 32-47 του μπλοκ των δομών (TB_HOLE), μετά τις γραμμές του
; κειμένου, στο GH_BUF + TU_ALEN. Το tu_run φέρνει από το OV_R1 μόνο αυτό το
; μέρος, ως το tuo_i· το OV_R1 κερδίζει 141 bytes για την κορδέλα του
; εργοταξίου (βήμα 202), και άλλα 57 με την ανάγνωση της γραμμής (tuo_line).
tuo_go:
        ld      hl,TB_HOLE
        ld      de,GH_BUF + TU_ALEN
        ld      a,TB_ROWS
tuo_ld:
        ld      bc,OV_UNIT
        ldir
        ld      c,DB_STRIDE - OV_UNIT   ; το B είναι 0 μετά το ldir
        add     hl,bc
        dec     a
        jr      nz,tuo_ld
        call    ob_b6                   ; θόλοι, δομές, EC_TU, worldinfo
        ld      a,(EC_TU)
        ld      (tuo_o),a               ; για τη σελίδα, στο τέλος (βήμα 175)
        cp      TU_YOURS
        jr      nz,tuo_new
        inc     a                       ; το μήνυμα κράτησε ως αυτό το γεγονός
tuo_new:
        or      a
        jr      nz,tuo_lp
        ld      a,(G_worldinfo + 3)
        add     a,a                     ; bit 7: κόσμος του tutorial
        ld      a,0
        adc     a,a                     ; 1, το πρώτο βήμα· 0, κανένα tutorial
        jr      z,tuo_set
tuo_lp:
        ld      (tuo_s),a
        cp      TU_YOURS
        jr      nc,tuo_set
        call    tuo_done                ; CY: το βήμα A έγινε
        ld      a,(tuo_s)
        jr      nc,tuo_set
        inc     a
        jr      tuo_lp
tuo_set:
        ld      (EC_TU),a
        ld      (tuo_s),a
        ; --- η γραμμή: 0-13 τα βήματα και το μήνυμα, 14 η γραμμή που ήταν ---
        dec     a
        cp      TU_YOURS
        jr      c,tuo_txt
        ld      a,TU_YOURS
tuo_txt:
        call    tuo_line                ; src/tutor2.asm (βήμα 202)
        ld      a,(tuo_s)
        ld      (tp_cur),a              ; η σελίδα του «?» (src/tpage.asm, βήμα 175)
        ; --- οι βλάβες σβηστές στα βήματα (or αντί για and στο ev_fault) ---
        ld      a,(tuo_s)
        dec     a
        cp      TU_N
        ld      a,#E6                   ; and n
        jr      nc,tuo_flt
        ld      a,#F6                   ; or n: ποτέ μηδέν, καμία βλάβη
tuo_flt:
        ld      (ev_fmask),a
        ; --- και τα γεγονότα το φέρνουν στα βήματα και στο μήνυμα ---
        ld      a,(tuo_s)
        dec     a
        cp      TU_YOURS
        ld      a,#C9                   ; ret
        jr      nc,tuo_ev
        xor     a                       ; nop
tuo_ev:
        ld      (tu_ev),a
        ld      bc,GA_PORT + PAGE_B1
        out     (c),c
        ; --- ΚΑΙ Η ΣΕΛΙΔΑ ΤΟΥ ΝΕΟΥ ΒΗΜΑΤΟΣ (βήμα 175, src/tpage.asm) ---
        ; Μόνο όταν το βήμα άλλαξε, από το 2 ως το μήνυμα του τέλους: το 1 το
        ; δείχνει το tu_open μαζί με την εισαγωγή, και στο 16 δεν μένει τίποτα.
        ; Μετά από ένα φόρτωμα το βήμα είναι αυτό που σώθηκε, και καμία.
        ld      a,(tuo_o)
        ld      b,a
        ld      a,(tuo_s)
        cp      b
        ret     z
        cp      2
        ret     c
        cp      TU_YOURS + 1
        ret     nc
        jp      tu_page                 ; src/help.asm. ΟΧΙ call: ο τομέας της
                                        ; σελίδας γράφεται εδώ, στο GH_BUF

tuo_s:      db 0                        ; το βήμα
tuo_o:      db 0                        ; το βήμα πριν από αυτό το γεγονός
tuo_i:      db 0                        ; η γραμμή του κειμένου
