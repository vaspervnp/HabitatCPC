; ghost.asm — ό,τι ζωγραφίζεται ΠΑΝΩ από τη σκηνή και πρέπει να φύγει καθαρά.
;
; Ο κέρσορας και το φάντασμα του §9.3 κινούνται με κάθε πάτημα. Το να
; ξαναζωγραφίζεται η περιοχή από κάτω κοστίζει 3 ως 9 frames ([§8.2]) — δηλαδή
; ο κέρσορας θα κουνιόταν πέντε φορές το δευτερόλεπτο. Αντ' αυτού κρατάμε
; ΑΡΧΕΙΟ ΑΝΑΙΡΕΣΗΣ: κάθε ορθογώνιο που γράφεται σώζει πρώτα ό,τι έσβησε.
;
; Μία εγγραφή: διεύθυνση οθόνης (2), πλάτος w, ύψος h, και w*h bytes, γραμμή
; προς γραμμή. Τα ορθογώνια δεν επικαλύπτονται ποτέ μεταξύ τους — γι' αυτό οι
; κάθετες πλευρές του πλαισίου ξεκινούν κάτω από την πάνω και σταματούν πάνω
; από την κάτω. Αν επικαλύπτονταν, το δεύτερο θα έσωζε ό,τι είχε ήδη γράψει το
; πρώτο και η αναίρεση θα άφηνε το φάντασμα καρφωμένο στην οθόνη.

; το GH_LOG και το GH_BUF είναι στο const.asm

; ---------------------------------------------------------------------------
; gh_reset — άδειο αρχείο.
; ---------------------------------------------------------------------------
gh_reset:
        ld      hl,GH_BUF
        ld      (gh_ptr),hl
        ld      hl,#00FF                ; x0 = 255, x1 = 0: άδειο περίγραμμα
        ld      (gh_bbx),hl
        ld      (gh_bby),hl
        ret

; ---------------------------------------------------------------------------
; gh_wrap — μετά από `inc de` που γύρισε το E στο 0: μέσα στο δαχτυλίδι των 2 KB.
;
; Το ph αυξήθηκε, και αν έγινε 0 σημαίνει ότι ήταν 7 και μπήκε στο πεδίο της
; γραμμής — οπότε πίσω οκτώ, στην αρχή του ΙΔΙΟΥ δαχτυλιδιού.
; ---------------------------------------------------------------------------
gh_wrap:
        ld      a,d
        and     7
        ret     nz
        ld      a,d
        sub     8
        ld      d,a
        ret

; ---------------------------------------------------------------------------
; gh_rect — ορθογώνιο w x h, κομμένο στο κάδρο. Σώζει και γράφει.
; In: (gh_x), (gh_y) 16-bit προσημασμένα, (gh_n) = w bytes, (gh_nv) = h
;     γραμμές, (gh_pen). Δεν τα αλλάζει: ο gh_box τα ξαναχρησιμοποιεί.
;
; ΕΝΑ ΟΡΘΟΓΩΝΙΟ, ΟΧΙ h ΛΩΡΙΔΕΣ. Ως το βήμα 35 η μονάδα ήταν η οριζόντια λωρίδα,
; και κάθε πλευρά του πλαισίου ενός θόλου L ήταν 124 λωρίδες του ενός byte —
; με δύο clip, έναν υπολογισμό διεύθυνσης και τρία bytes κεφαλίδας η καθεμιά.
; Το πράσινο φάντασμα του L κόστιζε 131 ms και το κόκκινο 263· και το κόκκινο
; δεν χωρούσε καν στο αρχείο (2.412 bytes στα 1.600), οπότε έλειπαν οι πέντε
; από τις οκτώ σειρές σημαδιών. Εδώ το clip και η διεύθυνση γίνονται μία φορά
; και οι γραμμές ακολουθούν με scr_nextline.
; ---------------------------------------------------------------------------
gh_rect:
        ld      hl,(gh_y)
        ld      (cl_pos),hl
        ld      a,(gh_nv)
        ld      (cl_len),a
        ld      hl,(clip_y0)
        ld      (cl_lo),hl
        call    ob_clip
        or      a
        ret     z
        ld      a,(cl_start)
        ld      (gh_ys),a
        ld      a,(cl_n)
        ld      (gh_hs),a
        ld      hl,(gh_x)
        ld      (cl_pos),hl
        ld      a,(gh_n)
        ld      (cl_len),a
        ld      hl,(clip_x0)
        ld      (cl_lo),hl
        call    ob_clip
        or      a
        ret     z
        ; --- από εδώ: ορθογώνιο ΜΕΣΑ στο κάδρο, (cl_start, gh_ys) πάνω-αριστερά,
        ; cl_n x gh_hs. Εδώ μπαίνει και το gh_mark, που δεν χρειάζεται clip.
ghr_put:
        ; --- χωράει; κεφαλίδα 4 + w*h. Γεμάτο αρχείο: μη γράφεις ό,τι δεν
        ; μπορείς να πάρεις πίσω. Επαναλήψεις όσο το ΠΛΑΤΟΣ: οι πλευρές του
        ; πλαισίου είναι 1 x 124, και ανάποδα ήταν 124 γύροι για ένα γινόμενο. ---
        ld      a,(gh_hs)
        ld      e,a
        ld      d,0
        ld      hl,4
        ld      a,(cl_n)
        ld      b,a
ghr_mul:
        add     hl,de
        djnz    ghr_mul
        ld      de,(gh_ptr)
        add     hl,de
        ld      de,GH_BUF + GH_LOG + 1
        or      a
        sbc     hl,de
        ret     nc
        ; ΤΟ ΠΕΡΙΓΡΑΜΜΑ ΤΟΥ ΑΡΧΕΙΟΥ. Η λίστα αλλαγών (§8.5) ζωγραφίζει κάτω από
        ; το φάντασμα χωρίς να το ξέρει, και η αναίρεση ύστερα γράφει πίσω bytes
        ; που δεν είναι πια στην οθόνη. Το dt_ghost το ρωτά ΑΥΤΟ: όχι το κουτί
        ; του κέρσορα, γιατί στη σύνδεση διαδρόμου τα σημάδια βγαίνουν έξω του.
        ld      hl,gh_bbx
        ld      a,(cl_start)
        cp      (hl)
        jr      nc,ghb_x0
        ld      (hl),a
ghb_x0:
        inc     hl
        ld      b,a
        ld      a,(cl_n)
        add     a,b                     ; το τέλος, αποκλειστικό
        cp      (hl)
        jr      c,ghb_x1
        ld      (hl),a
ghb_x1:
        inc     hl
        ld      a,(gh_ys)
        cp      (hl)
        jr      nc,ghb_y0
        ld      (hl),a
ghb_y0:
        inc     hl
        ld      b,a
        ld      a,(gh_hs)
        add     a,b
        cp      (hl)
        jr      c,ghb_y1
        ld      (hl),a
ghb_y1:
        ld      a,(cl_start)
        ld      c,a
        ld      a,(gh_ys)
        call    scr_addr
        ld      hl,(gh_ptr)
        ld      (hl),e
        inc     hl
        ld      (hl),d
        inc     hl
        ld      a,(cl_n)
        ld      (hl),a
        inc     hl
        ld      a,(gh_hs)
        ld      (hl),a
        inc     hl
        ld      ixl,a                   ; γραμμές
        ld      a,(cl_n)
        ld      ixh,a                   ; πλάτος
        ld      a,(gh_pen)
        ld      c,a
        call    gh_rows
        ld      (gh_ptr),hl
        ret

; ---------------------------------------------------------------------------
; gh_rows — ο βρόχος του gh_rect: σώσε και γράψε C, IXH bytes x IXL γραμμές.
; In: DE = οθόνη, HL = αρχείο. Out: HL μετά την εγγραφή.
;
; ΔΥΟ ΓΡΗΓΟΡΟΙ ΔΡΟΜΟΙ, γιατί ό,τι κοστίζει στο φάντασμα είναι οι βρόχοι, όχι
; η λογική του (βήμα 35: 94 ms το κόκκινο φάντασμα ενός L, τα 35 στους
; βρόχους). Μια στήλη πλάτους 1 — οι δύο πλευρές του πλαισίου, 124 γραμμές η
; καθεμιά — δεν σώζει και δεν ξαναφορτώνει τη διεύθυνση σε κάθε γραμμή. Μια
; γραμμή που δεν φτάνει στο #FF δεν ελέγχει το τύλιγμα σε κάθε byte: κοιτά μία
; φορά αν το τελευταίο της byte το περνά, και μόνο τότε πάει στον αργό δρόμο.
; ---------------------------------------------------------------------------
gh_rows:
        ld      a,ixh
        dec     a
        jr      nz,ghw_row
ghw_col:                                ; πλάτος 1: η στήλη
        ld      a,(de)
        ld      (hl),a
        inc     hl
        ld      a,c
        ld      (de),a
        call    scr_nextline
        dec     ixl
        jr      nz,ghw_col
        ret
ghw_row:
        push    de
        ld      b,ixh
        ld      a,b
        dec     a
        add     a,e                     ; το τελευταίο byte περνά το #FF;
        jr      c,ghw_slow
ghw_fast:
        ld      a,(de)
        ld      (hl),a
        inc     hl
        ld      a,c
        ld      (de),a
        inc     e
        djnz    ghw_fast
        jr      ghw_next
ghw_slow:
        ld      a,(de)
        ld      (hl),a
        inc     hl
        ld      a,c
        ld      (de),a
        inc     de
        ld      a,e
        or      a
        call    z,gh_wrap
        djnz    ghw_slow
ghw_next:
        pop     de
        call    scr_nextline
        dec     ixl
        jr      nz,ghw_row
        ret

; ---------------------------------------------------------------------------
; gh_undo — όλα πίσω. Μια ανταλλαγή βάζει στην οθόνη ό,τι ήταν από κάτω, και
; ό,τι πήγε στο αρχείο (το φάντασμα) πετιέται με το gh_reset.
; ---------------------------------------------------------------------------
gh_undo:
        call    gh_swap
        jp      gh_reset

; ---------------------------------------------------------------------------
; gh_swap — οθόνη και αρχείο ανταλλάσσουν bytes, ορθογώνιο προς ορθογώνιο.
;
; ΜΙΑ ρουτίνα, δύο δουλειές, γιατί η ανταλλαγή είναι η αντίστροφη του εαυτού
; της. Την πρώτη φορά η οθόνη παίρνει πίσω ό,τι ήταν κάτω από το φάντασμα και
; το αρχείο κρατά το φάντασμα· κάποιος ζωγραφίζει ελεύθερα από κάτω· τη δεύτερη
; φορά το φάντασμα ξαναπέφτει στις ΙΔΙΕΣ θέσεις και το αρχείο κρατά τα ΝΕΑ bytes
; από κάτω. Το ui_hide / ui_show κάνει το ίδιο αλλά ξαναϋπολογίζει ό,τι
; ζωγραφίζει — εγκυρότητα, σημάδια, σχέδιο διαδρόμου (βήμα 34).
;
; Τα ορθογώνια δεν επικαλύπτονται, οπότε η σειρά δεν μετράει.
; ---------------------------------------------------------------------------
gh_swap:
        ld      hl,GH_BUF
gs_lp:
        ld      de,(gh_ptr)
        ld      a,l
        cp      e
        jr      nz,gs_go
        ld      a,h
        cp      d
        ret     z
gs_go:
        ld      e,(hl)
        inc     hl
        ld      d,(hl)
        inc     hl
        ld      a,(hl)
        ld      ixh,a                   ; πλάτος
        inc     hl
        ld      a,(hl)
        ld      ixl,a                   ; ύψος
        inc     hl
        ; οι ίδιοι δύο γρήγοροι δρόμοι με το gh_rows
        ld      a,ixh
        dec     a
        jr      nz,gs_row
gs_col:
        ld      a,(de)
        ld      c,a
        ld      a,(hl)
        ld      (de),a
        ld      (hl),c
        inc     hl
        call    scr_nextline
        dec     ixl
        jr      nz,gs_col
        jr      gs_lp
gs_row:
        push    de
        ld      b,ixh
        ld      a,b
        dec     a
        add     a,e
        jr      c,gs_slow
gs_fast:
        ld      a,(de)
        ld      c,a
        ld      a,(hl)
        ld      (de),a
        ld      (hl),c
        inc     hl
        inc     e
        djnz    gs_fast
        jr      gs_next
gs_slow:
        ld      a,(de)
        ld      c,a
        ld      a,(hl)
        ld      (de),a
        ld      (hl),c
        inc     hl
        inc     de
        ld      a,e
        or      a
        call    z,gh_wrap
        djnz    gs_slow
gs_next:
        pop     de
        call    scr_nextline
        dec     ixl
        jr      nz,gs_row
        jr      gs_lp

; ---------------------------------------------------------------------------
; gh_box — πλαίσιο γύρω από ορθογώνιο: τέσσερα ορθογώνια, όχι 2 x h λωρίδες.
; In: (gh_bx) 16-bit x σε bytes, (gh_by) 16-bit y, (gh_bw) bytes, (gh_bh) γραμμές
;
; Οι πλευρές ξεκινούν κάτω από την πάνω και σταματούν πάνω από την κάτω: αν
; επικαλύπτονταν, η δεύτερη θα έσωζε ό,τι είχε ήδη γράψει η πρώτη.
; ---------------------------------------------------------------------------
GH_EDGE     equ 2                       ; πάχος της οριζόντιας πλευράς

gh_box:
        ; --- πάνω ---
        ld      hl,(gh_bx)
        ld      (gh_x),hl
        ld      hl,(gh_by)
        ld      (gh_y),hl
        ld      a,(gh_bw)
        ld      (gh_n),a
        ld      a,GH_EDGE
        ld      (gh_nv),a
        call    gh_rect
        ; --- κάτω ---
        ld      hl,(gh_by)
        ld      a,(gh_bh)
        sub     GH_EDGE
        call    ob_addsx
        ld      (gh_y),hl
        call    gh_rect
        ; --- αριστερά, ΧΩΡΙΣ τις γραμμές που έγραψαν οι οριζόντιες ---
        ld      a,(gh_bh)
        sub     GH_EDGE*2
        ret     c
        ret     z
        ld      (gh_nv),a
        ld      a,1
        ld      (gh_n),a
        ld      hl,(gh_by)
        ld      de,GH_EDGE
        add     hl,de
        ld      (gh_y),hl
        call    gh_rect
        ; --- δεξιά ---
        ld      hl,(gh_bx)
        ld      a,(gh_bw)
        dec     a
        call    ob_addsx
        ld      (gh_x),hl
        jp      gh_rect

; ---------------------------------------------------------------------------
; gh_mark — γέμισμα 2 bytes x 4 γραμμές στο κέντρο ενός tile. Ενα σημάδι για
; κάθε tile που ΔΕΝ επιτρέπεται, ώστε ο παίκτης να ξέρει ΠΟΙΟ φταίει.
; In: B = στήλη, C = σειρά του tile ΜΕΣΑ στο κάδρο (προσημασμένα, 8 bit).
;
; ΧΩΡΙΣ CLIP. Η κάμερα κουμπώνει πάντα σε tiles (το cam_p είναι πολλαπλάσιο
; του 4), οπότε ένα tile είτε φαίνεται ολόκληρο είτε καθόλου — και το σημάδι
; μαζί του. Ως το βήμα 35 κάθε σημάδι περνούσε από συντεταγμένες 16 bit, δύο
; ob_clip και τέσσερις λωρίδες· το κόκκινο φάντασμα ενός L έχει 64 σημάδια.
; ---------------------------------------------------------------------------
gh_mark:
        ld      a,b
        cp      VIEW_TW
        ret     nc                      ; αρνητικό είναι «μεγάλο» χωρίς πρόσημο
        ld      a,c
        cp      VIEW_TH
        ret     nc
        ld      a,b
        add     a,a
        add     a,a
        inc     a
        ld      (cl_start),a            ; x = 4 * στήλη + 1
        ld      a,c
        add     a,a
        add     a,a
        add     a,a
        add     a,a
        add     a,6
        ld      (gh_ys),a               ; y = 16 * σειρά + 6
        ld      a,2
        ld      (cl_n),a
        ld      a,4
        ld      (gh_hs),a
        jp      ghr_put

; gh_setpen — A = pen -> το byte γεμίσματος στο gh_pen.
gh_setpen:
        ld      l,a
        ld      h,0
        ld      de,hud_solid
        add     hl,de
        ld      a,(hl)
        ld      (gh_pen),a
        ret

gh_ptr:     dw GH_BUF           ; άδειο αρχείο από την εκκίνηση, όχι μόνο μετά το gh_reset
gh_x:       dw 0
gh_y:       dw 0
gh_n:       db 0
gh_nv:      db 0
gh_ys:      db 0
gh_hs:      db 0                ; γραμμές που μένουν μετά το clip
gh_pen:     db 0
; x0, x1 σε bytes οθόνης και y0, y1 σε γραμμές, με τη διάταξη των clip_x0..
; clip_y1 του object.asm — το dt_ghost τα φορτώνει στη θέση τους αυτούσια.
gh_bbx:     db 255, 0
gh_bby:     db 255, 0
gh_bx:      dw 0
gh_by:      dw 0
gh_bw:      db 0
gh_bh:      db 0
