; terrain.asm — ΤΙ ΖΗΤΑ Ο ΤΟΠΟΣ: η αντλία λίμνη, το ορυχείο φλέβα (§6.5).
;
; ΓΙΑΤΙ ΕΙΝΑΙ ΧΩΡΙΣΤΟ ΑΡΧΕΙΟ. Είναι η δεύτερη μισή δουλειά του bd_check, και θα
; καθόταν φυσικά δίπλα του μέσα στο src/build.asm — αλλά το build.asm τρέχει
; από την ΤΡΑΠΕΖΑ 2, όπου μετά το βήμα 30 έμεναν 66 ελεύθερα bytes, και αυτό
; εδώ είναι 110. Οι δύο περιοχές κώδικα φαίνονται και οι δύο πάντα (η τράπεζα 2
; κάθεται στο #8000 μόνιμα), οπότε το `jp bd_res` από την άλλη μεριά δεν
; κοστίζει τίποτα πέρα από τα τρία bytes του.
;
; Ολα τα bd_* που διαβάζει ζουν στο src/build.asm — απόλυτες διευθύνσεις, καμία
; σελιδοποίηση ανάμεσα.

; ---------------------------------------------------------------------------
; bd_res — ΤΟ ΥΛΙΚΟ ΠΟΥ ΖΗΤΑ Η ΔΟΜΗ, μέσα ή γύρω από το αποτύπωμα (§6.5).
;
; Ο πίνακας του §6.5 γράφει «extractor (on water)» και «mine (on ore)» από την
; πρώτη μέρα· ο κώδικας δεν το διάβαζε ποτέ, και η αντλία ήταν μια βρύση που
; έβγαινε οπουδήποτε — μέσα στην αποικία, στη μέση της ερήμου, παντού. Το bit 3
; του world byte (§3.5) το ΓΡΑΦΕΙ η γεννήτρια και το ΖΩΓΡΑΦΙΖΕΙ το
; tile_ore_overlay: η φλέβα φαίνεται στην οθόνη και δεν σήμαινε τίποτα.
;
; Ο κανόνας: το αποτύπωμα μένει εκεί που πατούσε — έδαφος, σκόνη ή θεμέλιο —
; και το υλικό πρέπει να βρίσκεται μέσα στο ορθογώνιο ΜΕ ΔΥΟ tiles περιθώριο.
; Ούτε η αντλία ούτε το ορυχείο μπορεί να πατήσει πάνω στο υλικό του: ούτε το
; νερό ούτε το βουνό χτίζονται.
;
; ΤΑ ΔΥΟ TILES ΕΙΝΑΙ ΜΕΤΡΗΜΕΝΑ, ΟΧΙ ΔΙΑΛΕΓΜΕΝΑ. Με ένα, η αντλία χτιζόταν
; (η ακτή είναι έδαφος που ακουμπά νερό) αλλά το ορυχείο ΠΟΥΘΕΝΑ: το ύψος
; ανεβαίνει βουνό -> βράχος -> έδαφος, ο βράχος δεν χτίζεται, και έτσι ανάμεσα
; στη φλέβα και στο πρώτο χτίσιμο έδαφος υπάρχει πάντα τουλάχιστον μία σειρά
; βράχου. Μετρημένο στο επίπεδο του παιχνιδιού: το κοντινότερο 4x4 που
; χτίζεται απέχει ΑΚΡΙΒΩΣ 2 tiles από φλέβα, σε 7 tiles από το κέντρο.
;
; ΤΡΕΧΕΙ ΜΟΝΟ ΟΤΑΝ ΤΟ ΑΠΟΤΥΠΩΜΑ ΕΙΝΑΙ ΗΔΗ ΚΑΛΟ, και αυτό δεν είναι μόνο
; ταχύτητα: εγγυάται ότι το περιθώριο δεν βγαίνει έξω από το επίπεδο. Από το
; r = 57 και έξω η γεννήτρια σηκώνει το ύψος κατά 40 ανά δαχτυλίδι (§5.5), άρα
; στο r >= 62 η προσθήκη είναι 240 και ΚΑΘΕ tile γίνεται βουνό — το ψηλότερο
; κατώφλι βουνού των τεσσάρων πλανητών είναι 205. Το βουνό δεν χτίζεται, άρα
; ένα έγκυρο αποτύπωμα μένει μέσα στο -61..61 και η σάρωση μέσα στο -63..63.
;
; Out: A = 0 αν επιτρέπεται. (bd_nres) = 0 · 1 θέλει νερό · 2 θέλει φλέβα.
; ---------------------------------------------------------------------------
bd_res:
        xor     a
        ld      (bd_nres),a
        ld      a,(bd_kind)
        cp      BK_STRUCT
        jr      nz,bdr_none
        ld      a,(bd_param)
        ld      c,1                     ; 1 = νερό
        cp      K_EXTRACT
        jr      z,bdr_go
        inc     c                       ; 2 = φλέβα
        cp      K_MINE
        jr      z,bdr_go
bdr_none:
        ; ΜΕ ΚΑΘΑΡΟ ΤΟ A, ΚΑΙ ΟΧΙ ΜΕ ΟΤΙ ΕΤΥΧΕ. Εδώ στεκόταν ένα `ret nz` μετά
        ; το `cp`, που γυρνούσε το ΕΙΔΟΣ της δομής ως αριθμό άκυρων tiles: ο
        ; συλλέκτης (K_COLLECT = 2) έβγαινε «2 άκυρα tiles» και δεν χτιζόταν
        ; πουθενά. Το έπιασε το tests/test_needs.py, που χτίζει επτά κτίσματα
        ; και είδε το τέταρτο να μην μπαίνει.
        xor     a
        ret
bdr_go:
        ld      a,c
        ld      (bd_nres),a             ; «λείπει», ώσπου να βρεθεί
        ld      a,(bd_ty)
        sub     RES_NEAR
        ld      (bd_cy),a
        ld      a,(bd_h)
        add     a,RES_NEAR*2
        ld      (bd_row),a
bdr_rl:
        ld      a,(bd_tx)
        sub     RES_NEAR
        ld      b,a
        ld      a,(bd_cy)
        ld      c,a
        call    tile_addr
        ld      a,(bd_w)
        add     a,RES_NEAR*2
        ld      b,a
bdr_cl:
        ld      a,(hl)
        call    bdr_test
        jr      z,bdr_yes
        inc     hl
        djnz    bdr_cl
        ld      hl,bd_cy
        inc     (hl)
        ld      hl,bd_row
        dec     (hl)
        jr      nz,bdr_rl
        ld      a,1                     ; δεν βρέθηκε: άκυρη θέση
        ret
bdr_yes:
        xor     a
        ld      (bd_nres),a
        ret

; bdr_test — A = world byte. Z αν είναι το υλικό που ζητά το (bd_nres).
; Δεν πειράζει ούτε HL ούτε BC: τρέχει μέσα στον βρόχο των στηλών.
bdr_test:
        ld      e,a
        ld      a,(bd_nres)
        dec     a
        ld      a,e
        jr      nz,bdr_ore
        and     7
        cp      W_WATER
        ret     z
        cp      W_DEEPWATER
        ret
bdr_ore:
        and     7 + 8                   ; κλάση ΚΑΙ το bit πόρου (§3.5)
        cp      W_MOUNTAIN + 8
        ret
bd_nres:    db 0                ; ποιο υλικό λείπει: 0 κανένα, 1 νερό, 2 φλέβα
