; screen.asm — αριθμητική διευθύνσεων οθόνης, ΜΕ την κάμερα μέσα.
;
; Διάταξη CPC:  addr = SCR_BASE + (y&7)*#800 + p,  όπου p η θέση μέσα στο
; δαχτυλίδι των 2.048 bytes. Χωρίς κάμερα το p ήταν απλώς (y>>3)*80 + x.
;
; ΤΟ ΔΑΧΤΥΛΙΔΙ. Ο CRTC κρατά 14 bits διεύθυνσης αλλά ο Gate Array πετάει τα
; bits 10 και 11: τα MA9..MA0 πάνε στα A10..A1. Άρα η σάρωση γυρίζει κάθε
; **1.024 λέξεις = 2.048 bytes**, και η οθόνη χρησιμοποιεί 1.000 από αυτές.
; Μόλις η κάμερα δώσει offset > 24 λέξεις, το σημείο τυλίγματος μπαίνει ΜΕΣΑ
; στην ορατή εικόνα: το p πρέπει να υπολογίζεται mod 2.048, και μια γραμμή
; sprite μπορεί να το πατήσει στη μέση (το bl_wrap του blit.asm).
;
;       p = ((y>>3)*SCR_W + x + cam_p) & #7FF
;       D = #C0 + (y&7)*8 + (p>>8)      E = p & #FF
;
; Το (y&7)*8 κάθεται στα bits 3-5 του D και το p>>8 στα 0-2 — δεν μπερδεύονται,
; και γι' αυτό το τύλιγμα του p είναι ένα `and #C7` πάνω στο D.

; ---------------------------------------------------------------------------
; scr_nextline — DE στην επόμενη γραμμή οθόνης.
; Χαλάει: A, F.  Διατηρεί: BC, HL, IX, IY.
;
; d += 8· αν ξεχειλίσει, ήμασταν στη γραμμή 7 της σειράς, οπότε η επόμενη
; γραμμή είναι -#3800 +#50 από εδώ. Το κρατάμε σε δύο βήματα ώστε το κρατούμενο
; του e να μπει στο d. Το `and #C7` στο τέλος είναι το δαχτυλίδι: χωρίς αυτό
; το p περνάει το #7FF και η γραμμή φεύγει οκτώ γραμμές πιο κάτω.
; ---------------------------------------------------------------------------
scr_nextline:
        ld      a,d
        add     a,8
        ld      d,a
        ret     nc                  ; ίδια σειρά χαρακτήρων — τελειώσαμε
        ld      a,e
        add     a,SCR_W
        ld      e,a
        ld      a,d                 ; το ld δεν πειράζει τα flags
        adc     a,#C0
        and     #C7                 ; p mod 2048
        ld      d,a
        ret

; ---------------------------------------------------------------------------
; scr_addr — διεύθυνση οθόνης για (x, y), με το offset της κάμερας μέσα.
; In :  C = x σε bytes (0..79),  A = y σε γραμμές (0..199)
; Out:  DE = διεύθυνση,  A = D,  HL = r*SCR_W + x + cam_p (χωρίς το mod)
; Χαλάει: F.  Κρατά: BC, IX, IY.
;
; ΧΩΡΙΣ ΠΙΝΑΚΑ ΑΠΟ ΤΟ ΒΗΜΑ 68 (DESIGN §8.2). Το r*80 είναι (y & #F8) * 10, δηλαδή
; 8r -> x4 -> +8r -> x2: τέσσερις προσθέσεις του HL, φθηνότερες από το να
; διαβαστεί λέξη από πίνακα 50 bytes. Το y μένει στο A ως το τέλος, άρα δεν
; χρειάζεται ούτε push af ούτε push bc.
; ---------------------------------------------------------------------------
scr_addr:
        ld      l,a
        and     #F8                 ; 8r, r = y >> 3
        ld      e,a
        ld      d,0
        ld      a,l                 ; το y, ως το τέλος
        ld      h,d
        ld      l,e                 ; HL = DE = 8r
        add     hl,hl
        add     hl,hl               ; 32r
        add     hl,de               ; 40r
        add     hl,hl               ; 80r = r * SCR_W   (<= 1.920)
        ld      e,c                 ; το D είναι ακόμη 0
        add     hl,de               ; + x
        ld      de,(cam_p)
        add     hl,de               ; + η κάμερα, σε bytes (0..2046): <= #0FBD
        add     a,a
        add     a,a
        add     a,a                 ; (y&7) * 8 στα bits 3-5, ό,τι να 'ναι στα 6-7
        or      #C0                 ; ...που το #C0 τα σβήνει: χωρίς `and 7`
        ld      e,a
        ld      a,h
        and     7                   ; p >> 8, mod 2048
        or      e
        ld      d,a
        ld      e,l
        ret

        assert  SCR_W == 80         ; το x10 του (y & #F8)

; Η κάμερα σε bytes μέσα στο δαχτυλίδι — 2x το offset λέξεων του CRTC.
cam_p:      dw 0
