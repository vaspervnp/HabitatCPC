; suit.asm — οι στολές (βήμα 90, DESIGN §6.6).
;
; Εξω από τη βάση ο άποικος αναπνέει από τη στολή του, και η στολή αδειάζει.
; Οι αποφάσεις του παίκτη:
;
;   ΔΙΑΡΚΕΙΑ     τρία λεπτά ανά έξοδο, δέκα στην αρχή (οι τέσσερις του σκάφους)
;   ΓΕΜΙΣΜΑ      σε κάθε έξοδο, δωρεάν: όποιος βγαίνει από airlock έχει πάντα
;                γεμάτη στολή — την αναπνοή μέσα την πληρώνει ήδη το οξυγόνο
;                της αποικίας (το emd_put του src/entity.asm)
;   ΕΠΙΣΤΡΟΦΗ    με ένα λεπτό αέρα αφήνει τη δουλειά και πάει στο κοντινότερο
;                airlock, μόνος του (su_lock)
;   ΘΑΝΑΤΟΣ      όταν αδειάσει, αμέσως
;   HUD          SUIT AIR LOW, όσο κάποιος έξω έχει κάτω από ένα λεπτό
;
; Η ΜΟΝΑΔΑ ΕΙΝΑΙ ΔΥΟ ΕΠΙΣΚΕΨΕΙΣ ΑΝΑΓΚΩΝ. Ο καθένας δέχεται επίσκεψη κάθε 64
; frames (96 άποικοι, 24 ανά περιστροφή, §7.2), και τα δέκα λεπτά είναι 469
; επισκέψεις — δεν χωρούν σε byte. Η στολή αδειάζει λοιπόν κάθε ΔΕΥΤΕΡΗ
; επίσκεψη, και το «ποια από τις δύο» είναι ένα bit στις σημαίες του ίδιου
; (F_SUITPH): καμία μεταβλητή που να πρέπει να γυρίζει μαζί με τον τροχό, και
; τίποτα για όσους είναι μέσα. Μία μονάδα = 128 frames = 2,56 s.
;
; Τα ρομπότ (ρόλοι 5-7, §6.1) δεν αναπνέουν.

SUIT_START  equ 234                     ; 234 x 128 frames = 9:59
SUIT_TRIP   equ 70                      ; 70 x 128 = 2:59
SUIT_LOW    equ 23                      ; 23 x 128 = 0:59 — γυρίζει μέσα
F_SUITPH    equ 64                      ; 1: η επόμενη επίσκεψη παίρνει μονάδα
SU_BOT      equ 5                       ; ο πρώτος ρόλος ρομπότ
; Πόσα τικ του HUD κρατά το SUIT AIR LOW μετά την τελευταία επίσκεψη που το
; είδε, συν ένα (το su_hud μετρά ΠΡΙΝ το δείξει η γραμμή). Το HUD ξαναγράφεται
; ανά 16 frames (ml_hudw) και η στολή κοιτάζεται ανά 128 (μία επίσκεψη στις
; δύο): οκτώ τικ ανάμεσα, και ένα περιθώριο.
SU_TTL      equ 10

; ---------------------------------------------------------------------------
; su_tick — ένας άποικος ΕΞΩ, στη θέση του οξυγόνου: jp από το nd_out
; (src/needs.asm), με L = id. Τελειώνει με jp: στο nd_die αν η στολή άδειασε,
; αλλιώς στο nd_load, αφού κάνει εδώ τη φθορά του νερού, του ύπνου και της
; τροφής — αντίγραφο του nd_d2. Χαλάει A, D, E και, αν ψάξει airlock, BC.
;
; ΕΞΩ ΚΑΝΕΝΑ ΔΩΜΑΤΙΟ ΔΕΝ ΔΙΝΕΙ ΤΙΠΟΤΑ, και γι' αυτό το nd_sat («στέκεται σε
; θόλο;») πηδιέται. Ως το βήμα 89 δεν πηδιόταν, και το nd_satisfy δεν κοιτά
; αν ο θόλος είναι έτοιμος: από το βήμα 87 ο χτίστης στέκεται ΕΞΩ, στο
; εργοτάξιο, και σε εργοτάξιο κοιτώνα κοιμόταν, σε εργοτάξιο κυλικείου έτρωγε
; από την αποθήκη. Και 13-21 us λιγότερα ανά επίσκεψη έξω.
;
; Η ΜΙΣΗ ΕΠΙΣΚΕΨΗ ΔΕΝ ΚΑΝΕΙ ΤΙΠΟΤΑ άλλο από το bit της, ούτε τον ρόλο
; κοιτά: το bit γυρίζει και στα ρομπότ, που δεν το διαβάζουν. Ετσι κοστίζει
; 9 us ως τη φθορά, και η αναζήτηση airlock, όσο κάποιος έχει λίγο αέρα και
; κανένα airlock δεν φτάνεται (στην αρχή, πριν χτιστεί), γίνεται ανά 128
; frames.
; ---------------------------------------------------------------------------
su_tick:
        ld      h,AG_PG
        bit     6,(hl)                  ; F_SUITPH: 1 = η επίσκεψη που αδειάζει
        jr      nz,su_full
        set     6,(hl)                  ; η μισή επίσκεψη: 9 us ως το su_nz
su_nz:
        ld      h,AG_PG + 4
        set     7,l
        ld      a,(hl)                  ; νερό
        or      a
        jr      z,su_d3
        dec     (hl)
su_d3:  inc     h
        ld      a,(hl)                  ; ύπνος
        or      a
        jr      z,su_d4
        dec     (hl)
su_d4:  res     7,l
        ld      a,(hl)                  ; τροφή
        or      a
        jp      z,nd_load
        dec     (hl)
        jp      nd_load

su_full:
        res     6,(hl)
        set     7,l
        ld      a,(hl)                  ; ρόλος
        res     7,l
        cp      SU_BOT
        jr      nc,su_nz                ; ρομπότ: δεν αναπνέει
        ld      h,AG_PG + 7
        dec     (hl)
        jp      z,nd_die                ; άδειασε: αμέσως
        ld      a,(hl)
        cp      SUIT_LOW + 1
        jr      nc,su_nz
        ld      a,SU_TTL
        ld      (su_alarm),a
        ; Πάει ήδη μέσα; Εξω, το T_NEED οδηγεί πάντα μέσα: σε airlock για τη
        ; στολή, ή σε θόλο για μια ανάγκη — και τον θόλο από έξω τον φτάνει
        ; κανείς μόνο από airlock. Το needs.asm δεν το ξανασβήνει έξω (nd_sated).
        ld      h,AG_PG + 3
        set     7,l
        ld      a,(hl)                  ; εργασία
        res     7,l
        cp      T_NEED
        jr      z,su_nz
        push    hl
        ld      h,AG_PG + 1
        ld      d,(hl)                  ; ο κόμβος του
        call    su_lock
        pop     hl
        inc     a
        jr      z,su_nz                 ; κανένα airlock που να φτάνεται
        dec     a
        ld      h,AG_PG + 2
        ld      (hl),a                  ; προορισμός
        inc     h
        set     7,l
        ld      (hl),T_NEED             ; αφήνει τη δουλειά του (§6.7)
        res     7,l
        jr      su_nz

; ---------------------------------------------------------------------------
; su_lock — D = κόμβος -> A = το κοντινότερο ΕΤΟΙΜΟ airlock στον γράφο (DIST),
; ή 255. Ισοπαλία: η πρώτη δομή, όπως το nd_nearest. Χαλάει BC, DE, HL.
;
; Ο δείκτης περπατά στο ST_KIND των δομών με add στο L ώσπου να κρατήσει: 13
; us ανά δομή που δεν είναι airlock — με τον IX ήταν 25, και το πέρασμα 800
; us. ΔΥΟ ΣΕΛΙΔΕΣ από το βήμα 154 (16 δομές στη μία, 32 στην άλλη, και κάθε
; σελίδα τελειώνει σε όριο εγγραφής, tools/pack.py): στο πρώτο κρατούμενο
; inc h, στο δεύτερο τέλος. Περνά και τις 48 θέσεις, και με 32 δομές· οι 16
; άδειες είναι 208 us, όσο θα κοστίζουν ούτως ή άλλως στο βήμα 155. Ο κόμβος
; βγαίνει από το HL μόνο σε airlock. Οι δομές είναι στην τράπεζα 6 και το DIST
; στην 1, στο ίδιο παράθυρο: η 1 μπαίνει μόνο για την ανάγνωση μιας απόστασης,
; και ξαναβγαίνει.
; ---------------------------------------------------------------------------
su_lock:
        ld      h,d
        ld      l,0
        srl     h
        rr      l
        set     6,h                     ; DIST[κόμβος], στο &4000
        ld      (sul_row + 1),hl
        ld      a,255
        ld      (su_best),a
        ld      d,a                     ; D = η καλύτερη απόσταση
        ld      hl,G_struct_tbl + ST_KIND
sul_lp:
        ld      a,(hl)
        cp      K_AIRLOCK
        jr      z,sul_hit
sul_nx:
        ld      a,l
        add     a,STRUCT_REC
        ld      l,a
        jr      nc,sul_lp               ; ως το τέλος της σελίδας
        inc     h
        ld      a,h
        cp      (G_struct_tbl + 48 * STRUCT_REC) >> 8
        jr      c,sul_lp                ; και η δεύτερη
        ld      a,(su_best)
        ret
sul_hit:
        inc     l
        inc     l
        ld      a,(hl)                  ; ST_STATE
        dec     l
        dec     l
        cp      DS_ACTIVE
        jr      nz,sul_nx
        push    hl
        ld      bc,-(G_struct_tbl + ST_KIND)
        add     hl,bc                   ; 8 x δομή, κάτω από 384
        ld      a,l
        srl     h
        rra
        rra
        rra                             ; η δομή: τα κρατούμενα είναι 0
        add     a,MAX_DOME
        ld      e,a                     ; E = ο κόμβος του
sul_row:
        ld      hl,0                    ; DIST[κόμβος] (γράφεται πάνω)
        or      l                       ; 0 ή 128, και ο κόμβος < 128
        ld      l,a
        ld      bc,GA_PORT + PAGE_B1
        out     (c),c
        ld      a,(hl)                  ; DIST[κόμβος][airlock]
        ld      c,PAGE_B6 & 255
        out     (c),c
        pop     hl
        cp      d
        jr      nc,sul_nx               ; ούτε πιο κοντά, ούτε απρόσιτο (255)
        ld      d,a
        ld      a,e
        ld      (su_best),a
        jr      sul_nx

; ---------------------------------------------------------------------------
; su_hud — ένα τικ του HUD, στην αρχή του hud_alert, όποιο μήνυμα κι αν
; κερδίσει. Μετά, (su_alarm) <> 0 σημαίνει «κάποιος έξω είχε λιγότερο από ένα
; λεπτό αέρα στα τελευταία SU_TTL - 1 τικ». Χαλάει A, HL.
; ---------------------------------------------------------------------------
su_hud:
        ld      hl,su_alarm
        ld      a,(hl)
        or      a
        ret     z
        dec     (hl)
        ret

su_alarm:   db 0
su_best:    db 0

        assert  SUIT_START <= 255 && SUIT_LOW < SUIT_TRIP
        assert  MAX_DOME + MAX_STRUCT <= 128      ; L | κόμβος, χωρίς κρατούμενο
        assert  F_SUITPH == 1 << 6               ; bit 6 στο su_tick
        assert  ((G_struct_tbl + 48 * STRUCT_REC) & 255) == 0 && (G_struct_tbl & 255) >= 128
        assert  STRUCT_REC == 8 && ST_KIND < 8 && ST_STATE == ST_KIND + 2
