; input.asm — πληκτρολόγιο και χειριστήριο (DESIGN §9.1).
;
; Το πληκτρολόγιο του CPC δεν διαβάζεται από θύρα: κρέμεται από τη ΘΥΡΑ Α του
; PPI, που την οδηγεί ο ήχος. Η σειρά είναι αυστηρή και αν κάποιο βήμα λείψει
; δεν διαβάζεται τίποτα — ή, χειρότερα, διαβάζεται σκουπίδι:
;
;   1. PPI control #82  θύρα Α ΕΞΟΔΟΣ (πάμε να γράψουμε στον ήχο)
;   2. θύρα Α  = 14     ο καταχωρητής του PSG που βλέπει το πληκτρολόγιο
;   3. θύρα C  = #C0    PSG: «επίλεξε καταχωρητή»
;   4. θύρα C  = #00    PSG: αδρανής
;   5. PPI control #92  θύρα Α ΕΙΣΟΔΟΣ
;   6. θύρα C  = #40|n  PSG: «διάβασε», με τη γραμμή n στα χαμηλά bits
;   7. in a,(#F4xx)     τα bits της γραμμής — ΜΗΔΕΝ σημαίνει πατημένο
;
; Το key_now κρατά τα bits ΟΠΩΣ ΕΡΧΟΝΤΑΙ, 0 = πατημένο: το ini τα γράφει
; κατευθείαν, και το in_read τα ρωτά με `and` και `sub 1` (βήμα 64). Τα
; act_now και act_hit είναι 1 = πατημένο, όπως πάντα.
;
; Η ΓΡΑΜΜΗ 9 ΕΙΝΑΙ ΤΟ ΧΕΙΡΙΣΤΗΡΙΟ. Δεν χρειάζεται τίποτε άλλο: το joystick 0
; κάθεται στην ίδια μήτρα με τα πλήκτρα. Και τα bits 0-5 της γραμμής του είναι
; ακριβώς οι ενέργειες 0-5 (πάνω, κάτω, αριστερά, δεξιά, fire 1, fire 2 =
; ακύρωση), με τη σειρά: «πληκτρολόγιο ΚΑΙ χειριστήριο» είναι ένα `or`, όχι
; δεύτερη στήλη στον πίνακα.

KEY_LINES   equ 10
; PPI_A / PPI_C / PPI_CTRL: στο const.asm — τα μοιράζεται με το sound.asm.

; --- οι ενέργειες, ως bits του act_now / act_hit ---
A_UP        equ 0
A_DOWN      equ 1
A_LEFT      equ 2
A_RIGHT     equ 3
A_FIRE      equ 4
A_CANCEL    equ 5
A_MENU      equ 6
A_NEXT      equ 7
A_HOME      equ 8
A_SPD1      equ 9
A_SPD2      equ 10
A_SPD3      equ 11
A_SPD4      equ 12
A_SAVE      equ 13
A_LOAD      equ 14
A_SHIP      equ 15                      ; C — κάλεσε πλοίο αποίκων (§6.11)
A_ACTIONS   equ 16                      ; όσα χωρούν στα δεκαέξι bit του act_now
A_JOY       equ #3F                     ; οι ενέργειες 0-5, και από τη γραμμή 9

; --- η μήτρα: ενέργεια -> (key_now + γραμμή, μάσκα) του πλήκτρου ---
; Το χειριστήριο δεν είναι εδώ: το A_JOY του in_read.
;
; Ο ΠΙΝΑΚΑΣ ΚΑΙ ΤΟ key_now ΘΕΛΟΥΝ ΜΙΑ ΣΕΛΙΔΑ (το H του in_read, assert στο
; τέλος). Γι' αυτό είναι ΠΡΩΤΑ στο αρχείο και το αρχείο μπαίνει στο main.asm
; αμέσως μετά τον βρόχο (βήμα 66): πάνω τους έχουν μόνο το start και το
; main_loop. Ως το βήμα 65 έρχονταν μετά από οκτώ αρθρώματα, και όταν μίκρυνε
; το blit.asm πέρασαν σελίδα.
act_src:
        db      (key_now + 0) & 255, #01        ; πάνω     — κέρσορας πάνω
        db      (key_now + 0) & 255, #04        ; κάτω
        db      (key_now + 1) & 255, #01        ; αριστερά
        db      (key_now + 0) & 255, #02        ; δεξιά
        db      (key_now + 1) & 255, #02        ; FIRE     — COPY
        db      (key_now + 8) & 255, #04        ; ακύρωση  — ESC
        db      (key_now + 5) & 255, #80        ; μενού    — SPACE
        db      (key_now + 8) & 255, #10        ; επόμενο  — TAB
        db      (key_now + 5) & 255, #10        ; κέντρο   — H
        db      (key_now + 8) & 255, #01        ; 1 παύση
        db      (key_now + 8) & 255, #02        ; 2 κανονικά
        db      (key_now + 7) & 255, #02        ; 3 γρήγορα
        db      (key_now + 7) & 255, #01        ; 4 πολύ γρήγορα
        db      (key_now + 7) & 255, #10        ; S σώσε
        db      (key_now + 4) & 255, #10        ; L φόρτωσε
        db      (key_now + 7) & 255, #40        ; C κάλεσε πλοίο
key_now:    defs KEY_LINES
act_now:    dw 0
act_hit:    dw 0

; ---------------------------------------------------------------------------
; in_scan — και οι δέκα γραμμές στο key_now. 0 = πατημένο.
; ---------------------------------------------------------------------------
in_scan:
        ld      bc,PPI_CTRL + #82
        out     (c),c                   ; 1
        ld      bc,PPI_A + 14
        out     (c),c                   ; 2
        ld      bc,PPI_C + #C0
        out     (c),c                   ; 3
        xor     a
        out     (c),a                   ; 4
        ld      bc,PPI_CTRL + #92
        out     (c),c                   ; 5
        ld      hl,key_now
        ld      a,#40
isc_lp:
        ld      b,PPI_C >> 8
        out     (c),a                   ; 6: το C δεν μετρά, μόνο το B
        ld      b,PPI_A >> 8
        ini                             ; 7: (hl) = η γραμμή, hl + 1
        inc     a
        cp      #40 + KEY_LINES
        jr      nz,isc_lp
        ld      bc,PPI_CTRL + #82
        out     (c),c
        ld      b,PPI_C >> 8
        xor     a
        out     (c),a
        ret

; ---------------------------------------------------------------------------
; in_read — σαρώνει και βγάζει act_now (κρατημένα) και act_hit (μόλις πατήθηκαν).
;
; Το act_hit είναι ΑΚΜΗ, όχι στάθμη, και χωρίς αυτό κάθε πάτημα θα έτρεχε
; πενήντα φορές το δευτερόλεπτο: ένα «χτίσε» θα έχτιζε πενήντα θόλους.
;
; Ο πίνακας διαβάζεται ανάποδα, από την ενέργεια 15 ως την 0, και κάθε
; απάντηση μπαίνει από δεξιά στο DE με rl: δεκαέξι ολισθήσεις, και η πρώτη
; καταλήγει στο bit 15. Ο,τι είχε το DE πριν βγαίνει ολόκληρο.
; ---------------------------------------------------------------------------
in_read:
        call    in_scan
        ld      hl,key_now              ; H = η σελίδα του πίνακα (assert),
        ld      c,l                     ; C = το τέλος του
        ld      b,A_ACTIONS
inr_lp:
        dec     c
        ld      l,c
        ld      a,(hl)                  ; μάσκα
        dec     c
        ld      l,c
        ld      l,(hl)                  ; key_now + γραμμή
        and     (hl)                    ; 0 = πατημένο
        sub     1                       ; Cy = πατημένο
        rl      e
        rl      d
        djnz    inr_lp
        ld      a,(key_now + 9)         ; και το χειριστήριο
        cpl
        and     A_JOY
        or      e
        ld      e,a

        ; --- ακμή: ό,τι είναι πατημένο τώρα και δεν ήταν πριν ---
        ld      hl,(act_now)
        ld      (act_now),de
        ld      a,l
        cpl
        and     e
        ld      l,a
        ld      a,h
        cpl
        and     d
        ld      h,a
        ld      (act_hit),hl
        ret

; ---------------------------------------------------------------------------
; in_held / in_hit — A = αριθμός ενέργειας. Out: NZ αν ισχύει (A = #FF, αλλιώς
; 0). Κρατά τα C, DE.
; ---------------------------------------------------------------------------
in_held:
        ld      hl,act_now
        jr      in_bit
in_hit:
        ld      hl,act_hit
in_bit:
        cp      8
        jr      c,ib_lo
        inc     hl
        sub     8
ib_lo:
        inc     a
        ld      b,a
        ld      a,(hl)
ib_l:   rrca                            ; το bit n στο Cy στην (n+1)-οστή
        djnz    ib_l
        sbc     a,a
        ret

        assert  key_now == act_src + 2 * A_ACTIONS
        assert  (act_src >> 8) == ((key_now + KEY_LINES - 1) >> 8)
        assert  A_JOY == (1 << A_UP | 1 << A_DOWN | 1 << A_LEFT | 1 << A_RIGHT | 1 << A_FIRE | 1 << A_CANCEL)
