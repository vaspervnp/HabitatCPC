; dirty1.asm — δύο χειριστές της λίστας αλλαγών (src/dirty.asm) που ΤΡΕΧΟΥΝ
; ΣΤΟ OV_R1 από το βήμα 201, όπως οι χειριστές της κατεδάφισης
; (src/dm_hand.asm): η λίστα τρέχει με τη βασική τράπεζα 1 στο παράθυρο, και
; ό,τι καλούν γυρίζει με την 1. Ως το βήμα 200 ήταν στην τράπεζα 0, και τα 62
; bytes τους μένουν εκεί για την κορδέλα των εργοταξίων (βήμα 202).
;
; ΚΑΙ ΣΤΑ BUILDS ΤΩΝ ΔΟΚΙΜΩΝ (tests/objtest.asm, uitest.asm), στον κώδικά τους:
; εκεί δεν υπάρχει OV_R1, και το test_dirty σπρώχνει ένα DK_TILE.
; ---------------------------------------------------------------------------
; --- ένας διάδρομος εμφανίζεται: ΜΙΑ σειρά της διαγωνίου του (§6.9) ---
; Τρία tiles από το (dt_a, dt_b) του κόσμου: όσα αγγίζουν τα δύο διαγώνια
; πλακίδια που μοιράζονται τη σειρά (cr_redraw). Το περίγραμμα μιας διαγωνίου
; n βημάτων είναι τετράγωνο n x n, και ως το βήμα 37 ξαναζωγραφιζόταν όλο σε
; έναν γύρο: 130 ms για 7 βήματα, 45 το έδαφος και 85 τα αντικείμενα.
;
; ΕΔΩ ΧΡΕΙΑΖΕΤΑΙ ΤΟ ob_draw_all, σε αντίθεση με το dh_site. Τα tiles που πατά
; ο διάδρομος είναι δικά του, αλλά τα άλλα δύο του τετραγώνου 2x2 κάθε
; πλακιδίου τα ΑΓΓΙΖΕΙ χωρίς να τα κατέχει — εκεί μπορεί να είναι δομή, άλλος
; θόλος ή ένας διάδρομος που διασταυρώνεται. Ως το βήμα 39 το ob_draw_all
; κόστιζε 30-45 ms ακόμη κι όταν δεν έβρισκε τίποτα· από το ευρετήριο, μια
; σειρά είναι 10-15 ms, και βγαίνει ακόμη μία ανά γύρο (dirty_cost).
dh_crow:
        ld      hl,rv_pend
        dec     (hl)
        ld      hl,(dt_a)
        ld      (vr_tx),hl              ; vr_tx, vr_ty = dt_a, dt_b
        ld      hl,1 * 256 + 3
        ld      (vr_w),hl               ; 3 tiles x 1 σειρά
        call    vr_clip
        ret     z
        call    dt_ghost_rect
        ; ΧΩΡΙΣ ΕΔΑΦΟΣ (view_add): ο διάδρομος μόνο προσθέτει, και με το
        ; έδαφος πρώτα ό,τι ήδη φαινόταν στη λωρίδα — η στροφή, η γωνία του
        ; θόλου — έσβηνε για δύο-τρία καρέ ως να ξαναζωγραφιστεί.
        call    ob_draw_all
        jp      ob_clip_full

; --- αλλάζει tile (ορυχείο, μετεωρίτης): το tile ΚΑΙ οι τέσσερις γείτονες ---
; Το autotile του καθενός εξαρτάται από τους δικούς του γείτονες, οπότε ένα
; tile που αλλάζει κλάση αλλάζει και τις τέσσερις παραλλαγές γύρω του. Το 3x3
; τα πιάνει όλα με ένα ορθογώνιο αντί για πέντε — το ίδιο ορθογώνιο κόσμου
; (vr_*) με το εργοτάξιο και τη διαγώνιο. Ως το βήμα 53 είχε δικό του
; αντίγραφο του κοψίματος στο κάδρο.
; ΚΑΙ ΚΑΤΩ ΑΠΟ ΤΟ ΦΑΝΤΑΣΜΑ (βήμα 109), όπως το dh_crow: από το 109 το DK_TILE
; σβήνει και το σήμα μιας δομής που τελείωσε (st_built), και ο κέρσορας μένει
; πάνω της μετά την τοποθέτηση. Χωρίς το dt_ghost_rect το αρχείο του
; φαντάσματος κρατούσε το εργοτάξιο, και η επόμενη ανταλλαγή το έγραφε πίσω —
; όπως, από το βήμα 38, το έδαφος κάτω από έναν κρατήρα στο πλαίσιο του κέρσορα.
dh_tile:
        ld      hl,(dt_a)
        dec     l
        dec     h
        ld      (vr_tx),hl              ; ο γείτονας βορειοδυτικά
        ld      hl,3 * 256 + 3
        ld      (vr_w),hl
        call    vr_clip
        ret     z
        call    dt_ghost_rect
        call    vr_paint                ; το έδαφος, και το clip πάνω του
        call    dh_occupied
        call    fg_objs                 ; ή μόνο οι φιγούρες (βήμα 89)
        jp      ob_clip_full
