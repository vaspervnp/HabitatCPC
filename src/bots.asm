; bots.asm — τα ρομπότ βγαίνουν από το απόθεμα Bots (βήμα 92, §6.11)
;
; Ως το βήμα 90 τα έφερναν τα πλοία αποίκων, τρία στους οκτώ, και το βήμα 91
; το σταμάτησε: ο παίκτης διαλέγει ποιοι έρχονται. Η πηγή τους είναι πια η
; μηχανή robots, που φτιάχνει το απόθεμα Bots από μέταλλο, επεξεργαστές και
; βιοπλαστικό. Ο κανόνας είναι του παίκτη:
;
;   - ΜΟΝΟ ΤΟΥ, χωρίς κουμπί. Οσο το απόθεμα έχει ένα Bot και κάποια από τις
;     δεκαέξι θέσεις ρομπότ είναι ελεύθερη, ένα ρομπότ ξυπνά στο εργοστάσιο
;     με τη μηχανή robots και το απόθεμα πέφτει κατά ένα. Ενα ανά περιστροφή.
;   - ΚΑΤΑΣΚΕΥΗΣ ΚΑΙ ΜΕΤΑΦΟΡΑΣ, εναλλάξ: η ζυγή θέση κατασκευής, η μονή
;     μεταφοράς, οπότε ένα που λείπει το ξαναφέρνει η θέση του. Από το βήμα
;     94 ΓΕΩΤΡΥΠΑΝΟ πρώτα, όσο τα ορυχεία έχουν θέσεις χωρίς γεωτρύπανο —
;     τρεις το καθένα (dr_need, πιο κάτω· src/drill.asm).
;   - ΩΣ ΔΕΚΑΕΞΙ, ΕΚΤΟΣ ΤΑΒΑΝΙΟΥ. Οι θέσεις 80-95 (AG_BOT0, src/const.asm).
;
; ΖΕΙ ΣΤΗΝ ΤΡΑΠΕΖΑ 6, στη δέσμευση b6code κάτω από τα πεδία των πρακτόρων.
; Η τράπεζα 0 έχει 17 bytes ως το πάτωμα των δοκιμών και ο κώδικας της 2 δέκα·
; ο τροχός όμως έχει την 6 στο παράθυρο από την είσοδο ως την έξοδό του
; (src/wheel.asm), οπότε ό,τι τρέχει ΜΟΝΟ μέσα του μπορεί να ζει εκεί. Οσα
; καλεί από εδώ (jb_dome_ptr, sb_rest, και μέσα του ent_claim, fg_mark, wh_push)
; είναι στις τράπεζες 0 και 2 και, όπως κάθε πέρασμα του τροχού, αφήνουν την 6
; στο παράθυρο όταν γυρίζουν.

B6C_MAX     equ 5633                    ; = B6C_MAX του tools/pack.py· 5.815 ως το 171 με τον χάρτη των εισβολέων· 256 ως το βήμα 92, 1.280 ως το 93, 1.298 ως το 95, 1.554 ως το 109, 5.138 ως το 110, 5.063 ως το 113, 5.831 ως το 135, 5.767 ως το 151
M_ROBOTS    equ 5                       ; η μηχανή robots: η σειρά του MACH στο pack.py

        assert  F_ALIVE == 1 && RL_CARRY == RL_CBOT + 1 && (AG_BOT0 & 1) == 0
        assert  (G_room_n >> 8) == ((G_room_list + R_FACTORY * ROOM_MAX + ROOM_MAX - 1) >> 8)

; ---------------------------------------------------------------------------
; bot_tick — μία περιστροφή, στη θέση 15: το econ_events πηδά εδώ, και κάθε
; έξοδος πηδά στους εισβολείς (fo_tick, src/foe.asm, βήμα 111· ως τότε στο
; ship_tick, όπου πηδούν εκείνοι) αντί να γυρίσει. Χωρίς απόθεμα η θέση πληρώνει
; 10 us αντί για 16 με call / ret (μετρημένο: 299 -> 309), και από το βήμα 111
; άλλα 8 για την πόρτα των εισβολέων (304 -> 312, tests/test_trade.py).
; ---------------------------------------------------------------------------
bot_tick:
        ld      hl,(EC_STOCK + 2 * S_BOT)
        ld      a,h
        or      l
        jp      z,fo_tick               ; κανένα Bot στο απόθεμα
        ; Η ΠΡΩΤΗ ΕΛΕΥΘΕΡΗ ΘΕΣΗ, ξετυλιγμένα: 6 us η θέση αντί για 10 με το
        ; djnz. Με δεκαέξι ρομπότ και απόθεμα που μεγαλώνει (η μηχανή δεν
        ; σταματά μόνη της) αυτό πληρώνεται σε κάθε περιστροφή: 181 us με τον
        ; βρόχο, ~100 ξετυλιγμένο. Η τράπεζα 6 έχει τα bytes.
        ld      hl,G_agent_fields + AG_BOT0
        repeat  AG_NBOT
        bit     0,(hl)                  ; F_ALIVE
        jr      z,bt_fac
        inc     l
        rend
        jp      fo_tick                 ; δεκαέξι ρομπότ: το όριο
        ; --- το εργοστάσιο με τη μηχανή robots, από το ευρετήριο δωματίων ---
bt_fac:
        ld      de,G_room_n + R_FACTORY
        ld      a,(de)
        or      a
        jp      z,fo_tick               ; κανένα εργοστάσιο
        ld      b,a
        ld      e,(G_room_list + R_FACTORY * ROOM_MAX) & 255
bt_flp:
        push    bc
        push    de
        push    hl
        ld      a,(de)                  ; ο θόλος
        ld      (sb_tab),a              ; κόμβος και προορισμός του καινούργιου
        ld      (sb_tab + 2),a
        call    jb_dome_ptr             ; HL = η εγγραφή (src/jobs.asm)
        ld      de,D_MACH
        add     hl,de
        ld      bc,8                    ; και οι οκτώ: οι άδειες είναι NO_MACH
        ld      a,M_ROBOTS
        cpir                            ; Z: βρέθηκε
        pop     hl
        pop     de
        pop     bc
        jr      z,bt_make
        inc     e
        djnz    bt_flp
        jp      fo_tick                 ; κανένα με μηχανή robots
bt_make:
        ex      de,hl                   ; DE = η θέση
        ld      hl,(EC_STOCK + 2 * S_BOT)
        dec     hl
        ld      (EC_STOCK + 2 * S_BOT),hl
        ; ΓΕΩΤΡΥΠΑΝΟ ΑΝ ΤΟ ΘΕΛΟΥΝ ΤΑ ΟΡΥΧΕΙΑ (βήμα 94): τρεις θέσεις το καθένα,
        ; και όσες δεν έχουν ακόμη γεωτρύπανο (src/drill.asm). Αλλιώς όπως στο 92.
        call    dr_need                 ; κρατά το DE
        ld      a,RL_DRILL
        jr      c,bt_role
        ld      a,e                     ; ζυγή θέση: κατασκευής, μονή: μεταφοράς
        and     1
        add     a,RL_CBOT
bt_role:
        ex      de,hl
        ld      (hl),F_ALIVE + F_INDOORS ; μέσα, στο εργοστάσιο
        set     3,h                     ; AG_ROLE
        ld      (hl),a
        call    sb_rest                 ; τα υπόλοιπα, όπως ο άποικος (src/ship.asm)
        jp      fo_tick
; ---------------------------------------------------------------------------
; dr_need — (βήμα 94, src/drill.asm) CY αν τα ορυχεία έχουν θέση χωρίς ρομπότ
; γεώτρησης: MINE_OPS για κάθε έτοιμο ορυχείο, μείον τα ζωντανά γεωτρύπανα.
; Τα ορυχεία τα μέτρησε ο κύκλος ροής (EC_MINES, src/flow.asm), που ξανατρέχει
; μόλις τελειώσει ή γκρεμιστεί κτίσμα: το σάρωμα των 32 δομών εδώ έκανε το
; ξύπνημα 1.412 us αντί για 715. Από το bot_tick, με την 6 μέσα. Κρατά το DE.
; ---------------------------------------------------------------------------
dr_need:
        ld      a,(EC_MINES)
        or      a
        ret     z                       ; κανένα ορυχείο: NC, χωρίς το πέρασμα
        ld      c,a
        add     a,a
        add     a,c
        ld      c,a                     ; C = οι θέσεις
        ld      hl,AG_ROLE + AG_BOT0    ; οι ρόλοι
        ld      b,AG_NBOT
drn_bt:
        ld      a,(hl)
        cp      RL_DRILL
        jr      nz,drn_bn
        res     3,h                     ; AG_PG
        bit     0,(hl)                  ; F_ALIVE
        set     3,h
        jr      z,drn_bn
        dec     c                       ; μια θέση έχει πια το γεωτρύπανό της
drn_bn:
        inc     l
        djnz    drn_bt
        ; C = θέσεις - γεωτρύπανα, από -16 ως 144: CY αν είναι από 1 ως 144.
        ; Ως το βήμα 155 από -16 ως 96, και το cp #80 ως πρόσημο· με 48 δομές
        ; οι θέσεις φτάνουν τις 144, και τα αρνητικά είναι 240-255.
        ld      a,c
        dec     a
        cp      MAX_STRUCT * MINE_OPS
        ret

        assert  MAX_STRUCT * MINE_OPS + AG_NBOT < 256 && MINE_OPS == 3
bot_end:                                ; το τέλος των ρομπότ (tests/test_bots.py)
