; bots.asm — τα ρομπότ βγαίνουν από το απόθεμα Bots (βήμα 92, §6.11)
;
; Ως το βήμα 90 τα έφερναν τα πλοία αποίκων, τρία στους οκτώ, και το βήμα 91
; το σταμάτησε: ο παίκτης διαλέγει ποιοι έρχονται. Η πηγή τους είναι πια η
; μηχανή robots, που φτιάχνει το απόθεμα Bots από μέταλλο, επεξεργαστές και
; βιοπλαστικό. Ο κανόνας είναι του παίκτη:
;
;   - ΜΟΝΟ ΤΟΥ, χωρίς κουμπί. Οσο το απόθεμα έχει ένα Bot και κάποια από τις
;     δεκαέξι θέσεις ρομπότ είναι ελεύθερη, ένα ρομπότ ξυπνά στο εργοστάσιο
;     με τη μηχανή robots και το απόθεμα πέφτει κατά ένα. Ενα ανά περιστροφή.
;   - ΚΑΤΑΣΚΕΥΗΣ ΚΑΙ ΜΕΤΑΦΟΡΑΣ, εναλλάξ: η ζυγή θέση κατασκευής, η μονή
;     μεταφοράς, οπότε ένα που λείπει το ξαναφέρνει η θέση του. Κανένα
;     γεωτρύπανο: καμία εργασία Drill δεν δημοσιεύεται ακόμη (§6.7).
;   - ΩΣ ΔΕΚΑΕΞΙ, ΕΚΤΟΣ ΤΑΒΑΝΙΟΥ. Οι θέσεις 80-95 (AG_BOT0, src/const.asm).
;
; ΖΕΙ ΣΤΗΝ ΤΡΑΠΕΖΑ 6, στη δέσμευση b6code κάτω από τα πεδία των πρακτόρων.
; Η τράπεζα 0 έχει 17 bytes ως το πάτωμα των δοκιμών και ο κώδικας της 2 δέκα·
; ο τροχός όμως έχει την 6 στο παράθυρο από την είσοδο ως την έξοδό του
; (src/wheel.asm), οπότε ό,τι τρέχει ΜΟΝΟ μέσα του μπορεί να ζει εκεί. Οσα
; καλεί από εδώ (jb_dome_ptr, sb_rest, και μέσα του ent_claim, fg_mark, wh_push)
; είναι στις τράπεζες 0 και 2 και, όπως κάθε πέρασμα του τροχού, αφήνουν την 6
; στο παράθυρο όταν γυρίζουν.

B6C_MAX     equ 1280                    ; = B6C_MAX του tools/pack.py· 256 ως το βήμα 92
M_ROBOTS    equ 5                       ; η μηχανή robots: η σειρά του MACH στο pack.py

        assert  F_ALIVE == 1 && RL_CARRY == RL_CBOT + 1 && (AG_BOT0 & 1) == 0
        assert  (G_room_n >> 8) == ((G_room_list + R_FACTORY * ROOM_MAX + ROOM_MAX - 1) >> 8)

; ---------------------------------------------------------------------------
; bot_tick — μία περιστροφή, στη θέση 15: το econ_events πηδά εδώ, και κάθε
; έξοδος πηδά στο ship_tick αντί να γυρίσει. Χωρίς απόθεμα η θέση πληρώνει
; 10 us αντί για 16 με call / ret (μετρημένο: 299 -> 309).
; ---------------------------------------------------------------------------
bot_tick:
        ld      hl,(EC_STOCK + 2 * S_BOT)
        ld      a,h
        or      l
        jp      z,ship_tick             ; κανένα Bot στο απόθεμα
        ; Η ΠΡΩΤΗ ΕΛΕΥΘΕΡΗ ΘΕΣΗ, ξετυλιγμένα: 6 us η θέση αντί για 10 με το
        ; djnz. Με δεκαέξι ρομπότ και απόθεμα που μεγαλώνει (η μηχανή δεν
        ; σταματά μόνη της) αυτό πληρώνεται σε κάθε περιστροφή: 181 us με τον
        ; βρόχο, ~100 ξετυλιγμένο. Η τράπεζα 6 έχει τα bytes.
        ld      hl,G_agent_fields + AG_BOT0
        repeat  AG_NBOT
        bit     0,(hl)                  ; F_ALIVE
        jr      z,bt_fac
        inc     l
        rend
        jp      ship_tick               ; δεκαέξι ρομπότ: το όριο
        ; --- το εργοστάσιο με τη μηχανή robots, από το ευρετήριο δωματίων ---
bt_fac:
        ld      de,G_room_n + R_FACTORY
        ld      a,(de)
        or      a
        jp      z,ship_tick             ; κανένα εργοστάσιο
        ld      b,a
        ld      e,(G_room_list + R_FACTORY * ROOM_MAX) & 255
bt_flp:
        push    bc
        push    de
        push    hl
        ld      a,(de)                  ; ο θόλος
        ld      (sb_tab),a              ; κόμβος και προορισμός του καινούργιου
        ld      (sb_tab + 2),a
        call    jb_dome_ptr             ; HL = η εγγραφή (src/jobs.asm)
        ld      de,D_MACH
        add     hl,de
        ld      bc,8                    ; και οι οκτώ: οι άδειες είναι NO_MACH
        ld      a,M_ROBOTS
        cpir                            ; Z: βρέθηκε
        pop     hl
        pop     de
        pop     bc
        jr      z,bt_make
        inc     e
        djnz    bt_flp
        jp      ship_tick               ; κανένα με μηχανή robots
bt_make:
        ex      de,hl                   ; DE = η θέση
        ld      hl,(EC_STOCK + 2 * S_BOT)
        dec     hl
        ld      (EC_STOCK + 2 * S_BOT),hl
        ex      de,hl
        ld      (hl),F_ALIVE + F_INDOORS ; μέσα, στο εργοστάσιο
        ld      a,l                     ; ζυγή θέση: κατασκευής, μονή: μεταφοράς
        and     1
        add     a,RL_CBOT
        set     7,l
        ld      (hl),a
        call    sb_rest                 ; τα υπόλοιπα, όπως ο άποικος (src/ship.asm)
        jp      ship_tick
bot_end:                                ; το τέλος των ρομπότ (tests/test_bots.py)
