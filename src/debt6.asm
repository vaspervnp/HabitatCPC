; debt6.asm — το χρέος των εργοταξίων (βήμα 198, DESIGN §6.9), στην ουρά 3 των
; σελίδων πεδίων της τράπεζας 6, μετά το src/water.asm: χωρίς δικό του
; B6T_PIECE. Μόνο όπου υπάρχει το src/build.asm (το παιχνίδι, το uitest).

; ---------------------------------------------------------------------------
; db_own — η τιμή του (bd_metal), (bd_biop) στο χρέος (βήμα 198, EC_DEBT):
; ό,τι τοποθετείται (bd_link, src/build.asm) ή μπαίνει στο FIT (fit_set). Με
; την 6 μέσα, και οι δύο την έχουν ήδη. db_add8 — E = μέταλλο, D = βιοπλαστικό:
; και οι διάδρομοι ενός θόλου (cr_owe), που δεν περνούν τα 255 (12 πλακίδια
; το πολύ, 6 και 3 το καθένα). Byte byte, όπως ως το 197 το bd_stock_pay: στο
; bd_commit δεν κοστίζει περισσότερο από εκείνο (tests/test_place.py). Κρατά
; το BC.
; ---------------------------------------------------------------------------
db_own:
        ld      de,(bd_metal)           ; E = μέταλλο, D = βιοπλαστικό
db_add8:
        ld      hl,EC_DEBT
        ld      a,(hl)
        add     a,e
        ld      (hl),a
        inc     l
        ld      a,(hl)
        adc     a,0
        ld      (hl),a
        inc     l                       ; EC_DEBT + 2: το βιοπλαστικό
        ld      a,(hl)
        add     a,d
        ld      (hl),a
        inc     l
        ld      a,(hl)
        adc     a,0
        ld      (hl),a
        ret
        assert  (EC_DEBT & 255) <= 252
