; main.asm — το παιχνίδι, ολόκληρο, σε ένα binary.
;
; Ως το βήμα 12 τα δύο μισά ζούσαν χωριστά: το tests/uitest.asm έδενε τον
; renderer με το build mode, το tests/simtest.asm την οικονομία με τον τροχό,
; και ΚΑΝΕΝΑ δεν έδενε και τα δύο. Αυτό σημαίνει ότι το συνολικό μέγεθος
; κώδικα κάτω από το &4000 ήταν αμέτρητο και καμία κλήση από το ένα μισό στο
; άλλο δεν είχε ποτέ μεταγλωττιστεί.
;
; Ο ΒΡΟΧΟΣ. Ενα frame είναι: μία θέση τροχού, μία φέτα λίστας βρώμικων, ένα
; ui_tick. Ο τροχός είναι η προσομοίωση (§7.2), η λίστα είναι η οθόνη (§8.5)
; και το ui_tick είναι ο παίκτης (§9.1). Και τα τρία έχουν ταβάνι, οπότε το
; frame δεν μπορεί να ξεφύγει — αυτό είναι όλος ο κανόνας 1 του §7.1.

        buildsna
        bankset 0
        org     #0100
        run     start

        include "const.asm"
        include "../build/sprite_consts.asm"
        include "../build/layout.asm"

FLIPTAB     equ G_flip_mode0
HAS_DISC    equ 1                        ; το ui.asm δίνει S/L μόνο εδώ (§11)
HAS_SIM     equ 1                        ; ...και το C, που θέλει πλοία (§6.11)
HAS_VIEW    equ 1                        ; ...και το wh_hook γεμάτο από τη μεταγλώττιση

        ; Ο ΦΟΡΤΩΤΗΣ ΠΗΔΑ ΣΤΟ #0100 (src/boot.asm). Από το βήμα 83 εκεί είναι ένα
        ; jp, και αμέσως μετά οι χειριστές της διακοπής: πρέπει να είναι όλοι
        ; στην ίδια σελίδα (src/isr.asm), και εδώ είναι η μόνη θέση της τράπεζας
        ; 0 που δεν μετακινείται όταν αλλάζει κάτι άλλο.
        jp      start
        include "isr.asm"

start:
        di
        ld      sp,#0100
        ; --- η διακοπή των λωρίδων (src/isr.asm): το διάνυσμα, IM 1, το R7, και
        ; τα pens του κάδρου. Οι διακοπές μένουν κλειστές: τις ανοίγει ο βρόχος.
        ; Το «jp isr» γράφεται στο #0038 εδώ και όχι από τη μεταγλώττιση: ο
        ; δίσκος φορτώνει από το #0100, και κάτω από αυτό είναι ό,τι άφησε το
        ; firmware. (Ως το βήμα 102 το is_init, με μόνο αυτόν τον καλούντα.)
        ld      a,#C3                   ; jp
        ld      (IS_VEC),a
        ld      hl,is_vs
        ld      (IS_VEC + 1),hl
        im      1
        ld      bc,CRTC_SEL + 7
        out     (c),c
        ld      bc,CRTC_VAL + IS_R7
        out     (c),c
        ld      hl,G_palette_fw + 1
        ld      de,is_pal + 3
        ld      b,3
isi_lp: ld      a,(hl)
        inc     hl
        push    hl
        ld      hl,fw_to_hw
        add     a,l
        ld      l,a
        adc     a,h
        sub     l
        ld      h,a
        ld      a,(hl)
        or      GA_INK
        ld      (de),a
        inc     de
        pop     hl
        djnz    isi_lp
        call    hw_mode0
        call    hw_clear                ; ό,τι άφησε ο φορτωτής, φεύγει τώρα
        ld      hl,G_palette_fw
        call    pal_set
        ; Ο πλανήτης ζει στα τέσσερα bytes που άφησε η γεννήτρια στην τράπεζα 6
        ; (§5.7): τέσσερα pens εδάφους, τίποτε άλλο.
        call    ob_b6                   ; BC = GA_PORT + PAGE_B6
        ld      a,(G_worldinfo + 2)
        ld      c,PAGE_B1               ; το B είναι ακόμη GA_PORT >> 8
        out     (c),c
        call    pal_planet
        xor     a
        call    pal_border
        ; Ο renderer παρουσιάζεται στην προσομοίωση ΠΡΙΝ από την πρώτη εντολή:
        ; το wh_hook ξεκινά δείχνοντας στο dirty_push (src/wheel.asm, HAS_VIEW).
        ; Ως το βήμα 70 το έγραφαν δύο εντολές εδώ, έξι bytes για μια τιμή που
        ; δεν αλλάζει ποτέ.
        call    snd_init
        call    ov_install              ; ο κώδικας του GH_BUF στις τρύπες (βήμα 101)
        call    game_new
        ; fall through

; ---------------------------------------------------------------------------
; main_loop — ένα frame.
;
; ΟΛΑ ΜΕΣΑ, ΒΗΜΑ 71. Το ml_wheel, το ml_boom, το ml_over και το ml_hud ήταν
; ρουτίνες με μία κλήση η καθεμία: ένα call και ένα ret για κάτι που μπορεί να
; είναι ένα jr. Εμεινε ρουτίνα μόνο το ml_alert, που έχει τρεις εξόδους και που
; το tests/test_sound.py καλεί μόνο του.
; ---------------------------------------------------------------------------
main_loop:
        ; ΟΙ ΔΙΑΚΟΠΕΣ ΑΝΟΙΓΟΥΝ ΕΔΩ, ΣΕ ΚΑΘΕ FRAME (βήμα 83). Μία εντολή, και ό,τι
        ; τις έκλεισε (ο δίσκος, ένα probe των δοκιμών) δεν τις αφήνει κλειστές
        ; πάνω από ένα frame. Χωρίς αυτές δεν υπάρχουν λωρίδες Mode 1 (§8.1).
        ei
        ld      b,PPI_B >> 8            ; το C δεν μετρά: το PPI ακούει το A11
ml_low:
        in      a,(c)
        rra
        jr      c,ml_low
ml_high:
        in      a,(c)
        rra
        jr      nc,ml_high

        ; Ο ΤΡΟΧΟΣ: όσες θέσεις ζητά η ταχύτητα του παίκτη (§9.1). 0 = παύση.
        ;
        ; Η ΤΑΧΥΤΗΤΑ ΔΕΝ ΣΥΝΤΟΜΕΥΕΙ ΤΙΠΟΤΑ, κάνει περισσότερα ανά frame:
        ; τέσσερις θέσεις είναι τέσσερις φορές η δουλειά, όχι ένα πέρασμα που
        ; τρέχει γρηγορότερα. Ο κανόνας 1 του §7.1 λέει ότι το frame δεν
        ; ξεφεύγει· στο x4 ξεφεύγει, και αυτό είναι ΕΠΙΛΟΓΗ του παίκτη — η
        ; προσομοίωση προχωρά τετραπλάσια και η οθόνη χάνει frames.
        ;
        ; Ζει εδώ και όχι στο wheel.asm επειδή ο τροχός δεν ξέρει από παίκτη:
        ; το wheel_tick είναι «ένα frame προσομοίωσης» και η σύμβαση τράπεζας
        ; του μένει μία. Ποιος ρυθμός τρέχει είναι δουλειά του βρόχου.
        ld      a,(ui_spd)
        ld      b,a                     ; B = 0 και στην παύση: το θέλει το mt_boom
        or      a
        jr      z,ml_still
mlw_lp:
        push    bc
        call    wheel_tick
        pop     bc
        djnz    mlw_lp
ml_still:
        ; ΕΠΕΣΕ ΜΕΤΕΩΡΙΤΗΣ (src/meteor.asm). Ο ήχος της κρούσης παίζει από εδώ
        ; και όχι από τον τροχό, όπως κάθε ήχος της αποικίας (ml_alert): η
        ; προσομοίωση τρέχει και στο harness, που δεν έχει ήχο να του πει.
        ld      hl,mt_boom
        ld      a,(hl)
        or      a
        jr      z,ml_calm
        ld      (hl),b                  ; B = 0, από τον τροχό
        ld      a,SFX_METEOR
        call    snd_play
ml_calm:
        ; Η ΛΙΣΤΑ ΑΛΛΑΓΩΝ ΞΕΧΕΙΛΙΣΕ: ό,τι χάθηκε, το λέει μια πλήρης σχεδίαση.
        ;
        ; Το dirty_push ΣΗΚΩΝΕ αυτή τη σημαία από το βήμα 6a, με το σχόλιο «μια
        ; πλήρης επανασχεδίαση κοστίζει, αλλά λέει αλήθεια» — και κανείς δεν τη
        ; διάβαζε. Οσο ένα κτίριο που τελείωνε ξαναζωγράφιζε ολόκληρο το κάδρο,
        ; μια χαμένη αλλαγή σκεπαζόταν στο επόμενο κτίριο. Από το βήμα 34 το
        ; κτίριο που τελειώνει είναι ΚΙ ΑΥΤΟ εγγραφή της λίστας (DK_BUILT): αν
        ; χαθεί, ο θόλος μένει εργοτάξιο στην οθόνη ώσπου να περάσει η κάμερα
        ; από πάνω του.
        ld      a,(dirty_over)
        or      a
        jr      z,ml_kept
        call    dirty_reset
        call    ui_hide
        call    view_draw
        call    ui_show
ml_kept:
        ; ΤΟ HUD ΕΧΕΙ ΔΙΚΟ ΤΟΥ ΡΟΛΟΙ, και είναι ΠΡΑΓΜΑΤΙΚΟΣ χρόνος: κάθε 16
        ; frames, όχι κάθε περιστροφή τροχού. Δύο λόγοι, και οι δύο μετρημένοι:
        ;
        ;   Το `wh_slot == 0` δεν πατιέται πάντα. Με ταχύτητα 2 η θέση προχωρά
        ;   ανά δύο, και αν η ταχύτητα άλλαξε σε μονή θέση δεν γίνεται ΠΟΤΕ
        ;   μηδέν: το HUD πάγωνε ενώ η προσομοίωση έτρεχε.
        ;
        ;   Μία επανασχεδίαση HUD κοστίζει ΤΡΙΑ frames. Ανά περιστροφή, στο x4
        ;   αυτό είναι τρία frames στα εφτά — η «τετραπλή» ταχύτητα έβγαινε
        ;   2,3x. Με σταθερό ρολόι βγαίνει 3,4x και ο παίκτης βλέπει το HUD
        ;   κάθε 19 frames σε κάθε ταχύτητα, που είναι πιο συχνά από όσο
        ;   προλαβαίνει να διαβάσει.
        ;
        ; Στην παύση δεν ξαναγράφεται καθόλου: τίποτα δεν άλλαξε.
        ;
        ; ΤΟ ΦΑΝΤΑΣΜΑ ΔΕΝ ΑΓΓΙΖΕΤΑΙ. Το HUD ζει στις λωρίδες πάνω και κάτω από
        ; το κάδρο (§8.1) και το φάντασμα μέσα σε αυτό, άρα δεν πατά ο ένας τον άλλον· ένα ui_hide/ui_show
        ; εδώ έσβηνε τον κέρσορα για τρία frames κάθε 320 ms, που φαίνεται σαν
        ; να τρεμοπαίζει. Το hud_draw σταματά στη σειρά 2: τις 3-4 τις κρατά ο
        ; πίνακας, και ξέρει μόνος του πότε πρέπει να ξαναγραφούν (§9.2).
        ld      a,(ui_spd)
        or      a
        jr      z,ml_nohud
        ld      hl,ml_hudw
        dec     (hl)
        jr      nz,ml_nohud
        ld      (hl),16
        call    ml_alert                ; HL = ml_hudw
        call    hud_draw
        call    ui_panel                ; ξαναγράφει ΜΟΝΟ αν άλλαξε η υπογραφή
ml_nohud:
        call    snd_tick
        call    dirty_tick
        call    ui_tick
        jp      main_loop               ; (το tests/test_reveal.py κρεμιέται εδώ)

        ; Εδώ, και όχι με τα άλλα: ο πίνακας του in_read και το key_now θέλουν
        ; μία σελίδα, και εδώ δεν τα σπρώχνει τίποτα (src/input.asm, βήμα 66).
        include "input.asm"

; Τα τρία bytes του βρόχου, ΜΑΖΙ και με αυτή τη σειρά: το ml_alert τα βρίσκει με
; inc hl.
ml_hudw:    db 1                    ; αντίστροφη μέτρηση για το ρολόι του HUD

; ΤΡΕΙΣ ΚΛΗΣΕΙΣ ΑΝΑΜΟΝΗΣ για το ml_alert, μία ανά bit: το srl βγάζει 7, 3, 1
; και στην τέταρτη 0, που μένει 0.
ml_warm:    db 15

; Ξεκινά ΜΗΔΕΝ — «τα πράγματα είναι ήδη άσχημα», που είναι η αλήθεια του
; §10.1: η αποικία ξεκινά χωρίς ρεύμα. Ο πρώτος ηλιακός το κάνει 1, και από
; εκεί και πέρα η ακμή σημαίνει «κάτι χάλασε».
ml_alarm:   db 0

        assert  ml_warm == ml_hudw + 1 && ml_alarm == ml_warm + 1
        assert  (PPI_B & 255) == 0 && (GA_PORT & 255) == 0 && PAGE_B6 < 256

; ---------------------------------------------------------------------------
; ml_alert — ο συναγερμός ηχεί ΜΙΑ ΦΟΡΑ, στην ακμή. In: HL = ml_hudw.
;
; Το «δεν υπάρχει ρεύμα» είναι κατάσταση, όχι γεγονός: χωρίς ακμή θα χτυπούσε
; πενήντα φορές το δευτερόλεπτο όσο κρατά, δηλαδή θα ήταν συνεχής θόρυβος και
; θα έκρυβε ό,τι άλλο ακούγεται. Καλείται από το ρολόι του HUD, ανά 16 frames:
; ο παίκτης μαθαίνει τα άσχημα νέα μαζί με την οθόνη που τα δείχνει.
; ---------------------------------------------------------------------------
ml_alert:
        ; ΤΡΕΙΣ ΚΛΗΣΕΙΣ ΑΝΑΜΟΝΗΣ. Η οικονομία τρέχει σε μία θέση του τροχού και
        ; ως να τρέξει, τα «εντάξει» της είναι ό,τι άφησε το game_new: το ρεύμα
        ; λέει ναι, η πρώτη περιστροφή το κάνει όχι, και ΚΑΘΕ νέο παιχνίδι
        ; χτυπούσε συναγερμό στο πρώτο δευτερόλεπτο. Τρεις κλήσεις είναι ~1 s.
        inc     hl                      ; ml_warm
        srl     (hl)
        ret     nz
        ; Ο ΚΩΔΩΝΑΣ ΧΤΥΠΑ ΓΙΑ ΜΠΛΑΚΑΟΥΤ, ΟΧΙ ΓΙΑ ΠΕΣΙΜΟ ΦΟΡΤΙΟΥ. Το P_ESS (=2)
        ; σημαίνει «η υποστήριξη ζωής κρατά», δηλαδή ακριβώς αυτό που έπρεπε να
        ; γίνει· μια σειρήνα κάθε βράδυ θα ήταν θόρυβος. Το λέει η γραμμή του
        ; HUD. Γι' αυτό A = EC_O2OK μόνο όταν υπάρχει ρεύμα σε οποιαδήποτε
        ; στάθμη, και 0 στο μπλακάουτ. Το EC_O2OK είναι 0 ή 1 (src/econ.asm).
        ld      a,(EC_POK)
        or      a
        jr      z,mla_pok
        ld      a,(EC_O2OK)             ; 1 = όλα καλά
mla_pok:
        inc     hl                      ; ml_alarm
        cp      (hl)                    ; C ΜΟΝΟ για 1 -> 0: «μόλις χάλασε»
        ld      (hl),a
        ret     nc                      ; ίδιο, ή μόλις έφτιαξε — δεν χτυπάει
        ld      a,SFX_ALERT
        jp      snd_play

