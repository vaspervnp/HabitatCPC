; main.asm — το παιχνίδι, ολόκληρο, σε ένα binary.
;
; Ως το βήμα 12 τα δύο μισά ζούσαν χωριστά: το tests/uitest.asm έδενε τον
; renderer με το build mode, το tests/simtest.asm την οικονομία με τον τροχό,
; και ΚΑΝΕΝΑ δεν έδενε και τα δύο. Αυτό σημαίνει ότι το συνολικό μέγεθος
; κώδικα κάτω από το &4000 ήταν αμέτρητο και καμία κλήση από το ένα μισό στο
; άλλο δεν είχε ποτέ μεταγλωττιστεί.
;
; Ο ΒΡΟΧΟΣ. Ενα frame είναι: μία θέση τροχού, μία φέτα λίστας βρώμικων, ένα
; ui_tick. Ο τροχός είναι η προσομοίωση (§7.2), η λίστα είναι η οθόνη (§8.5)
; και το ui_tick είναι ο παίκτης (§9.1). Και τα τρία έχουν ταβάνι, οπότε το
; frame δεν μπορεί να ξεφύγει — αυτό είναι όλος ο κανόνας 1 του §7.1.

        buildsna
        bankset 0
        org     #0100
        run     start

        include "const.asm"
        include "../build/sprite_consts.asm"
        include "../build/layout.asm"

FLIPTAB     equ G_flip_mode0
HAS_DISC    equ 1                        ; το ui.asm δίνει S/L μόνο εδώ (§11)
HAS_SIM     equ 1                        ; ...και το C, που θέλει πλοία (§6.11)

start:
        di
        ld      sp,#0100
        call    hw_mode0
        call    hw_clear                ; ό,τι άφησε ο φορτωτής, φεύγει τώρα
        ld      hl,G_palette_fw
        call    pal_set
        ; Ο πλανήτης ζει στα τέσσερα bytes που άφησε η γεννήτρια στην τράπεζα 6
        ; (§5.7): τέσσερα pens εδάφους, τίποτε άλλο.
        ld      bc,GA_PORT + PAGE_B6
        out     (c),c
        ld      a,(G_worldinfo + 2)
        ld      bc,GA_PORT + PAGE_B1
        out     (c),c
        call    pal_planet
        xor     a
        call    pal_border
        ; Ο renderer παρουσιάζεται στην προσομοίωση: από εδώ και πέρα κάθε
        ; αλλαγή που φαίνεται σπρώχνεται στη λίστα βρώμικων (§8.5).
        ld      hl,dirty_push
        ld      (wh_hook),hl
        call    snd_init
        call    game_new
        ; fall through

; ---------------------------------------------------------------------------
; main_loop — ένα frame.
; ---------------------------------------------------------------------------
main_loop:
        ld      bc,PPI_B
ml_low:
        in      a,(c)
        rra
        jr      c,ml_low
ml_high:
        in      a,(c)
        rra
        jr      nc,ml_high
        call    ml_wheel
        ld      hl,mt_boom              ; έπεσε μετεωρίτης (src/meteor.asm)
        ld      a,(hl)
        or      a
        call    nz,ml_boom
        ld      a,(dirty_over)
        or      a
        call    nz,ml_over
        ; ΤΟ HUD ΕΧΕΙ ΔΙΚΟ ΤΟΥ ΡΟΛΟΙ, και είναι ΠΡΑΓΜΑΤΙΚΟΣ χρόνος: κάθε 16
        ; frames, όχι κάθε περιστροφή τροχού. Δύο λόγοι, και οι δύο μετρημένοι:
        ;
        ;   Το `wh_slot == 0` δεν πατιέται πάντα. Με ταχύτητα 2 η θέση προχωρά
        ;   ανά δύο, και αν η ταχύτητα άλλαξε σε μονή θέση δεν γίνεται ΠΟΤΕ
        ;   μηδέν: το HUD πάγωνε ενώ η προσομοίωση έτρεχε.
        ;
        ;   Μία επανασχεδίαση HUD κοστίζει ΤΡΙΑ frames. Ανά περιστροφή, στο x4
        ;   αυτό είναι τρία frames στα εφτά — η «τετραπλή» ταχύτητα έβγαινε
        ;   2,3x. Με σταθερό ρολόι βγαίνει 3,4x και ο παίκτης βλέπει το HUD
        ;   κάθε 19 frames σε κάθε ταχύτητα, που είναι πιο συχνά από όσο
        ;   προλαβαίνει να διαβάσει.
        ;
        ; Στην παύση δεν ξαναγράφεται καθόλου: τίποτα δεν άλλαξε.
        ld      a,(ui_spd)
        or      a
        jr      z,ml_nohud
        ld      hl,ml_hudw
        dec     (hl)
        jr      nz,ml_nohud
        ld      (hl),16
        call    ml_hud
ml_nohud:
        call    snd_tick
        call    dirty_tick
        call    ui_tick
        jp      main_loop

ml_hudw:    db 1                    ; αντίστροφη μέτρηση για το ρολόι του HUD

; ml_boom — HL = mt_boom. Ο ήχος της κρούσης παίζει από εδώ και όχι από τον
; τροχό, όπως κάθε ήχος της αποικίας (ml_alert): η προσομοίωση τρέχει και στο
; harness, που δεν έχει ήχο να του πει.
ml_boom:
        ld      (hl),0
        ld      a,SFX_METEOR
        jp      snd_play

; ---------------------------------------------------------------------------
; ml_wheel — όσες θέσεις τροχού ζητά η ταχύτητα του παίκτη (§9.1). 0 = παύση.
;
; Η ΤΑΧΥΤΗΤΑ ΔΕΝ ΣΥΝΤΟΜΕΥΕΙ ΤΙΠΟΤΑ, κάνει περισσότερα ανά frame: τέσσερις
; θέσεις είναι τέσσερις φορές η δουλειά, όχι ένα πέρασμα που τρέχει γρηγορότερα.
; Ο κανόνας 1 του §7.1 λέει ότι το frame δεν ξεφεύγει· στο x4 ξεφεύγει, και
; αυτό είναι ΕΠΙΛΟΓΗ του παίκτη — η προσομοίωση προχωρά τετραπλάσια και η
; οθόνη χάνει frames.
;
; Ζει εδώ και όχι στο wheel.asm επειδή ο τροχός δεν ξέρει από παίκτη: το
; wheel_tick είναι «ένα frame προσομοίωσης» και η σύμβαση τράπεζας του μένει
; μία. Ποιος ρυθμός τρέχει είναι δουλειά του βρόχου.
; ---------------------------------------------------------------------------
ml_wheel:
        ld      a,(ui_spd)
        or      a
        ret     z
        ld      b,a
mlw_lp:
        push    bc
        call    wheel_tick
        pop     bc
        djnz    mlw_lp
        ret

; ml_over — η λίστα αλλαγών ξεχείλισε: ό,τι χάθηκε, το λέει μια πλήρης σχεδίαση.
;
; Το dirty_push ΣΗΚΩΝΕ αυτή τη σημαία από το βήμα 6a, με το σχόλιο «μια πλήρης
; επανασχεδίαση κοστίζει, αλλά λέει αλήθεια» — και κανείς δεν τη διάβαζε. Οσο
; ένα κτίριο που τελείωνε ξαναζωγράφιζε ολόκληρο το κάδρο, μια χαμένη αλλαγή
; σκεπαζόταν στο επόμενο κτίριο. Από το βήμα 34 το κτίριο που τελειώνει είναι
; ΚΙ ΑΥΤΟ εγγραφή της λίστας (DK_BUILT): αν χαθεί, ο θόλος μένει εργοτάξιο στην
; οθόνη ώσπου να περάσει η κάμερα από πάνω του.
ml_over:
        call    dirty_reset
        call    ui_hide
        call    view_draw
        jp      ui_show

; ---------------------------------------------------------------------------
; ml_alert — ο συναγερμός ηχεί ΜΙΑ ΦΟΡΑ, στην ακμή.
;
; Το «δεν υπάρχει ρεύμα» είναι κατάσταση, όχι γεγονός: χωρίς ακμή θα χτυπούσε
; πενήντα φορές το δευτερόλεπτο όσο κρατά, δηλαδή θα ήταν συνεχής θόρυβος και
; θα έκρυβε ό,τι άλλο ακούγεται. Καλείται από το ρολόι του HUD, ανά 16 frames:
; ο παίκτης μαθαίνει τα άσχημα νέα μαζί με την οθόνη που τα δείχνει.
; ---------------------------------------------------------------------------
ml_alert:
        ; ΤΡΕΙΣ ΚΛΗΣΕΙΣ ΑΝΑΜΟΝΗΣ. Η οικονομία τρέχει σε μία θέση του τροχού και
        ; ως να τρέξει, τα «εντάξει» της είναι ό,τι άφησε το game_new: το ρεύμα
        ; λέει ναι, η πρώτη περιστροφή το κάνει όχι, και ΚΑΘΕ νέο παιχνίδι
        ; χτυπούσε συναγερμό στο πρώτο δευτερόλεπτο. Τρεις κλήσεις είναι ~1 s.
        ld      hl,ml_warm
        ld      a,(hl)
        or      a
        jr      z,mla_go
        dec     (hl)
        ret
mla_go:
        ; Ο ΚΩΔΩΝΑΣ ΧΤΥΠΑ ΓΙΑ ΜΠΛΑΚΑΟΥΤ, ΟΧΙ ΓΙΑ ΠΕΣΙΜΟ ΦΟΡΤΙΟΥ. Το P_ESS (=2)
        ; σημαίνει «η υποστήριξη ζωής κρατά», δηλαδή ακριβώς αυτό που έπρεπε να
        ; γίνει· μια σειρήνα κάθε βράδυ θα ήταν θόρυβος. Το λέει η γραμμή του
        ; HUD. Χωρίς αυτή τη χαρτογράφηση το `and` θα έβγαζε 2 AND 1 = 0.
        ld      a,(EC_POK)
        or      a
        jr      z,mla_pok
        ld      a,1
mla_pok:
        ld      hl,EC_O2OK
        and     (hl)                    ; 1 = όλα καλά
        ld      hl,ml_alarm
        cp      (hl)
        ld      (hl),a
        ret     z                       ; τίποτα δεν άλλαξε
        or      a
        ret     nz                      ; μόλις έφτιαξε — αυτό δεν χτυπάει
        ld      a,SFX_ALERT
        jp      snd_play

ml_warm:    db 3

; Ξεκινά ΜΗΔΕΝ — «τα πράγματα είναι ήδη άσχημα», που είναι η αλήθεια του
; §10.1: η αποικία ξεκινά χωρίς ρεύμα. Ο πρώτος ηλιακός το κάνει 1, και από
; εκεί και πέρα η ακμή σημαίνει «κάτι χάλασε».
ml_alarm:   db 0

; ml_hud — το HUD μία φορά ανά περιστροφή τροχού, δηλαδή ανά 320 ms.
;
; Ως τώρα ξαναγραφόταν μόνο σε ενέργεια του παίκτη: το νερό έπεφτε 60 -> 0 και
; η μπάρα δεν κουνιόταν.
;
; ΤΟ ΦΑΝΤΑΣΜΑ ΔΕΝ ΑΓΓΙΖΕΤΑΙ. Το HUD ζει στις γραμμές 160-199 και το φάντασμα
; στο κάδρο, άρα δεν πατά ο ένας τον άλλον· ένα ui_hide/ui_show εδώ έσβηνε τον
; κέρσορα για τρία frames κάθε 320 ms, που φαίνεται σαν να τρεμοπαίζει.
; Το hud_draw σταματά στη σειρά 2: τις 3-4 τις κρατά ο πίνακας, και ξέρει μόνος
; του πότε πρέπει να ξαναγραφούν (§9.2).
ml_hud:
        call    ml_alert
        call    hud_draw
        jp      ui_panel                ; ξαναγράφει ΜΟΝΟ αν άλλαξε η υπογραφή

