; crates.asm — τα κιβώτια του σκάφους (βήμα 181, DESIGN §10.1).
;
; Ο ΠΑΙΚΤΗΣ: «Να μπορώ να κάνω demolish το αρχικό πλοίο και να πάρω resources.
; Αυτά θα μένουν έξω για 10 sol και μετά θα εξαφανίζονται, αν δεν μπουν σε
; αποθήκη.» Διάλεξε (AskUserQuestion, 2026-11-04):
;
;   150 μέταλλο και 100 βιοπλαστικό·
;   το αμπάρι των 750 μένει (STORE_BASE)·
;   μόνο με ένα airlock έτοιμο και μια αποθήκη, αλλιώς η γραμμή λέει τι λείπει
;   (dm_can, src/demolish.asm)·
;   σωρός στη θέση του, που οι εργάτες κουβαλούν 10-10 στην αποθήκη, όπως το
;   μετάλλευμα ενός ορυχείου (src/haul.asm), και ό,τι μείνει σε 10 sol χάνεται.
;
; ΣΤΗΝ ΙΔΙΑ ΕΓΓΡΑΦΗ, τη δομή 0, και στον ίδιο κόμβο, με τις ακμές του: όσοι
; κρέμονταν από το σκάφος (LK_OWN) δεν χάνουν τη σύνδεσή τους, και ο μεταφορέας
; φτάνει εκεί όπως έφτανε στο σκάφος. Το dm_do τα στήνει (dm_ship, src/dm_ovl.asm):
; K_CRATES, το πλαίσιο του σκάφους (CR_BOX), ακεραιότητα 255, η λήξη στα κάτω
; έξι bits του ST_OPS, ο σωρός στο ST_OWED, και η πρώτη Haul.
;
; ΟΤΑΝ ΦΥΓΟΥΝ (cr_vanish) ΜΕΝΕΙ Ο ΚΟΜΒΟΣ: το ST_SIZE γίνεται CR_GONE, μια θέση του
; struct_dims με 0,0 — ούτε σχέδιο (ob_struct) ούτε αποτύπωμα (al_node, mt_scan)
; — και τα 2x2 tiles ελευθερώνονται. Ενας κόμβος χωρίς σχήμα, στη θέση του
; σκάφους, από τον οποίο περνούν οι δρόμοι που περνούσαν από εκεί, και η ρίζα
; όσων δεν έχουν γονιό (dm_up), όπως ήταν το σκάφος. Να γκρεμιστεί κι αυτός
; θα ήθελε να ξαναδεθούν όλα τα παιδιά του, και από πουθενά αλλού δεν είναι
; σίγουρο ότι δεν θα κρεμαστούν από ένα δικό τους.
;
; Στην τράπεζα 0, δίπλα στο src/haul.asm: η 2 δεν είχε χώρο ούτε μετά το βήμα
; 180. Ολα με την 6 στο παράθυρο.

; ---------------------------------------------------------------------------
; cr_arrive — το hl_arrive (src/haul.asm) για τα κιβώτια: ο μεταφορέας τους
; στέκεται στον κόμβο 64. Οπως από ορυχείο, ένα φορτίο από τον σωρό, με το
; αγαθό του: μέταλλο όσο ο σωρός που μένει είναι από CR_BIO και πάνω, μετά
; βιοπλαστικό. Το αγαθό στο J_SITE (#80 | απόθεμα) και στο spare, και η επόμενη
; Haul (cr_next). Χωριστά από του ορυχείου, που έτσι πληρώνει μόνο ένα cp· την
; παράδοση, στον προορισμό ή εδώ, την κάνει το hla_crd / hla_here (src/haul.asm).
; HL -> J_SITE. Z: φορτίο στον δρόμο· NZ: τίποτα, ή παραδόθηκε εδώ.
; ---------------------------------------------------------------------------
cr_arrive:
        ex      de,hl                   ; DE -> J_SITE
        ld      hl,G_struct_tbl + ST_OPS
        res     ST_HAUL,(hl)
        inc     hl                      ; ST_OWED: ο σωρός
        assert  ST_OWED == ST_OPS + 1
        ld      a,(hl)
        sub     HAUL_LOAD
        ret     c                       ; κάτω από φορτίο: NZ, το A δεν είναι 0
        ld      (hl),a
        cp      CR_BIO
        ld      c,S_METAL
        jr      nc,cra_take
        inc     c                       ; S_BIOPL
        assert  S_BIOPL == S_METAL + 1
cra_take:
        ex      de,hl
        dec     hl
        dec     hl                      ; J_AGENT
        push    bc
        ld      a,(jb_ag)
        ld      e,a
        call    sp_take                 ; src/supply.asm, όπως στο hl_arrive
        pop     bc
        ld      a,(hl)                  ; J_NODE
        inc     hl
        inc     hl
        inc     hl
        cp      (hl)                    ; ακόμη 64: καμία αποθήκη δεν φτάνεται
        ld      a,c
        jp      z,hla_here              ; src/haul.asm: το φορτίο παραδίδεται εδώ
        or      #80
        ld      (hl),a                  ; J_SITE: το αγαθό, για την παράδοση
        ld      a,c
        call    hla_sp                  ; spare: το αγαθό που κουβαλά
        call    cr_next                 ; η επόμενη Haul, ή φεύγουν
        xor     a                       ; Z
        ret

; ---------------------------------------------------------------------------
; cr_next — από το cr_arrive: ένα φορτίο έφυγε από τα κιβώτια, και ο
; μεταφορέας του έχει πια J_NODE τον προορισμό — το jp_hava δεν βρίσκει την
; εργασία του για διπλότυπη. Η επόμενη Haul αν μένει φορτίο, αλλιώς φεύγουν.
; Κρατά τον IX· χαλάει τους άλλους.
; ---------------------------------------------------------------------------
cr_next:
        push    ix
        ld      ix,G_struct_tbl         ; τα κιβώτια είναι πάντα η δομή 0
        call    hlp_pile                ; src/haul.asm: με σωρό από HAUL_LOAD, μία Haul
crn_end:
        ld      a,(ix+ST_OWED)
        cp      HAUL_LOAD
        call    c,cr_vanish               ; κάτω από φορτίο: άδεια
        pop     ix
        ret

; ---------------------------------------------------------------------------
; cr_sol — μία φορά ανά sol, από το ev_after (src/econ.asm) μετά το sol_rollover,
; όταν η δομή 0 έχει μέγεθος CR_BOX: τα κιβώτια είναι εκεί. Στο sol της λήξης
; ό,τι έμεινε χάνεται, και φεύγουν· αλλιώς μια Haul αν δεν υπάρχει — ο πίνακας
; εργασιών ήταν γεμάτος, ή ο τελευταίος μεταφορέας δεν βρήκε αποθήκη που να
; φτάνεται και το παρέδωσε εκεί. Κρατά τον IX.
; ---------------------------------------------------------------------------
cr_sol:
        push    ix
        ld      ix,G_struct_tbl
        ld      a,(EC_SOL)
        xor     (ix+ST_OPS)
        and     CR_SMASK
        jr      nz,crl_live
        ld      (ix+ST_OWED),a          ; A = 0: η λήξη
crl_live:
        call    hlp_pile
        jr      crn_end

; ---------------------------------------------------------------------------
; cr_vanish — τα κιβώτια φεύγουν. Το ST_SIZE γίνεται CR_GONE (struct_dims 0,0),
; τα 3x3 tiles γύρω από το κέντρο ξαναζωγραφίζονται χωρίς αυτά (st_redraw, το
; DK_TILE του src/meteor.asm), και τα 2x2 tiles του πλαισίου χάνουν την κατοχή
; τους (W_OCC_STRUCT), όπως τη σφράγισε το game_new για το σκάφος. Η 6 μέσα,
; και πίσω.
; ---------------------------------------------------------------------------
cr_vanish:
        ld      hl,G_struct_tbl + ST_SIZE
        ld      (hl),CR_GONE
        ld      a,MAX_DOME
        call    st_redraw               ; src/meteor.asm, b6code
        ; το πρώτο tile του πλαισίου, (cx - 2) / 2 και (cy - 2) / 2 (al_node), στο
        ; tile_addr: H = #40 + (y + 64) / 2, L = (y & 1) x 128 + x + 64
        ld      hl,(G_struct_tbl + ST_CX)       ; L = cx, H = cy
        assert  ST_CY == ST_CX + 1
        ld      a,l
        sub     2
        sra     a
        add     a,64
        ld      e,a                     ; x + 64
        ld      a,h
        sub     2
        sra     a
        add     a,64
        or      #80
        rra
        ld      h,a                     ; #40 | (y + 64) / 2
        sbc     a,a
        and     #80
        or      e
        ld      l,a
        ld      bc,GA_PORT + PAGE_B4
        out     (c),c
        ld      de,127
        res     4,(hl)                  ; W_OCC_STRUCT
        inc     hl
        res     4,(hl)
        add     hl,de                   ; η επόμενη σειρά
        res     4,(hl)
        inc     hl
        res     4,(hl)
        assert  W_OCC_STRUCT == 1 << 4
        ld      bc,GA_PORT + PAGE_B6
        out     (c),c
        ret
