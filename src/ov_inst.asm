; ov_inst.asm — ο εγκαταστάτης των κομματιών στις τρύπες (βήμα 155). Τρέχει
; ΜΙΑ φορά, στην εκκίνηση, από το GH_BUF: εκεί τον φέρνει το ov_install, η
; πρώτη γραμμή της εικόνας στο OV_LOAD (src/main.asm), που τρέχει στη θέση
; της στην τράπεζα 1. Από το GH_BUF, που φαίνεται πάντα, αλλάζει σελίδα χωρίς
; να σβήσει τον εαυτό του.
;
; ΤΡΕΙΣ ΠΕΡΙΟΧΕΣ (src/const.asm, DESIGN §4.2):
;   OV_R1 — βασική τράπεζα 1, #6000, 1 KB συνεχές: ό,τι έμεινε από τις
;           γραμμές των δομών του DIST όταν οι αποστάσεις τους πήγαν στο
;           μπλοκ (DB_ROW). Οι χειριστές της κατεδάφισης (τρέχουν εδώ), οι
;           γραμμές του tutorial και ο κώδικάς του. Ένα ldir.
;   OV_R2 — βασική τράπεζα 1, οι στήλες 112-127 των 64 γραμμών θόλων του
;           DIST: 64 τρύπες των 16. Το σώσιμο και η βοήθεια.
;   OV_R3 — τράπεζα 5, οι στήλες 112-127 των 112 γραμμών του NEXTHOP: 112
;           τρύπες των 16. Η κατεδάφιση. Η εικόνα είναι στην τράπεζα 1 και οι
;           τρύπες στην 5, που δεν φαίνονται μαζί: περνά από το ovi_buf, μετά
;           από αυτόν τον κώδικα, σε τρία κομμάτια (ovi_half· δύο μισά ως το
;           βήμα 158).
; Ως το βήμα 154 όλα ήταν στις στήλες 96-127 των 96 γραμμών του DIST, σε
; κομμάτια των 32, και το ov_install τα μοίραζε από τη σελίδα 2. Με 112
; κόμβους οι τρύπες έγιναν των 16, και οι 64 του DIST δεν τα χωρούν.
;
; Η ΕΙΚΟΝΑ ΔΕΝ ΣΒΗΝΕΙ Ο,ΤΙ ΘΑ ΔΙΑΒΑΣΕΙ: είναι στο OV_LOAD = DB_ROW, πάνω από
; κάθε τρύπα της τράπεζας 1. Το μπλοκ των δομών μένει με τα σκουπίδια της,
; όπως έμεναν ως το 154 οι γραμμές 72-95: το γράφει το rt_flush πριν το
; διαβάσει κανείς. Γυρίζει με την 1.
; ---------------------------------------------------------------------------
ovi_go:
        ld      hl,OVI_R1
        ld      de,OV_R1
        ld      bc,R1_LEN
        ldir                            ; το HL στο OVI_R2
        ld      de,OV_R2
        ld      a,R2_UNITS
        call    ovi_sp                  ; το HL στο OVI_R3
        ld      de,OV_R3
        call    ovi_half                ; το πρώτο τρίτο
        call    ovi_half                ; το δεύτερο, και το τρίτο πέφτει από κάτω
; ovi_half — OVI_CH κομμάτια του OV_R3: από την εικόνα (HL, τράπεζα 1) στο
; ovi_buf, και από εκεί στις τρύπες (DE, τράπεζα 5). ΣΕ ΤΡΙΑ ΚΟΜΜΑΤΙΑ, γιατί
; πάνω από το ovi_buf είναι η αποικία δοκιμών (src/colony.asm) και ο κώδικας
; της εκκίνησης (src/startup.asm, βήμα 158), που τρέχει αυτή τη στιγμή και
; μετά από εδώ το game_new: ολόκληρη η κατεδάφιση στο ovi_buf θα τους έσβηνε
; (assert στο src/main.asm). Ως το βήμα 157 σε δύο μισά, με την αποικία στην
; τελευταία σελίδα. Το τρίτο ret γυρίζει σε όποιον κάλεσε το ov_install.
ovi_half:
        push    de
        ld      de,ovi_buf
        ld      bc,OVI_CH * OV_UNIT
        ldir
        pop     de
        push    hl
        ld      bc,GA_PORT + PAGE_B5
        out     (c),c
        ld      hl,ovi_buf
        ld      a,OVI_CH
        call    ovi_sp
        ld      bc,GA_PORT + PAGE_B1
        out     (c),c
        pop     hl
        ret

; ovi_sp — A κομμάτια των 16 από το HL, ένα σε κάθε γραμμή των 128 από το DE.
ovi_sp:
        ld      bc,OV_UNIT
        ldir
        ex      de,hl
        ld      bc,128 - OV_UNIT
        add     hl,bc
        ex      de,hl
        dec     a
        jr      nz,ovi_sp
        ret
ovi_buf:                                ; τα assert στο src/main.asm, μετά το OV_R3
