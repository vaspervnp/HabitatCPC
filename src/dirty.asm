        jp      ob_clip_full

; dh_occupied — πατάει κάτι το ορθογώνιο td_*; NZ αν ναι. Σελιδοποιεί την
; τράπεζα 4, όπου ζει ο κόσμος, και γυρίζει στην 1.
;
; Χωρίς αυτό, ΚΑΘΕ αλλαγή εδάφους πλήρωνε ολόκληρο το πέρασμα αντικειμένων —
; 99.840 us για ένα tile που έσκαψε ένα ρομπότ στην ερημιά. Τα bits κατοχής
; του §3.5 υπάρχουν ακριβώς για να μη χρειάζεται να ρωτηθεί η λίστα θόλων.
dh_occupied:
        ld      a,W_OCC_MASK
; dh_occ_a — A = ποια bits κατοχής μετρούν. Η φιγούρα έξω (βήμα 89) ρωτά μόνο
; το W_OCC_STRUCT: το μονοπάτι είναι θεμέλιο στο έδαφος, κανένα αντικείμενο.
dh_occ_a:
        ld      (dho_mask + 1),a
        ld      bc,GA_PORT + PAGE_B4
        out     (c),c
        ld      a,(td_nr)
        ld      e,a                     ; E = σειρές
        ld      a,(cam_ty)
        ld      hl,td_r0
        add     a,(hl)
        ld      d,a                     ; D = η σειρά του κόσμου
dho_row:
        ld      a,(cam_tx)
        ld      hl,td_c0
        add     a,(hl)
        ld      b,a
        ld      c,d
        call    tile_addr               ; DE μένει
        ld      a,(td_nc)
        ld      b,a
dho_col:
        ld      a,(hl)
dho_mask:
        and     #30                     ; bits κατοχής (dh_occ_a)
        jr      nz,dho_out
        inc     hl
        djnz    dho_col
        inc     d
        dec     e
        jr      nz,dho_row              ; στο τέλος Z: όλο ελεύθερο
dho_out:
        ld      bc,GA_PORT + PAGE_B1
        out     (c),c                   ; οι σημαίες μένουν
        ret

; dk_clamp — A = αρχή, C = μήκος, B = όριο κάδρου. Το μήκος ήταν πάντα 3
; ως το βήμα 34· το view_rect το θέλει όσο το κτίριο ή ο διάδρομος.
; Out: NZ, C = αρχή κομμένη, B = πλήθος· Z = εκτός κάδρου (και μήκος 0).
; Κρατά το HL.
dk_clamp:
        bit     7,a
        jr      z,dkc_pos
        ; αρνητική αρχή: κόψε από μπροστά
        neg
        ld      e,a
        ld      a,c
        sub     e
        jr      c,dkc_out
        jr      z,dkc_out
        ld      c,a
        xor     a
dkc_pos:
        ld      d,a                     ; αρχή
        add     a,c
        cp      b
        jr      c,dkc_ok
        ld      a,b
        sub     d
        jr      c,dkc_out
        jr      z,dkc_out
        ld      c,a
dkc_ok:
        ld      b,c
        ld      c,d
        inc     b
        dec     b                       ; Z: μήκος μηδέν, εκτός κάδρου όπως πριν
        ret
dkc_out:
        xor     a                       ; Z: οι δρόμοι προς τα εδώ δεν το εγγυώνται
        ret

