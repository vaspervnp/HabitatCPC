; ---------------------------------------------------------------------------
; rise6.asm — η πρόοδος ενός εργοταξίου όσο έρχονται τα φορτία του (βήμα 200,
; DESIGN §6.9). Στην ουρά των σημαδιών (B6T_0, βήμα 199): τρέχει με την 6 στο
; παράθυρο, από το sp_arrive (src/supply.asm). Στο simtest, στο uitest και στο
; objtest δίπλα στο src/supply6.asm.
;
; Η ΑΚΕΡΑΙΟΤΗΤΑ ΕΙΝΑΙ ΤΟ ΜΕΡΙΔΙΟ ΠΟΥ ΕΦΤΑΣΕ. Ως το βήμα 199 ένα εργοτάξιο είχε
; ακεραιότητα 0 όσο περίμενε υλικά, και ο χτίστης την ανέβαζε μετά (ja_build,
; src/jobs.asm). Τώρα κάθε φορτίο την ανεβάζει ως εκεί που λέει το μερίδιο:
;
;       p' = p + (255 - p) / (όσα μένουν + 1)
;
; που δίνει 255 x k / N μετά από k από τα N, χωρίς να ξέρει το N (το ST_OWED
; λέει μόνο όσα μένουν), και ξεκινά σωστά από όπου κι αν είναι: ένα σώσιμο του
; βήματος 199 με εργοτάξιο στη μέση έχει 0, και φαίνεται από το επόμενο φορτίο.
; Με το τελευταίο γίνεται 0 ξανά, για τον χτίστη. Το ob_rise (src/rise0.asm)
; τη διαβάζει μόνο όσο το εργοτάξιο χρωστά· ο μετεωρίτης την αφήνει τότε
; (mt_site, στην ουρά 1: src/full6.asm), όπως άφηνε το 0 της.
; ---------------------------------------------------------------------------

; sp_dlv — στη θέση του ld (hl),a / and c του sp_arrive: HL -> το byte του
; υλικού που χρωστιέται, A = η νέα του τιμή, DE -> το άλλο υλικό (θόλος) ή το
; ίδιο byte (δομή), C = η μάσκα (#FF θόλος, #F0 ή #0F δομή). Γράφει το A, και
; γυρίζει με τα HL, DE, A και τις σημαίες του and c· χαλάει το BC. Στο
; παιχνίδι, πριν γυρίσει, ένα DK_RSIZE και ένα DK_RECT στη λίστα αλλαγών: οι
; σειρές που φάνηκαν τις βρίσκει ο χειριστής, έξω από τον τροχό (dh_rise).
sp_dlv:
        ld      (hl),a
        and     c
        push    af
        push    de
        push    hl
        inc     c                       ; Z: θόλος
        ld      a,(de)
        jr      nz,sdl_st
        add     a,(hl)                  ; D_POWER + D_OPS
        jr      sdl_n
sdl_st:
        ld      b,a                     ; ST_OWED: μέταλλο<<4 | βιοπλαστικό
        and     15
        ld      c,a
        xor     b
        rrca
        rrca
        rrca
        rrca
        add     a,c
sdl_n:
        res     0,l
        dec     l                       ; -> D_INTEG = ST_INTEG
        ld      d,(hl)                  ; η πρόοδος πριν
        or      a
        jr      z,sdl_set               ; το τελευταίο: 0, για τον χτίστη
        ; (255 - p) / (όσα μένουν + 1), με ολίσθηση: οκτώ γύροι, ~90 us όσο κι αν
        ; είναι το πηλίκο. Με αφαίρεση ήταν ως 127 γύροι, 640 us, στη θέση 13 του
        ; τροχού (tests/test_install.py). Το υπόλοιπο στο A μένει κάτω από τον
        ; διαιρέτη, άρα το rla δεν χάνει bit όσο αυτός είναι ως 128.
        inc     a
        ld      b,a                     ; ο διαιρέτης
        ld      a,255
        sub     d
        ld      e,a                     ; ο διαιρετέος, και το πηλίκο στο τέλος
        xor     a
        ld      c,8
sdl_dv:
        sla     e
        rla
        cp      b
        jr      c,sdl_d0
        sub     b
        inc     e
sdl_d0:
        dec     c
        jr      nz,sdl_dv
        ld      a,e
        add     a,d
sdl_set:
        ld      (hl),a
        ifdef   HAS_VIEW
        ld      e,a
        ld      hl,9
        add     hl,sp
        ld      a,(hl)                  ; ο κόμβος: το push af του sp_arrive
        call    sdl_view                ; src/rise0.asm: δύο εγγραφές στη λίστα
        endif
        pop     hl
        pop     de
        pop     af
        ret
        ; το res 0,l / dec l: οι εγγραφές σε όρια του 8, χωρίς όριο σελίδας μέσα
        assert  D_INTEG == 5 && D_POWER == 6 && D_OPS == 7 && ST_INTEG == 5 && ST_OWED == 7
        assert  (G_dome_tbl & 7) == 0 && (DOME_REC & 7) == 0 && (G_struct_tbl & 7) == 0 && STRUCT_REC == 8
