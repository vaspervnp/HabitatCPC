; fight0.asm — ο φρουρός αφήνει την ανάγκη για τη μάχη (βήμα 150, DESIGN §6.10)
;
; Η ΑΠΟΦΑΣΗ ΤΟΥ ΠΑΙΚΤΗ: ο φρουρός μέσα στη βάση αφήνει κάθε ανάγκη για τη μάχη,
; ως να πέσει ο τελευταίος εισβολέας (fo_over: NO_TASK). Εξω το T_NEED λέει
; «πάω μέσα» — για τη στολή, ή για μια ανάγκη που μόνο μέσα δίνεται
; (src/suit.asm): εκείνο μένει, αλλιώς η στολή αδειάζει στη μάχη.
;
; Ως το βήμα 149 όποιος πήγαινε για ανάγκη δεν πολεμούσε. Μετρημένο στο
; tools/play.py, οκτώ κόσμοι επί 120 sol: σε 83 επιδρομές οι φρουροί ήταν στη
; μάχη το 98% του χρόνου και για ανάγκη το 2%, ποτέ κρίσιμη (κάτω από 16). Η
; σφαγή του βήματος 147 ήρθε όταν τελείωσε το νερό: διψούσαν όλοι, και οι οκτώ
; φρουροί πήγαιναν στο κυλικείο.
;
; ΟΙ ΑΝΑΓΚΕΣ ΔΕΝ ΧΡΕΙΑΖΟΝΤΑΙ ΚΑΝΕΝΑΝ ΕΛΕΓΧΟ. Ενας φρουρός στη μάχη με ανάγκη κάτω
; από 64 παίρνει T_NEED και τον δρόμο για το δωμάτιο στις θέσεις 8-10, αλλά η
; θέση 15 τρέχει πριν από την κίνηση (0-7) και τον ξαναστέλνει στη μάχη: δεν
; κάνει ούτε βήμα προς το κυλικείο. Ενα «πολεμά;» στην αρχή του nd_search το
; πλήρωνε ΚΑΘΕ άποικος που ψάχνει δωμάτιο, 16 us ο καθένας: η χειρότερη φέτα
; αναγκών του tests/test_noroom.py 4.490 -> 4.620 us, πάνω από το ταβάνι της.
;
; ΣΤΗΝ ΤΡΑΠΕΖΑ 0: το b6code είχε 1 byte. Το καλεί το fo_guard (src/foe.asm), με
; την 6 στο παράθυρο.

; fg_need — από το fo_guard: A = η εργασία του φρουρού, L = ο φρουρός | 128.
; Γυρίζει εκεί αν πάει στη μάχη. Αν πάει για ανάγκη έξω, τελειώνει και το
; fo_guard. Χαλάει DE.
fg_need:
        cp      T_NEED
        ret     nz
        ld      d,AG_PG
        ld      e,l
        res     7,e
        ld      a,(de)                  ; οι σημαίες του
        and     F_INDOORS
        ret     nz                      ; μέσα: η μάχη πρώτα
        pop     de                      ; έξω: πάει μέσα
        ret
