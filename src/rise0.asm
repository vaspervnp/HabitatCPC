; ---------------------------------------------------------------------------
; rise0.asm — το εργοτάξιο που υψώνεται από κάτω (βήμα 200, DESIGN §6.9): ό,τι
; ζωγραφίζει, στην τράπεζα 0. Ο παίκτης: «μέχρι να πάνε όλα να φαίνεται
; γραμμή παρά γραμμή το κτήριο».
;
; Ενα εργοτάξιο που χρωστά ακόμη φορτία (θόλος: D_POWER | D_OPS, δομή: ST_OWED)
; δείχνει μόνο τις κάτω H x p / 256 γραμμές του πλαισίου του, όπου H το ύψος
; του πλαισίου και p η ακεραιότητά του — που όσο έρχονται τα φορτία είναι το
; μερίδιο που έφτασε (sp_dlv, src/rise6.asm), και με το τελευταίο γίνεται 0 για
; τον χτίστη. Από πάνω μένει ό,τι ήταν: το έδαφος. Οταν δεν χρωστά τίποτα
; φαίνεται ολόκληρο, όπως ως το βήμα 199, και οι ρίγες του st_mark μένουν ως
; να τελειώσει ο μηχανικός.
;
; ΤΟ ΚΟΨΙΜΟ ΕΙΝΑΙ ΤΟ clip_y0: ανεβαίνει ως την πρώτη γραμμή που φαίνεται, για
; ό,τι ζωγραφίζει από εκεί και πέρα αυτός που κάλεσε (το κέλυφος, το εικονίδιο,
; η δομή), και ξαναπέφτει όταν εκείνος γυρίσει: το obr_go βάζει το ob_fall στη
; θέση της επιστροφής του. Οι αρμοί και οι φιγούρες δεν κόβονται.
; ---------------------------------------------------------------------------

; ob_rise — από το ob_shell και το ob_ricon, για θόλο σε κατάσταση 1, με το
; d_rec και το πλαίσιο (ob_getdome, ob_vis). Τράπεζα 6, που μένει.
ob_rise:
        ld      hl,(d_rec+D_POWER)      ; και το D_OPS: φορτία που χρωστά
        ld      a,h
        or      l
        ret     z                       ; κανένα: ολόκληρος
        ld      a,(d_qh)
        add     a,a
        ld      c,a                     ; το ύψος του πλαισίου
        ld      a,(d_rec+D_INTEG)
        ld      hl,(d_fy)
        ld      de,ob_fall
        ; fall through

; obr_go — A = p, C = H, HL = η πάνω γραμμή του πλαισίου (16 bits, με
; πρόσημο), DE = πού γυρίζει η ζωγραφική του καλούντος. Αν οι γραμμές που
; κρύβονται πέφτουν μέσα στο clip, το clip_y0 ανεβαίνει και ο καλών συνεχίζει
; με το DE για επιστροφή· αλλιώς απλώς γυρίζει. Η πρώτη γραμμή που φαίνεται
; έξω από το 0-255: πάνω από την οθόνη τα κρυμμένα δεν φαίνονται έτσι κι
; αλλιώς, και κάτω από αυτήν ούτε το κτίριο.
obr_go:
        push    de
        push    hl
        call    ob_mul                  ; H = οι γραμμές που φαίνονται (κρατά το C)
        ld      a,c
        sub     h                       ; όσες κρύβονται από πάνω
        pop     hl
        call    ob_addu                 ; HL = η πρώτη που φαίνεται
        ld      a,(clip_y0)
        ld      (ob_cy0),a
        inc     h
        dec     h
        jr      nz,obr_no
        cp      l
        jr      nc,obr_no               ; το clip αρχίζει πιο κάτω: δεν κόβεται τίποτα
        ld      a,l
        ld      (clip_y0),a             ; πάνω από το clip_y1 κόβει τα πάντα (ob_clip)
        pop     de
        pop     hl                      ; η συνέχεια του καλούντος
        push    de                      ; και η επιστροφή του, στο DE
        jp      (hl)
obr_no:
        pop     de
        ret

; ob_ricon — το εικονίδιο ενός θόλου που είναι εργοτάξιο (ob_fittings).
ob_ricon:
        call    ob_rise
        jp      ob_icon

; ob_fallm — της δομής: το clip πίσω, και οι ρίγες ολόκληρες (το st_mark
; μέσα στο ob_struct τις έκοψε όπως τη δομή).
ob_fallm:
        ld      hl,st_mark
        push    hl
; ob_fall — το clip_y0 πίσω. Χαλάει μόνο το A.
ob_fall:
        ld      a,(ob_cy0)
        ld      (clip_y0),a
        ret

; ---------------------------------------------------------------------------
; os_site — από το ob_struct, για κατάσταση κάτω από DS_ACTIVE: A = η κατάσταση,
; HL -> ST_STATE, το s_rec με τα πέντε πρώτα. Η άδεια θέση γυρίζει από το
; ob_struct (το ret z του ως το βήμα 199)· ένα εργοτάξιο που χρωστά παίρνει το
; κόψιμο, με το πλαίσιο που θα βρει το ob_struct: κέντρο μείον το μισό ύψος.
; Τράπεζα 6.
; ---------------------------------------------------------------------------
os_site:
        or      a
        jr      z,oss_none
        ld      a,(ob_meas)
        or      a
        ret     nz                      ; το ευρετήριο θέλει όλο το πλαίσιο
        inc     hl
        ld      c,(hl)                  ; ST_INTEG
        inc     hl
        inc     hl
        ld      a,(hl)                  ; ST_OWED
        or      a
        ret     z                       ; δεν χρωστά: ολόκληρη, με τις ρίγες
        ld      a,(s_rec+ST_KIND)
        add     a,a
        add     a,a
        ld      hl,s_rec+ST_SIZE
        add     a,(hl)
        add     a,a
        inc     a
        ld      hl,G_struct_dims
        call    ob_addu
        ld      b,(hl)                  ; το ύψος του πλαισίου
        ld      a,(s_rec+ST_CY)
        call    ob_sy                   ; κρατά το BC
        ld      a,b
        srl     a
        call    ob_subu
        ld      a,c
        ld      c,b
        ld      de,ob_fallm
        jr      obr_go
oss_none:
        pop     af
        ret
        assert  ST_INTEG == ST_STATE + 1 && ST_OWED == ST_STATE + 3
        assert  D_POWER == D_INTEG + 1 && D_OPS == D_POWER + 1

        ifdef   HAS_VIEW
; sdl_view — από το sp_dlv (src/rise6.asm), στον τροχό: A = ο κόμβος, D, E = η
; πρόοδος πριν και μετά. Δύο εγγραφές στη λίστα αλλαγών: DK_RSIZE με (μετά,
; πριν) και DK_RECT με (κόμβος, RISE_TY). Το DH_RECT βλέπει το RISE_TY και
; πηγαίνει στο dh_rise (src/rise1.asm), που βρίσκει τις σειρές και τις
; ξαναζωγραφίζει. ΟΧΙ ΕΔΩ: το al_node και τα δύο ob_mul των σειρών ήταν ~500
; us στη θέση 13 του τροχού. Το ζευγάρι μένει μαζί όπως της κατεδάφισης (το
; DK_RSIZE πρώτο σε πέρασμα, src/dirty.asm).
sdl_view:
        ld      b,e
        ld      c,d
        ld      e,a
        ld      a,DK_RSIZE
        call    dirty_push              ; κρατά B, C, E
        ld      b,e
        ld      c,RISE_TY
        ld      a,DK_RECT
        jp      dirty_push
        endif

ob_cy0:     db 0                        ; το clip_y0 πριν από το obr_go
