; carry.asm — τα αγαθά του εμπόρου κουβαλιούνται (βήμα 98, DESIGN §6.11).
;
; Ως το βήμα 97 η ανταλλαγή γινόταν στο FIRE: τα αποθέματα άλλαζαν και ο
; έμπορος έφευγε αμέσως. Οι αποφάσεις του παίκτη, όπως στο Planetbase:
;
;   - ΟΠΩΣ ΤΑ ΕΡΓΟΤΑΞΙΑ (βήμα 88). Οσα δίνεις φεύγουν από τα αποθέματα στο
;     FIRE· όσα παίρνεις μπαίνουν μόνο όταν φτάσει κάθε φορτίο σε αποθήκη ή
;     στο σκάφος.
;   - Ο ΕΜΠΟΡΟΣ ΠΕΡΙΜΕΝΕΙ όσο χρειαστεί, ώσπου να κουβαληθούν όλα, και μετά
;     φεύγει. Το μισό sol ισχύει μόνο χωρίς συμφωνία.
;   - ΚΟΥΒΑΛΑ ΟΠΟΙΟΣΔΗΠΟΤΕ, όπως την τροφοδοσία: κάθε άποικος και τα ρομπότ
;     μεταφοράς (job_roles #5F).
;
; ΤΙ ΧΡΩΣΤΙΕΤΑΙ, ΣΤΑ BYTES ΤΟΥ ΕΜΠΟΡΟΥ, που σώζονται ήδη (βήμα 93): μετά τη
; συμφωνία (tr_deal, src/lines.asm) το EC_SHKIND γίνεται SK_DEALT — η γραμμή
; του δεν ξανανοίγει, μία ανταλλαγή ανά επίσκεψη — το EC_SHETA #FFFF (4.096
; sol: το ship_tick δεν τον διώχνει), το EC_MARKUP τα φορτία που οφείλονται
; ΣΤΟΝ έμπορο, και οι ποσότητες του EC_CARGO όσα πήρες και είναι ακόμη στο
; πλοίο του. Ενα φορτίο είναι ως TRADE_LOAD μονάδες ενός αγαθού.
;
; ΤΟ ΦΟΡΤΙΟ ΕΙΝΑΙ ΤΗΣ ΕΡΓΑΣΙΑΣ, στο J_SITE της (src/const.asm), και η πίστα
; είναι το EC_PADNODE. Ενας μεταφορέας που πεινά, κουράζεται ή πεθαίνει αφήνει
; την εργασία (jb_reap), και ο επόμενος συνεχίζει με ό,τι κουβαλούσε — το
; jb_reap δεν τη γυρίζει πίσω, όπως και τη Haul (src/jobs.asm). Στον πράκτορα
; θα χανόταν.
;
; Ο ΓΥΡΟΣ (tr_arrive). Οπως η Supply, ο πράκτορας πάει πρώτα στην
; κοντινότερη αποθήκη ή στο σκάφος (sp_take, από το jb_take), και από εκεί:
;
;   ΣΕ ΑΠΟΘΗΚΗ   ένα φορτίο του εμπόρου μπαίνει στα αποθέματα (με ταβάνι)·
;                παίρνει ένα για τον έμπορο αν οφείλεται κάποιο, και πάει στην
;                πίστα — και άδειος, αν μένει κάτι στο πλοίο του. Ενα για τον
;                έμπορο που αφέθηκε στη μέση συνεχίζει για την πίστα.
;   ΣΤΗΝ ΠΙΣΤΑ   ό,τι φέρνει μένει εκεί· παίρνει ένα φορτίο από το πλοίο αν
;                μένει, και πάει στην κοντινότερη αποθήκη ή στο σκάφος — και
;                άδειος, αν οφείλονται κι άλλα στον έμπορο.
;
; Ετσι κάθε ταξίδι κουβαλά και προς τις δύο μεριές. Χωρίς αποθήκη ή σκάφος που
; να φτάνεται, το φορτίο παραδίδεται στην πίστα, όπως της μεταφοράς.
;
; ΟΤΑΝ ΔΕΝ ΜΕΝΕΙ ΤΙΠΟΤΑ από καμία μεριά η εργασία τελειώνει, και ο έμπορος
; φεύγει αν δεν μένει άλλη που να κουβαλά (tra_bye).
;
; ΧΩΡΙΣ ΠΙΣΤΑ — ένας μετεωρίτης τη ρίχνει, και ως να ξαναχτιστεί το πέρασμα
; δωματίων (src/needs.asm) γράφει EC_PADNODE = 255 — όποιος πάει προς τα εκεί
; μένει όπου είναι, με την εργασία και το φορτίο της, και ξαναρωτά σε κάθε
; πέρασμα. Ο κόμβος 255 δεν υπάρχει.

        assert  J_NODE == 1 && J_AGENT == 2 && J_SITE == 4 && JOB_REC == 5
        assert  TRADE_N < 16 && TRADE_LOAD < 16 && TRADE_GIVE < #10
        assert  (G_agent_fields & 255) == 0 && MER_SLOTS * 2 == 8

; ---------------------------------------------------------------------------
; tr_arrive — από το jb_arrive (src/jobs.asm): ο πράκτορας (jb_ag) μιας J_TRADE
; στέκεται στο J_NODE της, C. HL -> η εργασία. Η 6 στο παράθυρο.
; Out: Z       πάει αλλού, και η εργασία μένει δική του
;      NZ, NC  δεν μένει τίποτα: η εργασία τελειώνει (και ίσως φεύγει ο έμπορος)
; ---------------------------------------------------------------------------
tr_arrive:
        ld      de,J_SITE
        add     hl,de                   ; HL -> J_SITE: το φορτίο της
        ld      a,(EC_PADNODE)
        cp      c
        jr      z,tra_pad
tra_store:
        ; --- σε αποθήκη ή στο σκάφος ---
        ld      a,(hl)
        cp      TRADE_GIVE
        jr      z,tra_go                ; για τον έμπορο, αφημένο στη μέση
        jr      c,tra_e                 ; άδεια
        push    hl                      ; ένα του εμπόρου: στα αποθέματα
        ld      c,a
        rrca
        rrca
        rrca
        rrca
        and     15
        ld      e,a
        ld      d,0                     ; DE = ποσότητα
        ld      a,c
        and     15                      ; το απόθεμα
        call    ec_add_stock            ; src/stock.asm, με ταβάνι
        pop     hl
tra_e:  ld      (hl),0
        ld      a,(EC_MARKUP)           ; φορτία που οφείλονται στον έμπορο
        sub     1
        jr      c,tra_g0
        ld      (EC_MARKUP),a
        ld      (hl),TRADE_GIVE
        jr      tra_go
tra_g0: push    hl                      ; μένει κάτι στο πλοίο του;
        ld      hl,EC_CARGO + 1
        ld      b,MER_SLOTS
        xor     a
trl_lp: or      (hl)
        inc     hl
        inc     hl
        djnz    trl_lp
        pop     hl
        jr      z,tra_bye
tra_go: ld      a,(EC_PADNODE)
        inc     a
        ret     z                       ; η πίστα έπεσε (μετεωρίτης): περιμένει εδώ
        dec     a
        dec     hl
        dec     hl
        dec     hl                      ; J_NODE
        ld      (hl),a
        ld      hl,(jb_ag)
        ld      h,AG_PG + 2
        ld      (hl),a                  ; dest
        xor     a                       ; Z
        ret

tra_pad:
        ; --- στην πίστα: ό,τι φέρνει μένει εδώ, και ένα φορτίο από το πλοίο:
        ; από την πρώτη θέση με κάτι ακόμη, ως TRADE_LOAD μονάδες ---
        push    hl
        ld      hl,EC_CARGO
        ld      b,MER_SLOTS
trk_lp: ld      c,(hl)                  ; απόθεμα
        inc     hl
        ld      a,(hl)                  ; όσα μένουν
        or      a
        jr      nz,trk_got
        inc     hl
        djnz    trk_lp
        pop     hl
        ld      a,(EC_MARKUP)
        or      a
        jr      z,tra_bye               ; τίποτα από καμία μεριά
        xor     a                       ; άδειος, για ένα φορτίο του εμπόρου
        jr      tra_tk
trk_got:
        ld      b,a
        sub     TRADE_LOAD
        jr      nc,trk_st
        xor     a                       ; ως ένα φορτίο: όλα
trk_st: ld      (hl),a                  ; όσα μένουν μετά
        sub     b
        neg                             ; το φορτίο
        add     a,a
        add     a,a
        add     a,a
        add     a,a
        or      c
        pop     hl
tra_tk: ld      (hl),a                  ; J_SITE: το φορτίο
        push    hl
        dec     hl
        dec     hl                      ; J_AGENT
        ld      a,(jb_ag)
        ld      e,a
        call    sp_take                 ; src/supply.asm: J_NODE, dest. Z: καμία
        pop     hl
        jp      z,tra_store             ; καμία πηγή δεν φτάνεται: εδώ
        xor     a                       ; Z
        ret

; tra_bye — η εργασία τελειώνει. Οι άλλες J_TRADE χωρίς πράκτορα και χωρίς
; φορτίο σβήνουν· αν δεν μένει καμία άλλη, ο έμπορος φεύγει: EC_SHETA = 0, και
; το ship_tick τον παίρνει στην επόμενη περιστροφή. Out: NZ, NC.
tra_bye:
        ld      hl,G_job_tbl
        ld      de,JOB_REC
        ld      bc,MAX_JOB * 256        ; C = όσες μένουν, μαζί με αυτή
trb_lp: ld      a,(hl)
        cp      J_TRADE
        jr      nz,trb_n
        push    hl
        inc     hl
        inc     hl
        ld      a,(hl)                  ; J_AGENT
        inc     hl
        inc     hl
        inc     a
        jr      nz,trb_on               ; κάποιος την κρατά
        or      (hl)                    ; J_SITE: κουβαλά κάτι, αφημένο
trb_on: pop     hl
        jr      nz,trb_kp
        ld      (hl),NO_JOB             ; ανοιχτή και άδεια: δεν χρειάζεται
        db      #3E                     ; ld a,n: προσπερνά το inc c
trb_kp: inc     c
trb_n:  add     hl,de
        djnz    trb_lp
        dec     c                       ; αυτή
        jr      nz,trb_out
        ld      h,c
        ld      l,c
        ld      (EC_SHETA),hl           ; 0: φεύγει
trb_out:
        or      1                       ; NZ, NC
        ret
