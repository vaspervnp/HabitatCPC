; top.asm — ΤΟ ΟΡΙΟ ΣΑΡΩΣΗΣ ΤΩΝ ΔΟΜΩΝ (βήμα 157, DESIGN §4.2).
;
; Με 48 θέσεις (βήμα 156) κάθε πέρασμα του πίνακα πλήρωνε και τις άδειες: 18 us
; η καθεμία ο κύκλος ροής, 20 το rooms_rebuild σε κάθε περιστροφή, 15 το
; ευρετήριο, 9 ο κέρσορας, 50 το sp_sweep, και μία μοναχική πηγή της
; δρομολόγησης. Οι αποικίες γεμίζουν τον πίνακα από κάτω (το bdk_find δίνει την
; πρώτη άδεια θέση), οπότε πάνω από την ψηλότερη θέση σε χρήση δεν υπάρχει
; τίποτα: ΕΚΕΙ σταματούν.
;
; ST_TOP είναι αυτή η θέση + 1, στρογγυλεμένη πάνω σε ζυγό — ο κέρσορας
; περπατά ανά δύο θέσεις — και πάντα τουλάχιστον 2. Ποτέ δεν κατεβαίνει μέσα
; σε ένα παιχνίδι: μια κατεδάφιση αφήνει απλώς μια άδεια θέση από κάτω, όπως
; αφήνει και στη μέση. Ετσι δεν κατεβαίνει και το rt_n, και καμία γραμμή της
; δρομολόγησης κάτω από αυτό δεν μένει μπαγιάτικη ενώ κάποιος στέκεται εκεί.
; Οι μορφές του, και ποιος τις διαβάζει, στο src/const.asm.
;
; ΠΟΙΟΣ ΤΟ ΓΡΑΦΕΙ. Μόνο το st_set, από δύο μέρη:
;   το st_recount (src/wheel.asm), στο τέλος του wheel_reset: μετρά τον πίνακα
;     από πάνω (st_count, src/flow.asm, με την 6). Το wheel_reset τρέχει στην
;     αρχή κάθε παιχνιδιού — και της αποικίας δοκιμών — και μετά από κάθε
;     φόρτωμα, οπότε ούτε το game_new ούτε το σώσιμο χρειάζονται κάτι δικό
;     τους, και ένα σώσιμο πριν από το βήμα 157 φορτώνει.
;   το st_raise, από το al_commit (src/commit.asm), μετά από κάθε bd_commit:
;     μια δομή στη θέση ST_TOP ή πιο πάνω το ανεβάζει.
; Οι δοκιμές που γράφουν τον πίνακα μόνες τους καλούν το st_recount.
;
; ΖΕΙ ΣΤΟ OV_R1, στη βασική τράπεζα 1, όπως οι χειριστές του src/dm_hand.asm:
; τρέχει εκεί που είναι, με την 1 στο παράθυρο. Η τράπεζα 2 είχε ένα byte, το
; b1code 43 και το b6code 48· το OV_R1 183.
; ---------------------------------------------------------------------------

; st_set — A = ST_TOP (ζυγό, 2-48): οι πέντε μορφές, και το rt_n — η
; δρομολόγηση τρέχει τις πηγές ως το ST_TEND. Χαλάει A, B, HL.
st_set:
        ld      hl,ST_TOP
        ld      (hl),a
        ld      b,a
        rrca                            ; ζυγό: ακριβώς το μισό
        dec     hl
        ld      (hl),a                  ; ST_THALF
        dec     hl
        ld      a,b
        add     a,MAX_DOME
        ld      (hl),a                  ; ST_TEND
        ld      (rt_n),a
        ld      a,b
        sub     16 + 1
        jr      nc,sts_hi
        xor     a
sts_hi:
        inc     a                       ; ST_TOP - 16, ή 1 ως τις 16
        ld      hl,ST_THI
        ld      (hl),a
        dec     hl
        ld      (hl),0                  ; ST_TZERO
        ret
        assert  ST_THALF == ST_TEND + 1 && ST_TOP == ST_TEND + 2
        assert  ST_TZERO == ST_THI - 1

; st_raise — από το al_commit, μετά από κάθε bd_commit: αν η νέα δομή είναι
; στη θέση ST_TOP ή πιο πάνω, το όριο ανεβαίνει ως αυτήν, και η δρομολόγηση
; ξαναρχίζει για να περάσει και από τη νέα πηγή. Ενας θόλος δεν το αγγίζει.
; Χαλάει AF, B, HL.
st_raise:
        ld      a,(bd_node)
        sub     MAX_DOME
        ret     c                       ; θόλος
        ld      hl,ST_TOP
        cp      (hl)
        ret     c                       ; κάτω από το όριο: όπως ήταν
        add     a,2
        and     #FE                     ; θέση + 1, ζυγό
        call    st_set
        jp      rt_mark
