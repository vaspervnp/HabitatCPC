; ---------------------------------------------------------------------------
; menugeom.asm — η γεωμετρία της οθόνης του μενού και της φόρτωσης (βήμα 130,
; DESIGN §13.2). Τη μοιράζονται τρία προγράμματα που δεν βλέπουν το ένα τα
; σύμβολα του άλλου — το src/menu.asm (MENU.BIN, ζωγραφίζει), ο φορτωτής
; (src/boot.asm, γεμίζει τη μπάρα των αρχείων) και η γεννήτρια (src/gen.asm,
; γεμίζει τη δική της) — και το tools/menuworld.py, που τη διαβάζει από εδώ για
; την αναφορά των δοκιμών. Μόνο αριθμοί και + - * , ώστε να τη διαβάζει και η
; Python.
;
; MODE 0, η οθόνη στο #C000 χωρίς μετατόπιση (τη μηδενίζει το SCR SET MODE).
; «Χαρακτήρας» = 2 bytes x 8 γραμμές, η γραμματοσειρά 3x5 του παιχνιδιού
; (font_gfx): 40 στήλες, 25 σειρές.
; ---------------------------------------------------------------------------

MW_ORG      equ #4000       ; το MENU.BIN, στη βασική RAM: το πατούν μετά η
                            ; PAGE2.BIN και η BANK1.BIN, και το επίμετρο σβήνει
                            ; ό,τι μένει (src/boot.asm)
MW_N        equ 32          ; οι κόσμοι (tools/menuworld.py): δύναμη του 2, ο
                            ; φορτωτής διαλέγει με ld a,r · and MW_N - 1
MW_COLS     equ 20          ; το κομμάτι του κόσμου, σε tiles των 4 bytes x 16
MW_ROWS     equ 13          ; γραμμών· η 13η μισή (200 = 12 x 16 + 8)

; Ο τίτλος: κελιά του ενός byte και δύο γραμμών (tools/menuworld.py).
TITLE_X     equ 25          ; byte
TITLE_Y     equ 12          ; γραμμή

; Ο υπότιτλος, σε μαύρη λωρίδα χωρίς πλαίσιο.
SUB_COL     equ 8
SUB_ROW     equ 4
SUB_W       equ 24

; Το πάνελ: πλαίσιο στην πένα 4, μέσα μαύρο. Μία σειρά ψηλότερο από το βήμα
; 149, για την έκτη γραμμή: ως τότε από τη 11, 13 σειρές.
PNL_COL     equ 7
PNL_ROW     equ 10
PNL_W       equ 26
PNL_H       equ 14

; Το μενού μέσα στο πάνελ.
CHO_COL     equ 13          ; CHOOSE A WORLD
CHO_ROW     equ 11
OPT_COL     equ 8           ; οι γραμμές, η διαλεγμένη ανάποδα σε
OPT_ROW     equ 13          ; όλο το OPT_W
OPT_W       equ 24
OPT_N       equ 6           ; πέντε ως το βήμα 148· η έκτη το TUTORIAL (βήμα 149)
DSC_COL     equ 9           ; η περιγραφή της διαλεγμένης
DSC_ROW     equ 20
DSC_W       equ 23
KEY_COL     equ 9           ; τα πλήκτρα
KEY_ROW     equ 22

; Η φόρτωση, στο ίδιο πάνελ.
NAM_COL     equ 9           ; ο κόσμος που διάλεξε
NAM_ROW     equ 13
LOD_COL     equ 9           ; LOADING
LOD_ROW     equ 15
WLD_COL     equ 9           ; BUILDING THE WORLD: σβηστό (πένα 4) ως τη
WLD_ROW     equ 19          ; γεννήτρια, αναμμένο (πένα 5) από εκεί
WLD_W       equ 18

; Η μπάρα: ΜΙΑ για όλη την αναμονή. Τα αρχεία γεμίζουν τα πρώτα BAR_FILES
; bytes (ο φορτωτής, ανάλογα με τους τομείς τους), η γεννήτρια τα υπόλοιπα
; BAR_GEN, ένα ανά τέσσερις σειρές του κόσμου. Το γέμισμα είναι οι γραμμές
; 1-6 της χαρακτηρο-σειράς BAR_ROW, το πλαίσιο οι 0 και 7 και ένα byte
; αριστερά και δεξιά.
BAR_ROW     equ 17
BAR_X0      equ 18          ; το πρώτο byte του γεμίσματος
BAR_FILES   equ 12
BAR_GEN     equ 32          ; 128 σειρές / 4
BAR_W       equ BAR_FILES + BAR_GEN
BAR_INK     equ #F0         ; πένα 5 και στα δύο pixels
BAR_SCR     equ #C000 + BAR_ROW * 80 + BAR_X0
