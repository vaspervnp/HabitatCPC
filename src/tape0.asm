; ΜΕ ΤΗ ΣΕΙΡΑ ΤΗΣ ΠΛΗΡΟΥΣ ΣΧΕΔΙΑΣΗΣ. Ενας θόλος-εργοτάξιο: κέλυφος, αρμοί,
; εικονίδιο, ΚΟΡΔΕΛΑ, φιγούρες στον δακτύλιο (ob_fittings) — οι άποικοι
; πατούν πάνω της, και στον μικρό θόλο οι θέσεις 3 και 4 πέφτουν στην αριστερή
; πλευρά. Μια δομή-εργοτάξιο: το σχέδιό της, το σήμα, ΚΟΡΔΕΛΑ (st_mark). Οσοι
; ξαναζωγραφίζουν ένα κομμάτι ακολουθούν την ίδια σειρά: ο αρμός ενός νέου
; διαδρόμου (dh_conn) ξαναβάζει κορδέλα και φιγούρες από πάνω του.
