; os_mark — η ουρά του st_mark (src/figure.asm): το σήμα, και η κορδέλα της
; δομής. Με την 6, και πίσω.
os_mark:
        call    ob_mark
        ld      hl,tk_struct
        jr      tk_go

; ob_tapef — θόλος-εργοτάξιο στο d_rec, με το πλαίσιό του: η κορδέλα, και οι
; φιγούρες του δακτυλίου από πάνω της (ob_figures). Με την 6, και πίσω.
ob_tapef:
        ld      hl,ob_figures
        push    hl
        ld      hl,tk_dome
tk_go:
        ld      bc,GA_PORT + PAGE_B1
        out     (c),c
        ld      de,ob_b6
        push    de
        jp      (hl)
