; hw.asm — gate array: mode, ROM, παλέτα
;
; Το `palette_fw` των assets δίνει **firmware** colour numbers (0..26). Ο gate
; array θέλει **hardware** τιμές. Η μετάφραση δεν υπάρχει στα assets — είναι
; δουλειά της μηχανής, και ζει εδώ.

; ---------------------------------------------------------------------------
; hw_mode0 — Mode 0, και τα δύο ROM εκτός. Από εδώ και πέρα η μνήμη είναι δική μας.
; ---------------------------------------------------------------------------
hw_mode0:
        ld      bc,GA_PORT + RMR_MODE0
        out     (c),c
        ret

; ---------------------------------------------------------------------------
; hw_clear — και οι 16 KB της οθόνης στο pen 0.
;
; Χρειάζεται επειδή πριν από το παιχνίδι στην οθόνη υπάρχει ΚΑΤΙ ΑΛΛΟ: από τον
; δίσκο είναι η οθόνη φόρτωσης του boot.asm, και πριν από αυτήν το «Ready» του
; BASIC. Χωρίς σβήσιμο, το `run"habitat` φαινόταν γραμμένο πάνω στην αποικία ως
; την πρώτη πλήρη σχεδίαση — φάνηκε σε screenshot, σε καμία δοκιμή.
; ---------------------------------------------------------------------------
hw_clear:
        ld      hl,SCR_BASE
        ld      de,SCR_BASE + 1
        ld      bc,#4000 - 1
        ld      (hl),0
        ldir
        ret

; ---------------------------------------------------------------------------
; pal_set — στήνει και τα 16 pens από πίνακα firmware αριθμών.
; In:  HL = 16 bytes, pen 0..15
; ---------------------------------------------------------------------------
pal_set:
        ld      e,0                 ; pen
ps_loop:
        ld      a,(hl)
        inc     hl
        push    hl
        call    pal_pen
        pop     hl
        inc     e
        ld      a,e
        cp      16
        jr      nz,ps_loop
        ret

; ---------------------------------------------------------------------------
; pal_pen — ΕΝΑ pen. In: E = pen 0..15, A = firmware χρώμα 0..26.
; Χαλάει A, BC, HL. Κρατά το DE.
; ---------------------------------------------------------------------------
pal_pen:
        ld      hl,fw_to_hw
        ld      d,0
        push    de
        ld      e,a
        add     hl,de
        ld      a,(hl)              ; hardware τιμή
        pop     de
        or      GA_INK
        ld      b,a                 ; κρατάμε το χρώμα
        ld      a,e
        or      GA_PEN
        ld      c,a
        ld      a,b
        ld      b,GA_PORT/256
        out     (c),c               ; επιλογή pen
        ld      c,a
        out     (c),c               ; τιμή χρώματος
        ret

; ---------------------------------------------------------------------------
; pal_planet — ο πλανήτης, από την πλευρά της οθόνης. In: A = 0..3.
;
; Υπάρχει μόνο όπου είναι γνωστή η διάταξη των assets: το tests/blittest.asm
; δοκιμάζει τους πυρήνες σχεδίασης με σκέτο const.asm και δεν έχει πίνακα
; πλανητών να δείξει.
;
; Ενα σετ tiles, τέσσερα χρώματα (SPRITES.md, planet_pens): τα ίδια bytes
; νερού διαβάζονται ως πάγος, το ίδιο έδαφος ως ρηγόλιθος. ΜΟΝΟ τα pens
; 7, 11, 12, 14 — τα 1-6 είναι οι δομές και τα 8, 9, 10, 13, 15 τα εικονίδια,
; και ένα έδαφος που πατούσε επάνω τους θα έσβηνε ό,τι κάθεται πάνω του.
; ---------------------------------------------------------------------------
        ifdef G_planet_pens
pal_planet:
        and     3
        add     a,a
        add     a,a                 ; x4
        ld      l,a
        ld      h,0
        ld      de,G_planet_pens
        add     hl,de
        ld      de,pal_terrain
        ld      b,4
pp_lp:
        ld      a,(de)
        push    bc
        push    de
        push    hl
        ld      e,a                 ; το pen
        ld      a,(hl)              ; το χρώμα του πλανήτη
        call    pal_pen
        pop     hl
        pop     de
        pop     bc
        inc     hl
        inc     de
        djnz    pp_lp
        ret

pal_terrain: db 7, 11, 12, 14
        endif

; ---------------------------------------------------------------------------
; pal_border — χρώμα περιγράμματος από firmware αριθμό στον A.
; ---------------------------------------------------------------------------
pal_border:
        ld      hl,fw_to_hw
        ld      e,a
        ld      d,0
        add     hl,de
        ld      a,(hl)
        or      GA_INK
        ld      b,GA_PORT/256
        ld      c,GA_BORDER
        out     (c),c
        ld      c,a
        out     (c),c
        ret

; firmware colour number -> hardware τιμή (χωρίς το bit #40)
; 27 χρώματα· ό,τι είναι πάνω από 26 δεν υπάρχει.
; Τα 27 χρώματα firmware -> τιμές gate array. ΟΙ ΤΡΕΙΣ ΤΕΛΕΥΤΑΙΕΣ ΗΤΑΝ ΛΑΘΟΣ
; από το βήμα 1 ως το 17, και δύο από αυτές ήταν σε χρήση: το pen 6 (άποικοι)
; ζητά 24 bright yellow και έβγαινε #10 = σκούρο μπλε, το pen 5 ζητά 26 bright
; white και έβγαινε #01 = γκρίζο λευκό. Καμία δοκιμή δεν τα έπιανε, επειδή όλες
; συγκρίνουν ΑΡΙΘΜΟΥΣ PEN — τα golden PNG παράγονται από τον ίδιο πίνακα pen,
; όχι από το χρώμα που βγάζει το υλικό. Το tests/test_palette.py κοιτά πια το
; χρώμα.
fw_to_hw:
        db  #14,#04,#15,#1C,#18,#1D,#0C,#05,#0D
        db  #16,#06,#17,#1E,#00,#1F,#0E,#07,#0F
        db  #12,#02,#13,#1A,#19,#1B,#0A,#03,#0B
