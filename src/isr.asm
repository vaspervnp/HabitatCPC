; isr.asm — η διακοπή: δύο σπασίματα οθόνης ανά frame (DESIGN §8.1, βήμα 83).
;
; Η ΟΘΟΝΗ ΕΙΝΑΙ ΤΡΙΑ ΚΟΜΜΑΤΙΑ, δύο mode και δύο παλέτες:
;
;   γραμμές   0- 15   πάνω λωρίδα του HUD   Mode 1, pens λωρίδας
;   γραμμές  16-175   το κάδρο              Mode 0, η παλέτα του παιχνιδιού
;   γραμμές 176-199   κάτω λωρίδα του HUD   Mode 1, pens λωρίδας
;
; Ο Gate Array αλλάζει mode στο επόμενο HSYNC μετά την εγγραφή και χρώμα
; αμέσως. Τα σύνορα είναι δύο ΚΕΝΕΣ γραμμές, η 15 (η γραμμή 7 του γλύφου, που
; δεν τη χρησιμοποιεί κανένας χαρακτήρας) και η 176 (η πρώτη της κάτω λωρίδας,
; που μένει μαύρη): σε κενή γραμμή ούτε το mode ούτε τα pens 1-3 φαίνονται, οπότε
; κάθε σπάσιμο έχει ~88 us να γίνει αντί για τα ~24 του δεξιού περιθωρίου.
; Αλλάζουν ΜΟΝΟ τα pens 1-3: το pen 0 είναι μαύρο και στις δύο παλέτες, και το
; Mode 1 δεν βλέπει τα 4-15.
;
; ΠΟΤΕ ΧΤΥΠΑ Η ΔΙΑΚΟΠΗ. Ο Gate Array τη ζητά ανά 52 HSYNC, και δύο γραμμές μετά
; την αρχή του VSYNC ξαναμετρά από την αρχή. Με R7 = 33 το VSYNC πέφτει στη
; γραμμή 264 και οι διακοπές στις 266, 6, 58, 110, 162 και 214 (μετρημένο στον
; εξομοιωτή: tests/test_split.py). Καμία δεν είναι εκεί που χρειάζεται, οπότε:
;
;   266  is_vs    Mode 1 και τα pens της πάνω λωρίδας
;     6  is_top   αναμονή ως τη γραμμή 15· Mode 0, ΜΗΔΕΝΙΣΜΟΣ του μετρητή του
;                 Gate Array στην ίδια εγγραφή, και τα pens του κάδρου
;    67  is_i2    (52 γραμμές μετά τον μηδενισμό)
;   119  is_i3
;   171  is_bot   αναμονή ως τη γραμμή 176· Mode 1 και τα pens της κάτω λωρίδας
;   223  is_i5
;
; Ο μηδενισμός είναι αυτό που φέρνει την τέταρτη στη 171 αντί για τη 162: εννέα
; γραμμές αναμονής λιγότερες. Οι δύο αναμονές μαζί κρατούν ~12,5 γραμμές, 800 us
; ανά frame — η τιμή του Mode 1 στις λωρίδες.
;
; ΜΙΑ ΑΛΥΣΙΔΑ, ΟΧΙ ΜΕΤΡΗΤΗΣ. Κάθε χειριστής γράφει στο #0039 ποιος είναι ο
; επόμενος, και ο Z80 πηδά κατευθείαν εκεί: οι τρεις που δεν κάνουν τίποτα
; κοστίζουν 25 us αντί για 51 (ένας μετρητής ήθελε το VSYNC από το PPI και δύο
; συγκρίσεις σε κάθε διακοπή). Ολοι οι χειριστές ζουν στην ΙΔΙΑ σελίδα, ώστε η
; εγγραφή να είναι ένα byte — γι' αυτό το isr.asm είναι το πρώτο πράγμα στο
; #0100, μετά από ένα jp start.
;
; ΜΕΤΑ ΑΠΟ ΚΛΕΙΣΤΕΣ ΔΙΑΚΟΠΕΣ, is_on — ΟΧΙ ΣΚΕΤΟ ei. Οσο είναι κλειστές (δίσκος)
; χάνονται, και η πρώτη μετά το ei έρχεται όπου έρχεται: ο χειριστής που
; περίμενε τη γραμμή 6 τρέχει στην 100, άλλος παίρνει τη διακοπή του VSYNC, και
; η αλυσίδα ήθελε ως δύο frames να ξαναβρεί το βήμα — το έπιασε το test_save,
; με το κάδρο σε Mode 1 μετά το φόρτωμα. Ούτε το «επόμενος το is_vs» φτάνει:
; αν μια διακοπή έπεσε στις 32 γραμμές πριν από το VSYNC, ο Gate Array δεν δίνει
; καθόλου τη διακοπή της 266, και χάνεται άλλο ένα frame. Το is_on κάνει ό,τι
; θα έκανε ο ίδιος: περιμένει το VSYNC, μηδενίζει τον μετρητή (που καθαρίζει και
; τη διακοπή που περιμένει), κάνει τη δουλειά του is_vs, και δείχνει στο is_top.
; Ο Gate Array μηδενίζει ξανά μόνος του στο τέλος του HSYNC της 265 — και αφού ο
; μετρητής είναι τότε κάτω από 32, χωρίς διακοπή — οπότε η επόμενη έρχεται στη
; 6, όπως πάντα. Το πρώτο frame μετά είναι σωστό. Ως 20 ms αναμονής,
; μία φορά ανά σώσιμο ή φόρτωμα. Το ei του βρόχου δεν μπορεί να το κάνει: θα
; περίμενε ένα VSYNC σε κάθε frame.

; R7 = 33 ΑΝΤΙ ΓΙΑ 30: η εικόνα ανεβαίνει 24 γραμμές στην οθόνη. Με το 30 η
; πρώτη διακοπή μετά το VSYNC πέφτει στη 30-άρα, και η αναμονή ως τη γραμμή 15
; θα ήταν μία ολόκληρη περίοδος. Με το 34 θα ήταν μία γραμμή αντί για εννέα
; (~500 us λιγότερα ανά frame), με την εικόνα 32 γραμμές ψηλότερα.
;
; ΚΑΘΑΡΗ: μόνο AF και BC, στη στοίβα. Ο υπόλοιπος κώδικας κρατά πράγματα στους
; σκιώδεις (HL' η ουρά δρομολόγησης, AF' οι πυρήνες σχεδίασης): δεν αγγίζονται.
; Κανένα exx, κανένα ex af,af'.
;
; ΟΠΟΥ ΔΕΝ ΧΩΡΑ. Ο δίσκος (src/save.asm) κλείνει τις διακοπές για όσο κρατά:
; ο ελεγκτής δίνει ένα byte ανά 27 us και η αναμονή εδώ κρατά 550. Οσο είναι
; κλειστές, η οθόνη μένει όπως την άφησε το is_flat: Mode 0 παντού, και οι
; λωρίδες σβηστές. Και η παλέτα (src/hw.asm) γράφεται μόνο με κλειστές: η
; εγγραφή pen είναι δύο out, και η διακοπή ανάμεσά τους θα έστελνε το χρώμα
; σε άλλο pen.

IS_R7       equ 33
IS_WTOP     equ 141             ; βρόχοι των 4 us ως τη γραμμή 15 (μετρημένο)
IS_WBOT     equ 70              ; ...και ως τη 176
IS_WON      equ 22              ; is_on: από την αρχή του VSYNC (σωστά 1-43, μετρημένο)
RMR_MODE1   equ RMR_MODE0 + 1
RMR_IRQ     equ #10             ; μηδενίζει τον μετρητή διακοπών του Gate Array
IS_VEC      equ #0038

; --- 266: η αρχή του frame ---------------------------------------------------
; Η πάνω λωρίδα αρχίζει στη γραμμή 0, μακριά από εδώ: καμία αναμονή. Το Mode 1
; γράφεται και εδώ, όχι μόνο στο κάτω σπάσιμο, ώστε ένα frame που έχασε το κάτω
; να ξαναβρίσκει τη σωστή αρχή.
is_vs:
        push    af
        push    bc
        ld      b,PPI_B >> 8
        in      a,(c)
        rra                             ; CY = VSYNC
        jr      nc,is_out               ; όχι ακόμη: μένουμε εδώ
        ld      bc,GA_PORT + RMR_MODE1
        out     (c),c
is_vsp: ld      c,1
        out     (c),c
        ld      a,(is_pal + 0)
        out     (c),a
        inc     c
        out     (c),c
        ld      a,(is_pal + 1)
        out     (c),a
        inc     c
        out     (c),c
        ld      a,(is_pal + 2)
        out     (c),a
        ld      a,is_top & 255
is_next:
        ld      (IS_VEC + 1),a
is_out:
        pop     bc
        pop     af
        ei
        ret

; --- 6 -> 15: το κάδρο -------------------------------------------------------
; Η εγγραφή του mode ΚΑΙ ο μηδενισμός είναι ένα out, στη γραμμή 15 ~10 us μετά
; την αρχή της: μακριά από το τέλος του HSYNC (χαρακτήρας 60), ώστε το «52
; γραμμές μετά» να είναι πάντα η ίδια γραμμή. Τα pens ακολουθούν και τελειώνουν
; πριν αρχίσει η 16.
is_top:
        push    af
        push    bc
        ld      a,IS_WTOP
it_w:   dec     a
        jr      nz,it_w
        ld      bc,GA_PORT + RMR_MODE0 + RMR_IRQ
        out     (c),c
        ld      c,1
        out     (c),c
        ld      a,(is_pal + 3)
        out     (c),a
        inc     c
        out     (c),c
        ld      a,(is_pal + 4)
        out     (c),a
        inc     c
        out     (c),c
        ld      a,(is_pal + 5)
        out     (c),a
        ld      a,is_i2 & 255
        jr      is_next

; --- 67, 119, 223: τίποτα, μόνο ο επόμενος ----------------------------------
is_i2:
        push    af
        ld      a,is_i3 & 255
is_idle:
        ld      (IS_VEC + 1),a
        pop     af
        ei
        ret
is_i3:
        push    af
        ld      a,is_bot & 255
        jr      is_idle
is_i5:
        push    af
        ld      a,is_vs & 255
        jr      is_idle

; --- 171 -> 176: η κάτω λωρίδα ----------------------------------------------
; Τα pens ΜΕΤΑ το τέλος της 175 (η τελευταία γραμμή του κάδρου, ως τον
; χαρακτήρα 40) και πριν από την 177· το mode οπουδήποτε ανάμεσα στο HSYNC της
; 174 και της 176. Η 176 είναι κενή και τα σκεπάζει και τα δύο.
is_bot:
        push    af
        push    bc
        ld      a,IS_WBOT
ib_w:   dec     a
        jr      nz,ib_w
        ld      bc,GA_PORT + RMR_MODE1
        out     (c),c
        ld      c,1
        out     (c),c
        ld      a,(is_pal + 6)
        out     (c),a
        inc     c
        out     (c),c
        ld      a,(is_pal + 7)
        out     (c),a
        inc     c
        out     (c),c
        ld      a,(is_pal + 8)
        out     (c),a
        ld      a,is_i5 & 255
        jr      is_next
; ---------------------------------------------------------------------------
; is_on — οι διακοπές ξανά μετά από μακρύ di, στο βήμα (βλ. πάνω). Καλείται με
; κλειστές. Περιμένει το επόμενο VSYNC: ως ένα frame. Χαλάει A.
; ---------------------------------------------------------------------------
is_on:
        push    af
        push    bc
        ld      b,PPI_B >> 8
ion_lo: in      a,(c)                   ; αν είμαστε μέσα σε VSYNC, να τελειώσει
        rra
        jr      c,ion_lo
ion_hi: in      a,(c)                   ; η αρχή του: γραμμή 263-264
        rra
        jr      nc,ion_hi
        ld      a,IS_WON
ion_w:  dec     a
        jr      nz,ion_w
        ; ΠΡΙΝ από τον μηδενισμό του ίδιου του Gate Array (τέλος του HSYNC της
        ; 265), που ορίζει τη φάση. Μετρημένο: σωστό με 1 ως 43 βρόχους· από 45,
        ; μετά το τέλος της 266, οι διακοπές πάνε μία γραμμή πίσω.
        ld      bc,GA_PORT + RMR_MODE1 + RMR_IRQ
        out     (c),c
        jp      is_vsp                  ; τα pens, και επόμενος ο is_top

is_end:
        assert  is_vs >> 8 == (is_end - 1) >> 8 ; ένα byte διεύθυνσης (IS_VEC + 1)


; ---------------------------------------------------------------------------
; is_flat — μία οθόνη χωρίς σπασίματα, για όσο οι διακοπές είναι κλειστές:
; Mode 0 και τα pens του κάδρου παντού. Ο καλών σβήνει πρώτα τις λωρίδες
; (hud_inval), αλλιώς φαίνονται ως θόρυβος Mode 0. Χαλάει A, BC, HL.
; is_m1 — το ανάποδο: Mode 1 και τα pens της κάτω λωρίδας παντού, για την
; οθόνη βοήθειας (src/help.asm, βήμα 84).
; ---------------------------------------------------------------------------
is_m1:
        ld      bc,GA_PORT + RMR_MODE1
        ld      hl,is_pal + 6
        jr      isf_go
is_flat:
        ld      bc,GA_PORT + RMR_MODE0
        ld      hl,is_pal + 3
isf_go:
        out     (c),c
        ld      c,1
isf_lp:
        out     (c),c                   ; το pen
        ld      a,(hl)
        inc     hl
        out     (c),a                   ; το χρώμα του
        inc     c
        bit     2,c
        jr      z,isf_lp
        ret

; Τα pens 1-3, σε τιμές του Gate Array (με το GA_INK): πάνω λωρίδα, κάδρο, κάτω
; λωρίδα. Του κάδρου τα γράφει το is_init από το palette_fw των assets. Των
; λωρίδων: 1 κόκκινο, 2 πράσινο, 3 λευκό (hardware #0C, #12, #0B).
is_pal:     db GA_INK + #0C, GA_INK + #12, GA_INK + #0B
            db 0, 0, 0
            db GA_INK + #0C, GA_INK + #12, GA_INK + #0B

; ---------------------------------------------------------------------------
; is_init — το διάνυσμα, IM 1, το R7, και τα pens του κάδρου. Οι διακοπές
; μένουν κλειστές: τις ανοίγει ο βρόχος (main_loop).
;
; Το «jp isr» γράφεται στο #0038 εδώ και όχι από τη μεταγλώττιση: ο δίσκος
; φορτώνει από το #0100, και κάτω από αυτό είναι ό,τι άφησε το firmware.
; ---------------------------------------------------------------------------
is_init:
        ld      a,#C3                   ; jp
        ld      (IS_VEC),a
        ld      hl,is_vs
        ld      (IS_VEC + 1),hl
        im      1
        ld      bc,CRTC_SEL + 7
        out     (c),c
        ld      bc,CRTC_VAL + IS_R7
        out     (c),c
        ld      hl,G_palette_fw + 1
        ld      de,is_pal + 3
        ld      b,3
isi_lp: ld      a,(hl)
        inc     hl
        push    hl
        ld      hl,fw_to_hw
        add     a,l
        ld      l,a
        adc     a,h
        sub     l
        ld      h,a
        ld      a,(hl)
        or      GA_INK
        ld      (de),a
        inc     de
        pop     hl
        djnz    isi_lp
        ret
