; goals.asm — τα ορόσημα που φαίνονται, και η σελίδα του τέλους (βήμα 177,
; DESIGN §10.2-10.3). ΣΤΟ OV_R1, και τρέχει εκεί, με την 1 στο παράθυρο: το
; UI τρέχει πάντα έτσι (src/commit.asm), όπως το bar_want πριν από το bk_gen.
;
; Ο ΠΑΙΚΤΗΣ ρώτησε τι λείπει για να είναι πλήρες το παιχνίδι. Τα πέντε ορόσημα
; του §10.2 μετριούνταν από το βήμα 9 (EC_MILE, src/ship.asm) και ανέβαζαν το
; κύρος, αλλά καμία οθόνη δεν τα έλεγε· και όταν πέθαιναν όλοι, η γραμμή
; έλεγε COLONY LOST και τίποτε άλλο. Διάλεξε (AskUserQuestion, 2026-10-31):
; σελίδα όταν πιάνεται ένα ορόσημο, με το παιχνίδι σταματημένο· το G από την
; κύρια οθόνη για μια σελίδα με τα πέντε και πόσο απέχει το καθένα· και μετά
; το COLONY LOST μια σελίδα με τα sols, τους περισσότερους αποίκους, τα
; ορόσημα, το κύρος και τα νομίσματα, από όπου το L φορτώνει και κάθε άλλο
; πλήκτρο ξαναρχίζει από το μενού.
;
; ΠΩΣ ΦΤΑΝΕΙ ΕΔΩ: ΣΑΝ ΚΟΥΜΠΙ. Η τράπεζα 0 είχε 8 bytes ως το πάτωμα των
; δοκιμών και ο πίνακας ενεργειών του in_read είναι γεμάτος (δεκαέξι bits).
; Ομως το bk_scan ήδη διαβάζει σε κάθε frame τα γράμματα της μπάρας, με κώδικα
; που γράφει το bk_gen όταν αλλάζει η μπάρα. Στη μπάρα των ομάδων, όπου κανένα
; G δεν είναι κουμπί, το bk_more βάζει δύο ακόμη: το G, και το ms_req, ένα byte
; δίπλα στο key_now που διαβάζεται όπως μια ενδέκατη γραμμή πλήκτρων, μόνο όσο
; περιμένει μια σελίδα. Και τα δύο είναι το κουμπί BT_GOAL (src/bar.asm), που
; το bt_key στέλνει στο ms_key. 9 µs το frame για το G στη μπάρα των ομάδων,
; όσο κάθε γράμμα (§9.1)· άλλα 9 µs μόνο όσο υπάρχει αίτημα.
; ΚΑΙ ΤΟ TAB ΑΠΟ ΤΟ ΒΗΜΑ 186, ο χάρτης (src/map.asm): μια τρίτη θέση του ίδιου
; κουμπιού, ανάμεσα στο G και στο αίτημα, άλλα 9 µs το frame στη μπάρα των
; ομάδων. Το ms_key κοιτάζει το TAB πρώτο. 14 bytes του OV_R1.
; ΚΑΙ ΤΟ V ΑΠΟ ΤΟ ΒΗΜΑ 191, οι πόροι: όχι το BT_GOAL αλλά το δικό του κουμπί,
; το BT_RES της ΔΙΑΧΕΙΡΙΣΗΣ, που το bt_key στέλνει στο rs_key (src/help.asm).
; Αλλα 9 µs το frame στη μπάρα των ομάδων, και 10 bytes του OV_R1 (bkm_id).
; ---------------------------------------------------------------------------

; bk_more — από το bk_gen (src/button.asm): HL = η επόμενη θέση του bk_code, DE
; η επόμενη του bk_ids. Στη μπάρα των ομάδων το G, και το αίτημα αν υπάρχει·
; μετά το τέλος της λίστας, όπως το έγραφε το bk_gen ως το βήμα 176.
bk_more:
        ld      a,(bw_id + 1)
        cp      BT_CORR                 ; ομάδες: το R δεύτερο (ac_l_grp)
        jr      nz,bkm_end
        ld      bc,6 * 256 + #10        ; το G: γραμμή 6, μάσκα #10 (το bt_tab)
        call    bkm_one
        ld      bc,8 * 256 + #10        ; το TAB, ο χάρτης (βήμα 186): γραμμή 8, #10
        call    bkm_one
        ld      bc,6 * 256 + #80        ; το V, οι πόροι (βήμα 191): γραμμή 6, #80,
        ld      a,BT_RES                ; με το δικό του κουμπί (το bt_tab)
        call    bkm_id
        ld      a,(ms_req)
        rra
        jr      c,bkm_end               ; κανένα αίτημα: ούτε το κόστος του
        ld      bc,KEY_LINES * 256 + 1  ; το ms_req: «γραμμή» 10, bit 0
        call    bkm_one
bkm_end:
        ; --- το τέλος: jr bk_none στη θέση της επόμενης — εκτός αν η μπάρα
        ; γέμισε και τα δεκαπέντε, όπου η επόμενη θέση ΕΙΝΑΙ το bk_none ---
        ld      a,l
        cp      bk_none & 255
        ret     z
        ld      (hl),#18
        inc     hl
        ld      a,(bk_none - 1) & 255
        sub     l
        ld      (hl),a
        ret
; bkm_one — B = γραμμή, C = μάσκα: μια θέση του bk_code για το BT_GOAL, όπως
; τη γράφει το bk_gen. bkm_id — το ίδιο, για το κουμπί A (βήμα 191).
bkm_one:
        ld      a,BT_GOAL
bkm_id:
        push    af
        ld      (hl),#3A                ; ld a,(nn)
        inc     hl
        ld      a,b
        add     a,key_now & 255
        ld      (hl),a
        inc     hl
        inc     hl                      ; το πάνω byte: της σελίδας του key_now
        inc     hl                      ; and
        ld      (hl),c
        ld      bc,4                    ; jr z, inc c
        add     hl,bc
        pop     af
        ld      (de),a
        inc     de
        ret
        assert  BK_MAX >= 7 + 4         ; οι ομάδες, το ?, το G, το TAB, το V, το αίτημα

; ms_key — το BT_GOAL (src/act.asm), στο LOOK: το G, ή το αίτημα. Τη σελίδα τη
; διαλέγει και γράφει τα νούμερά της το ms_go της 7 (src/tpage.asm)· το
; tu_page τη δείχνει, με το «?» τη βοήθεια, και ξαναζωγραφίζει την οθόνη. Η
; σελίδα του τέλους γυρίζει μόνο με το L (κάθε άλλο πλήκτρο ξαναρχίζει το
; παιχνίδι, tp_new): τότε το φόρτωμα.
; ΚΑΙ ΤΟ TAB (βήμα 186): το ίδιο κουμπί, και εδώ ποιο πλήκτρο το πάτησε. Ο
; χάρτης στο src/map.asm (b1code).
ms_key:
        ld      a,(key_now + 8)
        and     #10
        jp      z,mp_open
        call    ui_hide                 ; το GH_BUF αδειάζει: εκεί ο οδηγός του δίσκου
        ld      a,TP_CHOOSE
        call    tu_page                 ; src/help.asm
        ld      a,(EC_GAMEOVER)
        or      a
        jp      z,ui_show
        ld      a,1                     ; το φόρτωμα (src/ui.asm)
        jp      ui_askslot
