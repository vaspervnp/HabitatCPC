; alert.asm — ο συναγερμός: όλοι μέσα (βήμα 166, DESIGN §6.10).
;
; Η ΑΠΟΦΑΣΗ ΤΟΥ ΠΑΙΚΤΗ: με την προσγείωση των εισβολέων, όποιος άποικος είναι
; έξω και δεν είναι φρουρός αφήνει τη δουλειά του και πάει στο κοντινότερο
; airlock, μέσα. Ο πίνακας εργασιών δεν τον ξαναστέλνει έξω ως το τέλος της
; μάχης. Ως τότε οι νεκροί των επιδρομών ήταν όλοι έξω: στα 8 μεγάλα παιχνίδια
; του βήματος 165, 33 από τους 63 νεοφερμένοι χωρίς δουλειά που στέκονταν
; στην πίστα όπου προσγειώνονται και οι εισβολείς, και 30 στο ορυχείο· οι 55
; πριν χτυπήσει φρουρός.
;
; ΜΕ T_FIGHT, όπως οι φρουροί: τη δουλειά του την αφήνει (jb_reap), ο πίνακας
; δεν τον ξαναπιάνει, και το fo_over τον δίνει πίσω όταν πέσει ο τελευταίος.
; Ο προορισμός είναι ο θόλος του airlock (βήμα 168), και από το airlock είναι
; μέσα (en_in). Οποιος πάει ήδη μέσα (T_NEED: η στολή ή μια ανάγκη) μένει
; όπως είναι. Οσο περπατά κανείς εισβολέας δεν τον χτυπά (fov_v).
;
; ΩΣ ΤΟΝ ΘΟΛΟ ΤΟΥ (βήμα 168), όχι ως το airlock: οι εισβολείς μπαίνουν από
; το airlock, και ο επόμενος στόχος τους (fo_pk) ήταν όσοι στέκονταν εκεί. Με
; τα φυτά του σεναρίου διορθωμένα οι αποικίες έγιναν πυκνότερες, με λιγότερα
; airlock, και στο C0DE 0 και οι 17 νεκροί των επιδρομών ήταν μέσα, στο
; airlock 66, οι 14 με T_FIGHT. Τώρα πάνε στον πρώτο γείτονα του airlock που
; είναι έτοιμος θόλος, και αν δεν είναι κανένας, στο airlock. Ο θόλος του
; καθενός βρίσκεται μία φορά ανά προσγείωση, την πρώτη φορά που διαλέγεται, και
; μένει στη λίστα SH_DOME: ψαγμένος για κάθε νέο κόμβο, η σκηνή των 48 του
; tests/test_sim.py έφτανε τα 25,5 ms, πάνω από ένα frame.
;
; ΣΤΗΝ ΠΡΟΣΓΕΙΩΣΗ (fo_land), όχι στην πρώτη περιστροφή της μάχης: εκείνη τη
; φορά η θέση 15 δεν πληρώνει μάχη, και στην επόμενη, πριν από τη θέση 15, η
; κίνηση (0-7) τους έχει ήδη βάλει στον δρόμο. Μια φόρτωση στη μέση της μάχης
; δεν τον ξανακάνει: όσοι πήγαιναν μέσα έχουν ακόμη T_FIGHT και προορισμό.
;
; ΤΟ su_lock ΘΑ ΗΤΑΝ 0,6 ms ΑΝΑ ΑΠΟΙΚΟ: περνά και τις 48 δομές για κάθε
; ερώτηση, και στην αποικία του tests/test_sim.py η πρώτη περιστροφή έφτασε
; τα 35,6 ms. Εδώ οι δομές περνιούνται μία φορά, και τα έτοιμα airlock μπαίνουν
; σε λίστα (sh_list) στη μνήμη εργασίας του src/crew.asm, G_crew: εκείνη τη
; θέλει μόνο η προσγείωση αποίκων και η γραμμή του εμπόρου, και όταν
; προσγειώνονται εισβολείς δεν είναι εδώ άλλο πλοίο. Για κάθε κόμβο, μία
; απόσταση ανά airlock (sh_near). Και όποιος στέκεται στον κόμβο του
; προηγούμενου (οι νεοφερμένοι της πίστας, οι εργάτες ενός ορυχείου) παίρνει
; την ίδια απάντηση (fo_ln, fo_la). Τα 16 πρώτα airlock, κατά θέση (32 ως το
; βήμα 167· τα άλλα 16 bytes του G_crew κρατούν τώρα τους θόλους τους)· τα
; παιχνίδια του σεναρίου χτίζουν ως 8.
;
; ΠΟΥ ΖΕΙ: το πέρασμα των αποίκων (fo_alert) στο b6code με τους εισβολείς·
; εδώ, στη σελίδα 2, η λίστα και το sh_near, που βάζει την τράπεζα 1 στο
; παράθυρο για το DIST — ο κώδικας του b6code θα έφευγε από κάτω του.
;
; ΤΟ ΚΟΣΤΟΣ (tests/test_sim.py): η θέση 15 της προσγείωσης 3.620 us χωρίς τον
; συναγερμό, 5.660 με όλους μέσα (τα δύο περάσματα), ~150 us ανά άποικο έξω σε
; κόμβο άλλο από του προηγούμενου: 6.500 με επτά σε τρεις κόμβους, 19.060 με
; 48 σε κόμβους που αλλάζουν κάθε φορά. Μία φορά ανά επιδρομή.

SH_MAX      equ 16
SH_LIST     equ G_crew                  ; κόμβοι airlock, και 255 στο τέλος
SH_DOME     equ SH_LIST + SH_MAX + 1    ; ο θόλος του καθενός, ή SH_UNK ως την πρώτη ερώτηση
SH_UNK      equ 254
        assert  (G_crew & 255) + 2 * SH_MAX + 1 <= 256  ; μία σελίδα: inc e, add a
        assert  2 * SH_MAX + 1 <= 33                    ; το G_crew (src/crew.asm)
        assert  ST_STATE == ST_KIND + 2 && (G_struct_tbl & 7) == 0
        assert  F_ALIVE == 1 && F_INDOORS == 2 && NO_TASK == 255

; ---------------------------------------------------------------------------
; sh_build — η sh_list: τα έτοιμα airlock, με τη σειρά των θέσεων. Από το
; fo_alert (src/foe.asm), με την τράπεζα 6 στο παράθυρο. Επιστρέφει A = 255.
; Χαλάει BC, DE, HL.
; ---------------------------------------------------------------------------
sh_build:
        ld      hl,G_struct_tbl + ST_KIND
        ld      de,SH_LIST
        ld      bc,MAX_STRUCT * 256 + MAX_DOME  ; B = πόσες, C = ο κόμβος της δομής
shl_lp:
        ld      a,(hl)
        cp      K_AIRLOCK
        jr      nz,shl_nx
        inc     l
        inc     l
        ld      a,(hl)                  ; ST_STATE
        dec     l
        dec     l
        cp      DS_ACTIVE
        jr      nz,shl_nx
        ld      a,e
        cp      (SH_LIST + SH_MAX) & 255
        jr      z,shl_nx                ; γεμάτη
        ld      a,c
        ld      (de),a
        ld      a,e
        add     a,SH_MAX + 1
        ld      e,a
        ld      a,SH_UNK
        ld      (de),a                  ; ο θόλος του: όταν ζητηθεί (sh_near)
        ld      a,e
        sub     SH_MAX
        ld      e,a                     ; ο επόμενος
shl_nx:
        inc     c
        ld      a,l
        add     a,STRUCT_REC
        ld      l,a
        jr      nc,shl_c
        inc     h                       ; η δεύτερη σελίδα (βήμα 154)
shl_c:
        djnz    shl_lp
        ld      a,255
        ld      (de),a                  ; το τέλος
        ld      (SH_LIST + SH_MAX),a    ; και η απάντηση «κανένα» του sh_near
        ret

; ---------------------------------------------------------------------------
; sh_near — D = κόμβος -> A = ο θόλος του κοντινότερου airlock της sh_list
; στον γράφο (DIST): ο πρώτος γείτονάς του που είναι έτοιμος θόλος, αλλιώς το
; ίδιο το airlock (SH_DOME)· ή 255. Ισοπαλία: το πρώτο, όπως το su_lock. Η γραμμή όπως
; στο su_lock: θόλος στο &4000 + 128 x κόμβος, δομή στο μπλοκ των δομών
; (blk_row, βήμα 155). Η τράπεζα 1 μπαίνει μία φορά για όλη τη λίστα, και
; ξαναβγαίνει η 6. Χαλάει BC, DE, HL.
; ---------------------------------------------------------------------------
sh_near:
        ld      a,d
        cp      MAX_DOME
        jr      nc,shn_st
        ld      h,d
        ld      l,0
        srl     h
        rr      l
        set     6,h                     ; DIST[κόμβος], στο &4000
        jr      shn_go
shn_st:
        call    blk_row                 ; src/jobs.asm
shn_go:
        ld      a,(SH_LIST + SH_MAX) & 255
        ld      (sh_best),a             ; κανένα: εκεί είναι 255 (sh_build)
        ld      d,l                     ; D = η βάση της γραμμής (κάτω byte)
        ld      bc,GA_PORT + PAGE_B1
        out     (c),c
        ld      b,255                   ; B = η καλύτερη απόσταση
        ld      a,d
        ld      de,SH_LIST
        ld      c,a                     ; C = η βάση
shn_lp:
        ld      a,(de)                  ; ένα airlock
        inc     a
        jr      z,shn_end               ; το τέλος
        dec     a
        inc     e
        add     a,c                     ; 0 ή 128 και ο κόμβος < 128, ή blk_row
        ld      l,a
        ld      a,(hl)                  ; DIST[κόμβος][airlock]
        cp      b
        jr      nc,shn_lp               ; ούτε πιο κοντά, ούτε απρόσιτο (255)
        ld      b,a
        ld      a,e
        add     a,SH_MAX
        ld      (sh_best),a             ; ο θόλος του, στο SH_DOME (το E πέρασε ήδη)
        jr      shn_lp
shn_end:
        ld      bc,GA_PORT + PAGE_B6
        out     (c),c
        ; ΚΑΙ ΣΤΟΝ ΘΟΛΟ ΤΟΥ (βήμα 168): ο πρώτος γείτονας του airlock που
        ; είναι έτοιμος θόλος (en_in). Αν κανένας, το airlock. Μία φορά ανά
        ; airlock: μετά από τη λίστα.
        ld      a,(sh_best)
        ld      l,a
        ld      h,SH_LIST >> 8          ; HL = ο θόλος του, στο SH_DOME
        ld      a,(hl)
        cp      SH_UNK
        ret     nz                      ; ήδη γνωστός, ή 255: κανένα airlock
        push    hl
        ld      a,l
        sub     SH_MAX + 1
        ld      l,a
        ld      a,(hl)                  ; το airlock
        ld      e,a                     ; E = το airlock
        ld      l,a
        ld      h,NODEPG
        ld      b,(hl)                  ; ο βαθμός του
        inc     b
        dec     b
        jr      z,shd_no
        add     a,(G_node_adj >> 3) & 255
        ld      l,a
        ld      h,G_node_adj >> 11
        add     hl,hl
        add     hl,hl
        add     hl,hl                   ; οι γείτονές του
shd_lp:
        ld      a,(hl)
        cp      MAX_DOME
        jr      nc,shd_nx               ; δομή ή μονοπάτι
        push    hl
        push    de
        call    en_in                   ; src/door.asm: CY αν είναι έτοιμος (κρατά BC)
        pop     de
        pop     hl
        ld      a,(hl)
        jr      c,shd_put
shd_nx:
        inc     l
        djnz    shd_lp
shd_no:
        ld      a,e
shd_put:
        pop     hl
        ld      (hl),a                  ; στη λίστα, για τον επόμενο
        ret

sh_best:    db 0
