; wake6.asm — το ξύπνημα των εργοταξίων που περιμένουν υλικά, στην ουρά 5 των
; σελίδων πεδίων της τράπεζας 6, μετά το src/supply6.asm (βήμα 198, DESIGN
; §6.9). Στο tests/simtest.asm το B6T_PIECE δεν κάνει τίποτα.

; ---------------------------------------------------------------------------
; sp_wake — από τον κύκλο ροής (src/flow.asm), με την 6. Αν κάποιο υλικό
; περίμενε απόθεμα (EC_WAIT, sp_pay), το sp_sweep ξαναβάζει ό,τι λείπει από
; τον πίνακα, και ό,τι δεν πληρώνεται ακόμη ξαναφεύγει στο σήκωμα (sp_go) και
; ξανασημειώνεται: ένα σάρωμα ανά κύκλο ροής όσο κάτι περιμένει. Και ό,τι
; χάθηκε από γεμάτο πίνακα, όπως από το βήμα 115.
; ---------------------------------------------------------------------------
sp_wake:
        ld      hl,EC_WAIT
        ld      a,(hl)
        or      a
        jr      z,spw_lost
        ld      (hl),0
        ld      (jb_lost),a             ; όχι 0: το σάρωμα
spw_lost:
        ld      a,(jb_lost)
        or      a
        ret     z
        jp      sp_sweep
