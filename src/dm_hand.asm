; dm_hand.asm — δύο χειριστές της λίστας αλλαγών (src/dirty.asm) για την
; κατεδάφιση, που ΤΡΕΧΟΥΝ ΕΚΕΙ ΠΟΥ ΕΙΝΑΙ: στην αρχή του OV_R1, στη βασική
; τράπεζα 1 — εκεί που είναι το παράθυρο όταν τρέχει η λίστα, και όπου
; ξαναγυρίζει κάθε χειριστής. Κάθε ορθογώνιο της κατεδάφισης είναι ένα
; DK_RSIZE και ένα DK_RECT (dm_do), ένα ανά πέρασμα της λίστας: όλα μαζί στο
; FIRE έκαναν το καρέ ως 270 ms.
;
; Ως το βήμα 154 ήταν η «σειρά 0» του src/dm_ovl.asm: γραμμένοι για το GH_BUF,
; έτρεχαν στην τρύπα της γραμμής 0 του DIST (#4060), άρα χωρίς αναφορές στον
; εαυτό τους. Από το 155 ο συναρμολογητής τους βάζει στη θέση που τρέχουν
; (src/main.asm), και το DH_RSIZE και το DH_RECT είναι απλώς οι ετικέτες τους.
; Τους φέρνει εκεί το ov_install, με το υπόλοιπο OV_R1.
; ---------------------------------------------------------------------------
DH_RSIZE:
        ld      hl,(dt_a)
        ld      (vr_w),hl               ; vr_w, vr_h
        ret
DH_RECT:
        ld      hl,(dt_a)
        ld      (vr_tx),hl              ; vr_tx, vr_ty
        call    vr_clip                 ; src/view.asm
        ret     z                       ; έξω από το κάδρο
        call    dt_ghost_rect           ; το φάντασμα σηκώνεται, αν είναι εκεί
        call    vr_paint                ; το έδαφος
        jp      vr_objs                 ; ό,τι το πατά, και το clip πίσω
