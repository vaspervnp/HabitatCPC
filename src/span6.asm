; span6.asm — το αδιαφανές τέλος των κελυφών (βήμα 114, DESIGN §8.4).
;
; Τα κελύφη των θόλων είναι γεμάτα ως το κέντρο τους: μέσα στα διαστήματα του
; src/span.asm, το 80-90% των ζευγών έχει μάσκα 0. Το tools/pack.py αποθηκεύει
; τις στήλες στο τέλος κάθε ομάδας που είναι έτσι και στις οκτώ γραμμές της
; (k, όταν είναι τουλάχιστον K_MIN) χωρίς τη μάσκα τους, και εδώ ζωγραφίζονται
; με αντιγραφή: ldir (5 us το byte αντί για 18) ή, καθρεφτισμένα, μία
; αναζήτηση στον πίνακα (18 us αντί για 32). Η εικόνα είναι η ίδια byte προς
; byte: (οθόνη AND 0) OR χρώμα = χρώμα.
;
; ΣΤΟ b6code, ΟΧΙ ΣΤΗΝ ΤΡΑΠΕΖΑ 0. Ενα κέλυφος ζωγραφίζεται μόνο με την 6 στο
; παράθυρο — εκεί είναι τα διαστήματα και ο πίνακας καθρεφτίσματος — οπότε και
; αυτός ο κώδικας τρέχει μόνο τότε. Τα κελύφη μίκρυναν 872 bytes, και τα 768
; έγιναν χώρος του b6code (B6C_MAX), όπως στο βήμα 110. Στα tests/objtest.asm
; και tests/uitest.asm μπαίνει επίπεδα, όπως το joint.asm.

; ---------------------------------------------------------------------------
; blt_op_flip — μία γραμμή ΑΔΙΑΦΑΝΗ, καθρεφτισμένη (βήμα 114): σκέτα bytes
; χρώματος, χωρίς μάσκα, διαβασμένα προς τα πίσω — το αδιαφανές τέλος ενός
; κελύφους (src/span.asm).
; In :  HL = το πρώτο byte που γράφεται,  DE = οθόνη,  B = bytes.
; Out:  IX = ένα byte πριν από το τελευταίο που διαβάστηκε.
; Χαλάει: A, BC, HL, IX (και IY, AF' στο τύλιγμα).  Απαιτεί: τράπεζα 6 (FLIPTAB).
; 18 us το byte, ενώ το blt_mask_flip θέλει 32: μία αναζήτηση στον πίνακα, όχι
; δύο, και κανένα `and`.
; ---------------------------------------------------------------------------
blt_op_flip:
        push    hl
        pop     ix
        ld      h,FLIPTAB >> 8
        ld      a,d
        or      #F8
        inc     a
        jr      z,bof_chk
bof_run:
        ld      l,(ix+0)
        ld      a,(hl)
        ld      (de),a
        inc     de
        dec     ix
        djnz    bof_run
        ret
bof_chk:
        ld      a,b
        dec     a
        add     a,e
        jr      nc,bof_run
        ld      iy,bof_run
        jp      bl_wrap                 ; στην τράπεζα 0

; ---------------------------------------------------------------------------
; spk_nf / spk_fl — ομάδα με αδιαφανές τέλος (βήμα 114, tools/pack.py): m ζεύγη
; με μάσκα και μετά k bytes μόνο χρώμα. A = από ποια στήλη του διαστήματος
; αρχίζει η οθόνη — κανονικά η πρώτη που φαίνεται, καθρεφτισμένα η τελευταία,
; που γράφεται πρώτη — και (obl_n) πόσες φαίνονται. Αν φαίνεται μόνο το ένα
; κομμάτι, ο πυρήνας του κατευθείαν· αν και τα δύο, το sp2_*. Το E (η στήλη
; στην οθόνη) μένει για το spg_pk.
; ---------------------------------------------------------------------------
spk_nf:
        ld      d,a                     ; ofs
spk_m:  ld      a,0                     ; m (το sp_grp)
        ld      c,a
        sub     d                       ; m - ofs: τα ζεύγη με μάσκα που φαίνονται
        jr      c,skn_op
        jr      z,skn_op
        ld      b,a
        ld      a,(obl_n+1)
        sub     b
        ld      a,d
        jp      c,spg_pt                ; μόνο ζεύγη με μάσκα, όπως πάντα
        jp      z,spg_pt
        ld      a,(obl_n+1)
        sub     b
        ld      (sp2_n2+1),a            ; και μετά τα αδιαφανή
        ld      a,b
        ld      (sp2_n1+1),a
        ld      a,d
        add     a,a                     ; από το ζεύγος ofs
        ld      hl,sp2_nf
        jp      spg_pk
skn_op:
        ld      a,c
        add     a,d                     ; μόνο αδιαφανή: το byte 2m + (ofs - m)
        ld      hl,blt_op_line          ; = m + ofs
        jp      spg_pk

spk_fl:
        ld      d,a                     ; ofs: η δεξιότερη στήλη, γράφεται πρώτη
        ld      a,(spk_m+1)
        ld      c,a                     ; m
        ld      a,d
        sub     c
        ld      a,d
        jp      c,spg_pt                ; ofs < m: μόνο ζεύγη με μάσκα
        sub     c
        inc     a                       ; τα αδιαφανή που φαίνονται: ofs - m + 1
        ld      b,a
        ld      a,(obl_n+1)
        sub     b
        jr      c,skf_op
        jr      z,skf_op
        ld      (sf2_n2+1),a            ; και μετά τα ζεύγη
        ld      a,b
        ld      (sf2_n1+1),a
        ld      hl,sp2_fl
        jr      skf_go
skf_op:
        ld      hl,blt_op_flip          ; μόνο αδιαφανή
skf_go:
        ld      a,c
        add     a,d                     ; το byte m + ofs
        jp      spg_pk

; sp2_nf — μία γραμμή σε δύο κομμάτια: n1 ζεύγη με μάσκα, μετά n2 bytes χρώμα.
; Είναι συνεχόμενα στη γραμμή, οπότε το HL που αφήνει το blt_mask_line είναι
; ήδη το πρώτο χρώμα, και το DE η επόμενη θέση της οθόνης.
sp2_nf:
sp2_n1: ld      b,0
        call    blt_mask_line
sp2_n2: ld      b,0
        jp      blt_op_line

; sp2_fl — καθρεφτισμένο: πρώτα τα n1 αδιαφανή, από το τέλος της γραμμής προς
; τα πίσω, μετά τα n2 ζεύγη. Το IX του blt_op_flip σταματά στο χρώμα του
; ζεύγους m - 1, ένα byte μετά την αρχή του.
sp2_fl:
sf2_n1: ld      b,0
        call    blt_op_flip
        push    ix
        pop     hl
        dec     hl
sf2_n2: ld      b,0
        jp      blt_mask_flip
