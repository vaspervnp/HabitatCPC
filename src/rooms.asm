; rooms.asm — τι ΕΙΝΑΙ ένας θόλος, και τι κάθεται μέσα του (DESIGN §6.1, §6.5)
;
; Ως το βήμα 25 το bd_commit έγραφε «δωμάτιο: κενό ως την επιλογή» και οκτώ
; NO_MACH, και επιλογή δεν υπήρχε πουθενά: ό,τι έχτιζε ο παίκτης μετά την
; αρχική αποικία ήταν κέλυφος. Μετρημένο στο tools/balance.py — κάθε γραμμή
; παιχνιδιού που έλυνε το νερό τελείωνε στην ΤΡΟΦΗ, και η τροφή θέλει
; θερμοκήπιο και mach_food, δηλαδή θόλο με δωμάτιο.
;
; Η ΕΠΙΛΟΓΗ ΓΙΝΕΤΑΙ ΣΤΟΝ ΚΑΤΑΛΟΓΟ, ΟΧΙ ΜΕΤΑ. Ενα δεύτερο μενού πάνω σε
; χτισμένο θόλο θα ήθελε δική του κατάσταση διεπαφής, δικό του φάντασμα και
; δικό του «ποιον θόλο δείχνεις». Δεξιά-αριστερά διαλέγει μέγεθος, πάνω-κάτω
; διαλέγει δωμάτιο: δύο άξονες στο ίδιο μενού, καμία καινούργια κατάσταση.
;
; ΤΑ ΜΗΧΑΝΗΜΑΤΑ ΕΡΧΟΝΤΑΙ ΜΕ ΤΟ ΔΩΜΑΤΙΟ, και δεν πληρώνονται χωριστά. Το
; assets/SPRITES.md §6 λέει ήδη ποια μηχανήματα δέχεται κάθε δωμάτιο
; (`room_machines`, μάσκα 12 bit) και σε ποια μεγέθη χωράει το καθένα
; (`machine_rules`) — οι δύο πίνακες φτάνουν για να γεμίσει ένας θόλος μόνος
; του. Οπου το δωμάτιο δέχεται πολλά, οι υποδοχές μοιράζονται ΚΥΚΛΙΚΑ: ένα
; μεγάλο εργοστάσιο βγάζει σίδερο, βιοπλαστικό, όπλα, ρομπότ και ανταλλακτικά
; αντί για οκτώ φορές το ίδιο. Οταν ο παίκτης θέλει οκτώ ίδια, θα χρειαστεί
; επιλογή ανά υποδοχή — και αυτή είναι άλλη οθόνη, όχι άλλος πίνακας.

RM_N        equ 10                      ; πόσα δωμάτια προσφέρει ο κατάλογος
RM_MACH     equ 12                      ; MACH_TYPES / PLANT_TYPES

; Η σειρά είναι η σειρά που τα χρειάζεσαι: αέρας, φαγητό, ύπνος, και μετά τα
; υπόλοιπα. Το πρώτο επιτρεπτό είναι και το προεπιλεγμένο.
rm_list:
        db R_OXYGEN, R_CANTEEN, R_QUARTERS, R_GREENHS, R_FACTORY
        db R_LAB, R_MEDBAY, R_CONTROL, R_STORAGE, R_LOUNGE
rm_names:
        dw t_r_oxy, t_r_can, t_r_qrt, t_r_grn, t_r_fac
        dw t_r_lab, t_r_med, t_r_ctl, t_r_sto, t_r_lng

; ---------------------------------------------------------------------------
; rm_room — Out: A = το δωμάτιο που δείχνει το bd_rsel.
; ---------------------------------------------------------------------------
rm_room:
        ld      a,(bd_rsel)
        ld      hl,rm_list
        add     a,l
        ld      l,a
        ld      a,0
        adc     a,h
        ld      h,a
        ld      a,(hl)
        ret

; ---------------------------------------------------------------------------
; rm_name — Out: HL = το κείμενο (τράπεζα 7) του τρέχοντος δωματίου.
; ---------------------------------------------------------------------------
rm_name:
        ld      a,(bd_rsel)
        add     a,a
        ld      hl,rm_names
        add     a,l
        ld      l,a
        ld      a,0
        adc     a,h
        ld      h,a
        ld      a,(hl)
        inc     hl
        ld      h,(hl)
        ld      l,a
        ret

; ---------------------------------------------------------------------------
; rm_build — A = δωμάτιο. Γεμίζει το rm_buf με ό,τι επιτρέπεται εκεί μέσα, στο
;            τρέχον μέγεθος (bd_param).
;
;   Out: A = (rm_nbuf) = πόσα· CY αν το δωμάτιο ΘΕΛΕΙ μηχανήματα αλλά κανένα
;        δεν χωράει στο μέγεθος. Χωρίς CY και με μηδέν, το δωμάτιο απλώς δεν
;        έχει μηχανήματα (κατάλυμα, αποθήκη, σαλόνι) — αυτό επιτρέπεται.
;
; Ενας βρόχος, δύο δουλειές: ο κατάλογος τον ρωτά «χωράει;» και το χτίσιμο τον
; ρωτά «τι βάζω μέσα;». Το mach_oxygen μπαίνει ΜΟΝΟ σε μικρό θόλο
; (machine_rules bit0, §6.5), άρα το δωμάτιο οξυγόνου δεν προσφέρεται σε
; μεσαίο ή μεγάλο: θα ήταν θόλος που πληρώνεται και δεν παράγει.
; ---------------------------------------------------------------------------
rm_build:
        push    bc
        push    de
        push    hl
        ld      hl,rm_buf
        ld      b,0
        cp      R_GREENHS               ; τα φυτά δεν έχουν κανόνα μεγέθους
        jr      nz,rmb_mach
rmb_pl:
        ld      (hl),b                  ; θερμοκήπιο: όλα τα φυτά με τη σειρά
        inc     hl
        inc     b
        ld      a,b
        cp      RM_MACH
        jr      c,rmb_pl
        jr      rmb_out                 ; A = RM_MACH, CY καθαρό
rmb_mach:
        add     a,a                     ; room_machines: δύο bytes το δωμάτιο
        ld      l,a
        ld      h,0
        ld      de,G_room_machines
        add     hl,de
        ld      e,(hl)
        inc     hl
        ld      d,(hl)                  ; DE = μάσκα 12 bit
        ld      a,d
        or      e
        ld      hl,rm_buf
        jr      z,rmb_out               ; δωμάτιο χωρίς μηχανήματα: A = 0
        ld      a,(bd_param)
        push    hl
        ld      hl,rm_sbit
        add     a,l
        ld      l,a
        ld      a,0
        adc     a,h
        ld      h,a
        ld      a,(hl)
        ld      (rm_mbit),a             ; 1 << μέγεθος
        pop     hl
        ld      c,0                     ; C = πόσα μπήκαν
rmb_lp:
        ld      a,e
        and     1
        jr      z,rmb_nx
        push    de
        ld      a,b
        ld      de,G_machine_rules
        add     a,e
        ld      e,a
        ld      a,0
        adc     a,d
        ld      d,a
        ld      a,(de)
        pop     de
        push    hl
        ld      hl,rm_mbit
        and     (hl)
        pop     hl
        jr      z,rmb_nx                ; δεν χωράει σε αυτό το μέγεθος
        ld      (hl),b
        inc     hl
        inc     c
rmb_nx:
        srl     d
        rr      e
        inc     b
        ld      a,b
        cp      RM_MACH
        jr      c,rmb_lp
        ld      a,c
        or      a
        scf                             ; ζητούσε μηχανήματα· κανένα δεν χωρά
        jr      z,rmb_st
        or      a                       ; καθαρίζει το CY
rmb_out:
        ld      a,l
        sub     rm_buf & 255
rmb_st:
        ld      (rm_nbuf),a
        pop     hl
        pop     de
        pop     bc
        ret

rm_sbit:    db 1,2,4

; ---------------------------------------------------------------------------
; rm_fits — A = θέση καταλόγου δωματίων. Z αν χωράει στο τρέχον μέγεθος.
; ---------------------------------------------------------------------------
rm_fits:
        push    hl
        ld      hl,rm_list
        add     a,l
        ld      l,a
        ld      a,0
        adc     a,h
        ld      h,a
        ld      a,(hl)
        pop     hl
        call    rm_build
        ld      a,0                     ; ΟΧΙ xor: το CY είναι η απάντηση
        adc     a,0                     ; 0 = χωράει, 1 = όχι
        or      a
        ret

; ---------------------------------------------------------------------------
; rm_step — A = +1 ή -1. Προχωράει το bd_rsel στο επόμενο ΕΠΙΤΡΕΠΤΟ δωμάτιο.
; ---------------------------------------------------------------------------
rm_step:
        ld      c,a
        ld      b,RM_N
rms_lp:
        ld      a,(bd_rsel)
        add     a,c
        cp      RM_N
        jr      c,rms_st
        ; Εκτός ορίων, και οι δύο άκρες με το ίδιο cp: ακριβώς RM_N σημαίνει
        ; ότι πέρασε το τέλος, οτιδήποτε άλλο είναι το #FF της αρχής.
        jr      z,rms_zero
        ld      a,RM_N - 1
        jr      rms_st
rms_zero:
        xor     a
rms_st:
        ld      (bd_rsel),a
        call    rm_fits
        ret     z
        djnz    rms_lp
        ret                             ; κανένα δεν χωράει — αδύνατο, αλλά

; ---------------------------------------------------------------------------
; rm_fix — μετά από αλλαγή μεγέθους: αν το τρέχον δωμάτιο δεν χωράει πια,
;          προχώρα στο επόμενο που χωράει.
; ---------------------------------------------------------------------------
rm_fix:
        ld      a,(bd_kind)
        or      a                       ; BK_DOME
        ret     nz
        ld      a,(bd_rsel)
        call    rm_fits
        ret     z
        ld      a,1
        jr      rm_step

; ---------------------------------------------------------------------------
; rm_fitout — A = θόλος. Γεμίζει τις υποδοχές του με ό,τι δέχεται το δωμάτιό
;             του. ΑΠΑΙΤΕΙ ΤΡΑΠΕΖΑ 6.
;
; Το D_ROOM έχει ήδη γραφτεί από το bd_commit· εδώ διαβάζεται από την εγγραφή
; και όχι από το bd_rsel, ώστε η ίδια ρουτίνα να δουλεύει και για θόλο που
; ήρθε από αλλού. Οπου το δωμάτιο δέχεται πολλά, οι υποδοχές μοιράζονται
; ΚΥΚΛΙΚΑ πάνω στη λίστα του rm_build.
; ---------------------------------------------------------------------------
rm_fitout:
        call    ob_domeadr
        push    hl
        ld      de,D_SIZE
        add     hl,de
        ld      a,(hl)
        ld      (bd_param),a            ; το rm_build διαβάζει από εκεί
        inc     hl
        ld      a,(hl)                  ; δωμάτιο
        call    rm_build
        or      a
        jr      z,rmo_none
        ld      a,(bd_param)            ; πόσες υποδοχές έχει το μέγεθος
        ld      l,a
        ld      h,0
        ld      de,G_machine_count
        add     hl,de
        ld      b,(hl)
        pop     hl
        push    hl
        ld      de,D_MACH
        add     hl,de                   ; HL -> υποδοχή 0
        ld      c,0                     ; C = δείκτης στη λίστα
rmo_sl:
        push    bc
        ld      a,c
        ld      de,rm_buf
        add     a,e
        ld      e,a
        ld      a,0
        adc     a,d
        ld      d,a
        ld      a,(de)
        ld      (hl),a                  ; η μηχανή (ή το φυτό)
        push    hl
        ld      de,D_HEALTH - D_MACH
        add     hl,de
        ld      (hl),200                ; καινούργια, γερή
        pop     hl
        inc     hl
        pop     bc
        inc     c
        ld      a,(rm_nbuf)
        cp      c
        jr      nz,rmo_sn
        ld      c,0                     ; κυκλικά
rmo_sn:
        djnz    rmo_sl
rmo_none:
        pop     hl
        ret

rm_mbit:    db 1
rm_nbuf:    db 0
rm_buf:     defs RM_MACH
