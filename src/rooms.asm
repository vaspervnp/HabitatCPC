; rooms.asm — τι ΕΙΝΑΙ ένας θόλος, και τι κάθεται μέσα του (DESIGN §6.1, §6.5)
;
; Ως το βήμα 25 το bd_commit έγραφε «δωμάτιο: κενό ως την επιλογή» και οκτώ
; NO_MACH, και επιλογή δεν υπήρχε πουθενά: ό,τι έχτιζε ο παίκτης μετά την
; αρχική αποικία ήταν κέλυφος. Μετρημένο στο tools/balance.py — κάθε γραμμή
; παιχνιδιού που έλυνε το νερό τελείωνε στην ΤΡΟΦΗ, και η τροφή θέλει
; θερμοκήπιο και mach_food, δηλαδή θόλο με δωμάτιο.
;
; Η ΕΠΙΛΟΓΗ ΓΙΝΕΤΑΙ ΣΤΟΝ ΚΑΤΑΛΟΓΟ, ΟΧΙ ΜΕΤΑ. Ενα δεύτερο μενού πάνω σε
; χτισμένο θόλο θα ήθελε δική του κατάσταση διεπαφής, δικό του φάντασμα και
; δικό του «ποιον θόλο δείχνεις». Δεξιά-αριστερά διαλέγει μέγεθος, πάνω-κάτω
; διαλέγει δωμάτιο: δύο άξονες στο ίδιο μενού, καμία καινούργια κατάσταση.
;
; ΤΟ ΔΩΜΑΤΙΟ ΛΕΕΙ ΤΙ ΧΩΡΑΕΙ, Ο ΠΑΙΚΤΗΣ ΤΙ ΜΠΑΙΝΕΙ (βήμα 45). Το
; assets/SPRITES.md §6 λέει ποια μηχανήματα δέχεται κάθε δωμάτιο
; (`room_machines`, μάσκα 12 bit) και σε ποια μεγέθη χωράει το καθένα
; (`machine_rules`): το rm_build φτιάχνει από αυτά τη λίστα που βλέπει ο
; εξοπλισμός (src/fit.asm). Ως το βήμα 44 ο θόλος γέμιζε μόνος του, κυκλικά
; πάνω στη λίστα — ένα μεγάλο εργοστάσιο έβγαζε σίδερο, βιοπλαστικό, όπλα,
; ρομπότ και ανταλλακτικά, και ο παίκτης δεν μπορούσε να ζητήσει οκτώ ίδια.

RM_N        equ 10                      ; πόσα δωμάτια προσφέρει ο κατάλογος
RM_MACH     equ 12                      ; MACH_TYPES / PLANT_TYPES
        assert  FIT_MAX == 1 + RM_MACH          ; η λίστα του εξοπλισμού (fit.asm)

; Η σειρά είναι η σειρά που τα χρειάζεσαι: αέρας, φαγητό, ύπνος, και μετά τα
; υπόλοιπα. Το πρώτο επιτρεπτό είναι και το προεπιλεγμένο.
rm_list:
        db R_OXYGEN, R_CANTEEN, R_QUARTERS, R_GREENHS, R_FACTORY
        db R_LAB, R_MEDBAY, R_CONTROL, R_STORAGE, R_LOUNGE
rm_names:
        dw t_r_oxy, t_r_can, t_r_qrt, t_r_grn, t_r_fac
        dw t_r_lab, t_r_med, t_r_ctl, t_r_sto, t_r_lng

; ---------------------------------------------------------------------------
; rm_room — Out: A = το δωμάτιο που δείχνει το bd_rsel.
; rm_at   — A = θέση καταλόγου -> A = δωμάτιο. Κρατά τα BC, DE.
; ---------------------------------------------------------------------------
rm_room:
        ld      a,(bd_rsel)
rm_at:
        ld      hl,rm_list
        add     a,l
        ld      l,a
        adc     a,h
        sub     l
        ld      h,a
        ld      a,(hl)
        ret

; ---------------------------------------------------------------------------
; rm_name — Out: HL = το κείμενο (τράπεζα 7) του τρέχοντος δωματίου.
; ---------------------------------------------------------------------------
rm_name:
        ld      a,(bd_rsel)
        add     a,a
        ld      hl,rm_names
        add     a,l
        ld      l,a
        adc     a,h
        sub     l
        ld      h,a
        ld      a,(hl)
        inc     hl
        ld      h,(hl)
        ld      l,a
        ret

; ---------------------------------------------------------------------------
; rm_build — A = δωμάτιο. Γεμίζει το rm_buf με ό,τι επιτρέπεται εκεί μέσα, στο
;            τρέχον μέγεθος (bd_param, 0..2). Κρατά τα BC, DE, HL.
;
;   Out: A = (rm_nbuf) = πόσα· CY αν το δωμάτιο ΘΕΛΕΙ μηχανήματα αλλά κανένα
;        δεν χωράει στο μέγεθος. Χωρίς CY και με μηδέν, το δωμάτιο απλώς δεν
;        έχει μηχανήματα (κατάλυμα, αποθήκη, σαλόνι) — αυτό επιτρέπεται.
;
; Ενας βρόχος, δύο δουλειές: ο κατάλογος τον ρωτά «χωράει;» και το χτίσιμο τον
; ρωτά «τι βάζω μέσα;». Το mach_oxygen μπαίνει ΜΟΝΟ σε μικρό θόλο
; (machine_rules bit0, §6.5), άρα το δωμάτιο οξυγόνου δεν προσφέρεται σε
; μεσαίο ή μεγάλο: θα ήταν θόλος που πληρώνεται και δεν παράγει.
; ---------------------------------------------------------------------------
rm_build:
        push    bc
        push    de
        push    hl
        cp      R_GREENHS               ; τα φυτά δεν έχουν κανόνα μεγέθους
        jr      nz,rmb_mach
        ld      hl,rm_plants            ; θερμοκήπιο: με σειρά ΚΛΑΣΗΣ (βλ. κάτω)
        ld      de,rm_buf
        ld      bc,RM_MACH
        ldir                            ; το CY μένει καθαρό από το cp
        ld      a,RM_MACH
        jr      rmb_st
rmb_mach:
        ld      c,a
        add     a,a                     ; room_machines: δύο bytes το δωμάτιο
        add     a,G_room_machines & 255
        ld      l,a
        ld      h,G_room_machines >> 8
        ld      e,(hl)
        inc     l
        ld      d,(hl)                  ; DE = μάσκα 12 bit
        ld      a,d
        or      e
        jr      z,rmb_st                ; δωμάτιο χωρίς μηχανήματα: A = 0, NC
        ld      a,c
        ld      hl,rm_pref
        call    ob_addu
        ld      a,(hl)
        push    af                      ; η κύρια μηχανή, για το τέλος
        ld      a,(bd_param)
        ld      c,a
        srl     c
        inc     a
        add     a,c
        ld      (rm_mbit),a             ; 1 << μέγεθος: 1, 2, 4
        ld      hl,rm_buf
        ld      bc,RM_MACH * 256        ; B = γύροι, C = μηχανή
rmb_lp:
        srl     d
        rr      e
        jr      nc,rmb_nx               ; δεν τη δέχεται το δωμάτιο
        push    hl
        ld      a,c
        add     a,G_machine_rules & 255
        ld      l,a
        ld      h,G_machine_rules >> 8
        ld      a,(rm_mbit)
        and     (hl)
        pop     hl
        jr      z,rmb_nx                ; δεν χωράει σε αυτό το μέγεθος
        ld      (hl),c
        inc     hl
rmb_nx:
        inc     c
        djnz    rmb_lp
        pop     de                      ; D = η κύρια μηχανή, 255 αν δεν έχει
        ld      a,l
        sub     rm_buf & 255            ; πόσα
        scf                             ; ζητούσε μηχανήματα· κανένα δεν χωρά
        jr      z,rmb_st
        ld      (rm_nbuf),a
        ; --- Η ΚΥΡΙΑ ΜΗΧΑΝΗ ΤΟΥ ΔΩΜΑΤΙΟΥ ΠΑΙΡΝΕΙ ΤΗΝ ΥΠΟΔΟΧΗ 0: αν μπήκε, όσες
        ; μπήκαν πριν από αυτήν πάνε μία θέση πίσω ---
        ld      c,a                     ; BC = πόσα (το B είναι 0 μετά το djnz)
        ld      a,d
        ld      hl,rm_buf
        cpir
        jr      nz,rmb_ok               ; δεν τη δέχεται, δεν χωρά, ή δεν έχει
        dec     hl
        ld      a,l
        sub     rm_buf & 255            ; η θέση της
        jr      z,rmb_ok                ; ήδη πρώτη
        ld      c,a
        ld      a,(hl)
        ld      d,h
        ld      e,l
        dec     hl
        lddr
        ld      (de),a
rmb_ok:
        ld      a,(rm_nbuf)
        or      a                       ; καθαρίζει το CY
rmb_st:
        ld      (rm_nbuf),a
        pop     hl
        pop     de
        pop     bc
        ret

; ΠΟΙΑ ΜΗΧΑΝΗ ΠΑΙΡΝΕΙ ΤΗΝ ΥΠΟΔΟΧΗ 0, ανά δωμάτιο. Οχι διακόσμηση: μια μηχανή
; τρέχει μόνο αν η υποδοχή της είναι μικρότερη από το πλήθος των χειριστών
; (§6.5), άρα σε δωμάτιο με έναν άνθρωπο μέσα τρέχει ΜΟΝΟ η υποδοχή 0. Με την
; αριθμητική σειρά της room_machines το εργαστήριο έβγαζε επεξεργαστές — που
; τους φτιάχνει και το control — και ΠΟΤΕ vitromeat, οπότε η αλυσίδα της
; τροφής ήταν άφτιαχτη σε κάθε μέτρηση του tools/balance.py. Κανόνας: πρώτη η
; μηχανή που δεν τη φτιάχνει κανένα άλλο δωμάτιο.
rm_pref:
        db 255, 255, 255, 255, 255, 255      ; empty..greenhouse
        db 255, 255                          ; storage, airlock
        db 1                                 ; factory   -> iron
        db 9                                 ; lab       -> vitromeat
        db 10                                ; medbay    -> beds
        db 255                               ; lounge

; ΚΑΙ ΤΑ ΦΥΤΑ ΜΕ ΤΗΝ ΙΔΙΑ ΛΟΓΙΚΗ. Το plant_class δίνει 0-4 άμυλο, 5-9
; λαχανικά, 10 φάρμακα, 11 δέντρο· με τη σειρά της αρίθμησης ένα μεσαίο
; θερμοκήπιο φύτευε τέσσερα αμυλούχα και κανένα λαχανικό, και το mach_food
; θέλει άμυλο ΚΑΙ λαχανικά ΚΑΙ vitromeat. Εναλλαγή κλάσεων, με άλλη ποικιλία
; σε κάθε γύρο ώστε να μη φυτρώνει τέσσερις φορές το ίδιο sprite. ΟΙ
; ΤΕΣΣΕΡΙΣ ΠΡΩΤΕΣ είναι η πρώτη ποικιλία κάθε κλάσης, και το fit_new τις
; διαβάζει ως τέτοιες.
rm_plants:  db 0, 5, 10, 11, 1, 6, 2, 7, 3, 8, 4, 9

; ---------------------------------------------------------------------------
; rm_fits — A = θέση καταλόγου δωματίων. Z αν χωράει στο τρέχον μέγεθος.
; Κρατά τα BC, DE.
; ---------------------------------------------------------------------------
rm_fits:
        call    rm_at
        call    rm_build
        sbc     a,a                     ; CY -> #FF, NZ: δεν χωράει
        ret

; ---------------------------------------------------------------------------
; rm_step — A = +1 ή -1. Προχωράει το bd_rsel στο επόμενο ΕΠΙΤΡΕΠΤΟ δωμάτιο.
; ---------------------------------------------------------------------------
rm_step:
        ld      c,a
        ld      b,RM_N
rms_lp:
        ld      a,(bd_rsel)
        add     a,c
        cp      RM_N
        jr      c,rms_st
        ; Εκτός ορίων, και οι δύο άκρες με το ίδιο cp: ακριβώς RM_N σημαίνει
        ; ότι πέρασε το τέλος, οτιδήποτε άλλο είναι το #FF της αρχής.
        ld      a,RM_N - 1
        jr      nz,rms_st
        xor     a
rms_st:
        ld      (bd_rsel),a
        call    rm_fits
        ret     z
        djnz    rms_lp
        ret                             ; κανένα δεν χωράει — αδύνατο, αλλά

; ---------------------------------------------------------------------------
; rm_fix — μετά από αλλαγή μεγέθους: αν το τρέχον δωμάτιο δεν χωράει πια,
;          προχώρα στο επόμενο που χωράει.
; ---------------------------------------------------------------------------
rm_fix:
        ld      a,(bd_kind)
        or      a                       ; BK_DOME
        ret     nz
        ld      a,(bd_rsel)
        call    rm_fits
        ret     z
        ld      a,1
        jr      rm_step

        ; Στοίχιση 16: τα 15 bytes από εδώ ως το τέλος του rm_buf δεν πατούν ποτέ
        ; αλλαγή σελίδας, όπου κι αν πέσει ο κώδικας (το assert από κάτω έσπασε
        ; στο βήμα 83, όταν η τράπεζα 0 κατέβηκε κατά τους χειριστές της διακοπής).
        align   16
rm_mbit:    db 1
rm_nbuf:    db 0
            db NO_MACH              ; ΤΟ ΑΔΕΙΟ ΠΡΙΝ ΑΠΟ ΤΗ ΛΙΣΤΑ: ο εξοπλισμός
rm_buf:     defs RM_MACH            ; (fit_enter) αντιγράφει από το rm_buf - 1
        assert  FIT_MAX == RM_MACH + 1          ; το ΑΔΕΙΟ και ως 12 μηχανές
        assert  (rm_buf & 255) + RM_MACH <= 256 ; το πλήθος από το κάτω byte
        assert  (G_room_machines & 255) + 2 * (R_LOUNGE + 1) <= 256
        assert  (G_machine_rules & 255) + RM_MACH <= 256
