; commit.asm — ό,τι βάζει η τοποθέτηση γύρω από το νέο κτίσμα (βήμα 94).
;
; ΖΕΙ ΣΤΗΝ ΤΡΑΠΕΖΑ 1, στη δέσμευση b1code πάνω από τα εικονίδια m και l
; (#7F60, 160 bytes). Η τράπεζα 1 είναι η προεπιλογή του παραθύρου: το UI
; τρέχει με αυτήν μέσα, και ό,τι καλεί από εδώ τη γυρίζει πίσω πριν από το
; ret — το al_node και το al_w4 (src/link.asm), το lk_ground, το cr_link_bc, το
; view_rect. Κανένα δεν αφήνει άλλη τράπεζα μέσα, γιατί τότε ο κώδικας εδώ θα
; είχε χαθεί κάτω από τα πόδια του. Οι ρουτίνες ανά tile (al_cbs, al_cbr) που
; καλούνται ΜΕ την τράπεζα 4 μέσα μένουν στην 2.
;
; Ως το βήμα 93 όλα αυτά ήταν στο src/link.asm, στην τράπεζα 2, που είχε 8
; bytes. Το βήμα 94 ήθελε εκεί να ζωγραφίζονται οι συνδέσεις εδάφους, να μη
; στρώνονται θεμέλια κάτω από τους θόλους και να δημοσιεύεται η γεώτρηση.
;
; Στη ΔΟΚΙΜΑΣΤΙΚΗ έκδοση του UI (tests/uitest.asm) το αρχείο μπαίνει μαζί με τα
; υπόλοιπα: εκεί η 1 δεν έχει τίποτα δικό της, και οι κλήσεις είναι απόλυτες.

B1C_MAX     equ 160                     ; = B1C_MAX του tools/pack.py

; ---------------------------------------------------------------------------
; al_commit — μετά από ένα bd_commit που πέτυχε: οι διάδρομοι ή το μονοπάτι
; που έδειξε το φάντασμα. Οι διάδρομοι μπαίνουν με το cr_commit (σφραγίδα,
; πληρωμή με την τιμή του καταλόγου ανά πλακίδιο, ακμή) και ζωγραφίζονται με
; το cr_redraw· το μονοπάτι γίνεται θεμέλιο, ακμή, και ζωγραφίζεται εδώ.
; ---------------------------------------------------------------------------
al_commit:
        ld      a,(al_pt)
        inc     a
        jr      nz,alc_pth
        ; --- ΤΟ ΠΕΡΠΑΤΗΜΑ ΣΤΟ ΕΔΑΦΟΣ (βήμα 87): ένα εργοτάξιο δεν έχει αέρα,
        ; άρα φτάνεις σε αυτό από έξω. Ο,τι δεν έχει μονοπάτι — θόλος, airlock,
        ; η πρώτη δομή — παίρνει σύνδεση εδάφους ως το κοντινότερο airlock ή
        ; το σκάφος. Ο θόλος τη χάνει όταν τελειώσει (lk_done)· το airlock την
        ; κρατά, γιατί είναι η πόρτα. (Το al_plan αφήνει το al_pt στο 255 για
        ; ό,τι δεν είναι δομή με μονοπάτι.)
        ld      a,(bd_node)
        ld      b,a
        call    lk_ground               ; και το al_pt = η άλλη άκρη
        call    alc_cor                 ; οι διάδρομοι (src/link.asm)
        ; ΚΑΙ ΖΩΓΡΑΦΙΖΕΤΑΙ (βήμα 94, ο παίκτης: «το sprite για τις βάσεις
        ; χρησιμοποίησέ το για τους εξωτερικούς διαδρόμους»). Του airlock και
        ; της πρώτης δομής, που μένουν· όχι του θόλου, που φεύγει όταν
        ; τελειώσει και θα άφηνε πίσω του ένα μονοπάτι προς το πουθενά. ΜΕΤΑ
        ; από τους διαδρόμους: ο διάδρομος ενός airlock πιάνει τα tiles του, και
        ; το Γ που συχνά περνά από εκεί δεν τα κάνει θεμέλιο από κάτω του.
        ld      a,(bd_kind)
        or      a                       ; BK_DOME
        call    nz,lk_draw
        ld      a,255                   ; το φάντασμα δεν έχει πια μονοπάτι
        ld      (al_pt),a
        ret

; lk_draw — η σύνδεση εδάφους ως το al_pt: ένα Γ, πρώτα κατά x, από το
; κεντρικό tile του νέου ως το κεντρικό tile της άλλης άκρης. Γίνεται θεμέλιο
; ΜΟΝΟ ό,τι είναι ελεύθερο έδαφος που χτίζεται (al_cbr): το νερό, το βουνό, ο
; κρατήρας και κάθε κτίσμα που βρεθεί στον δρόμο μένουν ως έχουν, και το
; μονοπάτι περνά από πάνω τους χωρίς να φαίνεται — όπως περπατάνε κι οι
; άποικοι. Χωρίς όριο μήκους: η σύνδεση εδάφους δεν είχε ποτέ.
;
; ΣΚΕΛΟΣ-ΣΚΕΛΟΣ, ΚΑΙ ΜΟΝΟ Ο,ΤΙ ΑΛΛΑΞΕ ΞΑΝΑΖΩΓΡΑΦΙΖΕΤΑΙ: από το πρώτο ως το
; τελευταίο tile που έγινε θεμέλιο. Το Γ ενός airlock περνά συχνά μέσα από την
; αποικία — κυλικείο, θόλος οξυγόνου, οι διάδρομοί τους — όπου δεν αλλάζει
; τίποτα, και ολόκληρο το σκέλος ξαναζωγραφισμένο ανέβαζε το FIRE από 149 σε
; 223 ms (tests/test_reach.py, όριο 200).
lk_draw:
        ld      a,(al_pt)
        inc     a
        ret     z                       ; καμία άκρη: τίποτα να δεθεί
        dec     a
        call    al_node                 ; το αποτύπωμά της και το al_q
        xor     a
        ld      (al_ori),a              ; πρώτα κατά x
        ld      hl,al_cbr
        jr      alc_legs

alc_pth:
        ld      a,(bd_node)
        ld      b,a
        ld      a,(al_pt)
        ld      c,a
        call    lk_keepp                ; το Γ κρατιέται (βήμα 102), και η ακμή
        ld      hl,al_cbs
        call    al_lgo
        ; ΜΟΝΟ ΤΑ TILES ΤΟΥ ΜΟΝΟΠΑΤΙΟΥ, σκέλος-σκέλος. Το ορθογώνιο κέντρο-γωνία-
        ; κέντρο έπιανε και κομμάτια των δύο αποτυπωμάτων, και ο ηλιακός
        ; πλήρωνε 68 ms στο FIRE για να ξαναζωγραφίσει τον θόλο απέναντι. Τα
        ; tiles ενός σκέλους είναι στη σειρά, οπότε το πρώτο και το τελευταίο
        ; τους είναι το ορθογώνιό του. Το autotile των γειτόνων δεν αλλάζει:
        ; το μονοπάτι πατά μόνο έδαφος, σκόνη ή θεμέλιο, που δεν μετρούν.
        ld      hl,al_cbb
; alc_legs — HL = ρουτίνα ανά tile που κρατά το πρώτο και το τελευταίο tile του
; σκέλους (al_cbb, al_cbr): τα δύο σκέλη του Γ, το καθένα ξαναζωγραφισμένο.
alc_legs:
        ld      (al_cb),hl
        call    al_k
        push    hl
        call    al_leg                  ; P..K
        pop     bc
        ld      hl,(al_q)               ; K..Q
; al_leg — ένα σκέλος από το (B, C) ως το (H, L): τα tiles του που κράτησε η
; ρουτίνα, ξαναζωγραφισμένα, αν κράτησε κανένα.
al_leg:
        xor     a
        ld      (al_en),a
        call    al_s4                   ; με την τράπεζα 4 μέσα (src/link.asm)
        ld      a,(al_en)
        or      a
        ret     z
        ld      bc,(al_ef)
        ld      hl,(al_el)
; al_vr — το ορθογώνιο από το (B, C) ως το (H, L), ξαναζωγραφισμένο.
al_vr:
        ld      a,h
        sub     b
        jp      p,alv_x
        neg
        ld      b,h
alv_x:
        inc     a
        ld      (vr_w),a
        ld      a,b
        ld      (vr_tx),a
        ld      a,l
        sub     c
        jp      p,alv_y
        neg
        ld      c,l
alv_y:
        inc     a
        ld      (vr_h),a
        ld      a,c
        ld      (vr_ty),a
; alv_jp — η κατεδάφιση (βήμα 102, src/dm_ovl.asm) γράφει εδώ για λίγο μια
; δική της ρουτίνα: τα σκέλη μιας σύνδεσης εδάφους που ξαναδένεται πάνε στη
; λίστα της, και ζωγραφίζονται ένα ανά πέρασμα όπως τα άλλα ορθογώνια της.
alv_jp:
        jp      view_rect

; al_lgo — HL = ρουτίνα ανά tile: το μονοπάτι που διαλέχτηκε, με την 4. Και
; για το φάντασμα (al_ghost, από το ui_show). Εδώ από το βήμα 94, για να χωρέσει
; στην τράπεζα 2 η μάσκα της ανάθεσης (jb_open, src/drill.asm): δεν σελιδοποιεί
; η ίδια, και το al_node και το al_w4 γυρίζουν με την 1. ΣΤΟ ΤΕΛΟΣ: το
; alc_legs πέφτει στο al_leg χωρίς άλμα, και ανάμεσά τους δεν χωρά τίποτα.
al_lgo:
        ld      (al_cb),hl
        ld      a,(al_po)
        ld      (al_ori),a
        ld      a,(al_pt)
        call    al_node
        jp      al_w4
