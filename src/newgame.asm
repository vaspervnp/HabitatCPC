; newgame.asm — η κατάσταση εκκίνησης του §10.1.
;
; Ως το βήμα 12 αυτό δεν υπήρχε: κάθε δοκιμή έστηνε τον κόσμο της μόνη της, και
; κάθε μία ξεχνούσε κάτι διαφορετικό. Το χειρότερο ήταν ο πίνακας εργασιών —
; το άδειο είναι 255 ενώ το μηδέν σημαίνει «εργασία Build», οπότε ένας πίνακας
; που δεν αρχικοποιήθηκε διαβάζεται ως τριάντα δύο εργασίες Build.
;
; Η ΓΕΝΝΗΤΡΙΑ ΔΕΝ ΕΙΝΑΙ ΕΔΩ. Δεν χωράει: ο κώδικας του παιχνιδιού πιάνει 15,9 KB
; από τα 16,1 της τράπεζας 0 και η γεννήτρια θέλει άλλα 2,9. Είναι ξεχωριστό
; φόρτωμα — τρέχει, γράφει το επίπεδο στην τράπεζα 4, και μετά φορτώνεται το
; παιχνίδι από πάνω της. Δες DESIGN §4.2.

M_OXYGEN    equ 0

NG_SEED     equ #ACE1
; οι πίνακες οντοτήτων της τράπεζας 6, ένα συνεχές μπλοκ (src/layout), από
; τους θόλους ως το τέλος της τράπεζας (βήμα 172: ως τότε από τους πράκτορες ως
; το worldinfo, και ως το βήμα 154 ως το τέλος των διαδρόμων, που πήγαν στην 5)
NG_B6_LEN   equ #8000 - G_dome_tbl

; ---------------------------------------------------------------------------
; game_new — από το μηδέν ως το πρώτο frame.
;
; ΜΙΑ ΡΟΗ (βήμα 74): το σκούπισμα, η αποικία, οι άνθρωποι και τα αποθέματα
; ήταν τέσσερις ρουτίνες με έναν καλούντα, αυτόν εδώ. Η σειρά είναι η ίδια.
; ---------------------------------------------------------------------------
game_new:
        ; --- κάθε πίνακας στην τιμή που σημαίνει «άδειο», και αυτή ΔΕΝ είναι
        ; πάντα το μηδέν. Η οικονομία και ο γράφος: τράπεζα 2, πάντα ορατή.
        ; ΟΛΗ, ως τις προσγειώσεις του βήματος 111 (EC_LANDS· ως το 110 ως τα
        ; ορυχεία του 94, EC_MINES· ως το 93 ως το τέλος
        ; του φορτίου του εμπόρου, ως το 92 ως το EC_NBUILD, και το φορτίο θα
        ; έμενε από την προηγούμενη παρτίδα — tests/test_newgame.py). Ως το
        ; βήμα 88 86 bytes: τα πέντε της βροχής μετεωριτών (βήμα 38, +86..+90)
        ; έμεναν κι αυτά.
        ld      hl,G_econ_state
        ld      bc,EC_LANDS - G_econ_state
        call    ng_zero
        ld      hl,NODE_DEG
        ld      bc,127
        call    ng_zero
        ; --- τα LK_OWN (src/link.asm): «τίποτα», όχι 0, που είναι η σύνδεση
        ; εδάφους ως το σκάφος (βήμα 154) ---
        ld      hl,LK_OWN
        ld      (hl),LKO_NONE
        ld      bc,MAX_STRUCT - 1
        call    ng_dup
        ; --- ο πίνακας εργασιών: 255, όχι 0 ---
        ld      hl,G_job_tbl
        ld      de,JOB_REC
        ld      a,NO_JOB
        ld      b,MAX_JOB
ngw_job:
        ld      (hl),a
        add     hl,de
        djnz    ngw_job
        ; --- οι πίνακες οντοτήτων: ΕΝΑ μπλοκ στην τράπεζα 6, από τους θόλους
        ; ως το τέλος της τράπεζας (τα assert στο τέλος).
        ld      bc,GA_PORT + PAGE_B6
        out     (c),c
        ld      hl,G_dome_tbl
        ld      bc,NG_B6_LEN - 1
        call    ng_zero
        ; Τρεις στήλες πρακτόρων θέλουν 255, όχι 0: μια θέση 0 σημαίνει «στην
        ; πρώτη θέση του δακτυλίου», μια ακμή 0 «στον δρόμο για τον πρώτο
        ; γείτονα», και μια εργασία 0 «κρατάει την εργασία μηδέν». Είναι τρεις
        ; διαδοχικές σελίδες: AG_SLOT, AG_EDGE, AG_TASK (ως το βήμα 171 οι
        ; στήλες +128 των AG_NODE, AG_DEST, AG_PROG). Οι N_AGENT (188· 128 ως
        ; το βήμα 172), όχι η σελίδα: η ουρά της πρώτης από το 192 είναι η
        ; στήλη 1 του DF_PG (src/object.asm).
        ld      hl,AG_SLOT
        ld      c,3                     ; το A είναι ακόμη 255
ngw_ff:
        ld      b,N_AGENT
ngw_fl:
        ld      (hl),a
        inc     l
        djnz    ngw_fl
        ld      l,b                     ; 0
        inc     h                       ; η επόμενη σελίδα
        dec     c
        jr      nz,ngw_ff
        ; --- οι διάδρομοι, στην τράπεζα 5 από το βήμα 154: CT_EMPTY, όχι 0, και
        ; μία εγγραφή ακόμη, που μένει άδεια (το dmk_lp κοιτάζει την επόμενη) ---
        call    asc_b5
        ld      hl,G_corr_tbl
        ld      (hl),CT_EMPTY
        ld      bc,(MAX_CORR + 1) * CORR_REC - 1
        call    ng_dup
        call    asc_b6

; --- ΑΔΕΙΑ ΑΡΧΗ (βήμα 87): μόνο το σκάφος, οι άνθρωποι και τα αποθέματα --
;
; Ο παίκτης χτίζει τα πάντα, και το πρώτο του κτίσμα το φτάνουν από το σκάφος
; (lk_ground, src/link.asm). Η αποικία των βημάτων 12-86 μένει πιο κάτω ως
; ΑΠΟΙΚΙΑ ΔΟΚΙΜΩΝ: τη στήνει μόνο ένα ng_colony = 1, που το γράφουν τα tests
; στο build/colony.sna (tests/test_game.py). Το παιχνίδι δεν το αγγίζει ποτέ.
        ld      a,(ng_colony)
        or      a
        jp      nz,ngt_colony           ; src/colony.asm

; --- ΤΟ ΣΚΑΦΟΣ: η δομή 0, κόμβος 64, στο (0, 0). Δεν είναι κτίριο — δεν
; χτίζεται, δεν είναι «κοντά» (al_scans), δεν το χτυπά μετεωρίτης — αλλά
; ζωγραφίζεται σαν δομή και πιάνει τα 2x2 tiles του: κατοχή, όχι θεμέλιο. ---
ng_ship:
        ld      hl,ng_shiprec           ; η τράπεζα 6 είναι μέσα από το σκούπισμα
        ld      de,G_struct_tbl
        call    ngc_rec                 ; 0, 0, K_SHIP, 0, DS_ACTIVE, 255
        ld      bc,GA_PORT + PAGE_B4
        out     (c),c
        ld      bc,#FFFF                ; το tile (-1, -1)
        call    tile_addr
        set     4,(hl)                  ; W_OCC_STRUCT
        inc     hl
        set     4,(hl)
        ld      de,127
        add     hl,de                   ; η επόμενη σειρά (tile_addr)
        set     4,(hl)
        inc     hl
        set     4,(hl)
        ld      bc,GA_PORT + PAGE_B6
        out     (c),c
        ld      de,ng_crew
        ld      a,F_ALIVE               ; έξω, δίπλα στο σκάφος

        ; --- έξι άποικοι: τέσσερις εργάτες, ένας μηχανικός, μία βιολόγος
        ; (βήμα 120· ως τότε τέσσερις). DE = ζευγάρια (ρόλος, κόμβος) ως το
        ; 255, ώστε η αποικία δοκιμών να κρατά τους τέσσερις της. ---
ng_people:
        ld      (ng_r),a                ; οι σημαίες τους
        ld      c,0                     ; ο πράκτορας
ngp_lp:
        ld      h,AG_PG
        ld      l,c
        ld      a,(ng_r)
        ld      (hl),a
        set     3,h                     ; AG_ROLE
        ld      a,(de)
        inc     de
        ld      (hl),a                  ; ρόλος
        ld      a,(de)
        inc     de
        res     3,h
        inc     h
        ld      (hl),a                  ; κόμβος
        inc     h
        ld      (hl),a                  ; προορισμός = εκεί που είναι
        push    bc
        push    de
        call    ent_claim               ; A = κόμβος -> A = θέση
        pop     de
        pop     bc
        ld      h,AG_SLOT >> 8
        ld      l,c
        ld      (hl),a                  ; η θέση στον δακτύλιο
        ; οι ανάγκες γεμάτες, και τα δύο πεδία τριών σελίδων: ένας άποικος
        ; που ξεκινά στο μηδέν πεθαίνει πριν προλάβει να περπατήσει ως το ψυγείο.
        ld      h,AG_WATER >> 8
        ld      b,3
ngp_n:
        ld      (hl),255
        res     3,h
        ld      (hl),255
        set     3,h
        inc     h
        djnz    ngp_n
        res     3,h                     ; AG_SUIT
        ld      (hl),SUIT_START         ; δέκα λεπτά αέρα στην αρχή (βήμα 90)
        inc     c
        ld      a,(de)
        inc     a
        jr      nz,ngp_lp
        ; ΤΑ ΣΥΜΒΑΝΤΑ ΑΠΟ ΤΟΝ ΣΠΟΡΟ ΤΟΥ ΚΟΣΜΟΥ (βήμα 120· ως τότε πάντα #ACE1).
        ; Ο παίκτης του tools/play.py είδε την ίδια βλάβη του θόλου 0 στο sol
        ; 4,44 και την ίδια βροχή μετεωριτών στο 10,5 σε κάθε κόσμο: κάθε
        ; παιχνίδι από τον δίσκο είχε το ίδιο σενάριο καταστροφών. Το seed
        ; μένει στην τράπεζα 6 από τη γεννήτρια (src/gen.asm)· το main.sna και
        ; οι δοκιμές δεν την τρέχουν, βρίσκουν μηδέν, και κρατούν το #ACE1.
        ld      hl,(G_worldinfo)
        ld      a,h
        or      l
        jr      nz,ngp_seed
        ld      hl,NG_SEED              ; το μηδέν είναι απορροφητικό στο LFSR
ngp_seed:
        ld      (EC_RND),hl
        ld      bc,GA_PORT + PAGE_B1
        out     (c),c

        ; --- τα αποθέματα του §10.1, το ρολόι, και ό,τι άλλο δεν ξεκινά από το
        ; μηδέν: ζευγάρια (χαμηλό byte διεύθυνσης, τιμή) στη σελίδα της οικονομίας.
        ; Η αποικία δοκιμών ξαναγράφει μετά τα δικά της.
        ld      hl,ng_econ
        ld      b,(ng_econ_end - ng_econ) / 2
        call    nge_set
        ld      a,(ng_colony)
        or      a
        ld      b,(ng_econ_col_end - ng_econ_end) / 2   ; από εκεί που έμεινε
        call    nz,nge_set
        call    wheel_reset
        call    rt_mark
        jp      ui_init

; nge_set — HL = ζευγάρια (χαμηλό byte, τιμή), B = πόσα. HL μετά το τελευταίο.
nge_set:
        ld      d,G_econ_state >> 8
nge_lp:
        ld      e,(hl)
        inc     hl
        ld      a,(hl)
        inc     hl
        ld      (de),a
        djnz    nge_lp
        ret

; ngc_rec — HL = πρότυπο (cx, cy, και δύο bytes), DE = εγγραφή: τα τέσσερα,
; και DS_ACTIVE, 255 (ακεραιότητα: χτισμένο). HL += 4, DE += 6.
ngc_rec:
        ld      bc,4
        ldir
        ex      de,hl
        ld      (hl),DS_ACTIVE
        inc     hl
        ld      (hl),255
        inc     hl
        ex      de,hl
        ret

; (το ng_zero ζει στο src/hw.asm από το βήμα 101: το hw_clear είναι η αρχή του)

; --- δεδομένα --------------------------------------------------------------
; και στην άδεια αρχή, όλοι στο σκάφος (κόμβος 64)
ng_crew:
        db 0, MAX_DOME
        db 0, MAX_DOME
        db 1, MAX_DOME
        db 2, MAX_DOME
        db 0, MAX_DOME                  ; και δύο εργάτες ακόμη (βήμα 120): ο
        db 0, MAX_DOME                  ; χρήστης, αντί για όριο στην παραγωγή
        db 255
; το σκάφος: cx, cy, είδος, μέγεθος (ngc_rec)
ng_shiprec:
        db 0, 0, K_SHIP, 0
; 1 = η αποικία δοκιμών· μόνο τα tests το γράφουν (build/colony.sna)
ng_colony:  db 0
ng_r:       db 0                ; οι σημαίες των αποίκων· η ακτίνα στο colony.asm

; ΜΕΤΑΛΛΟ 75, ΒΙΟΠΛΑΣΤΙΚΟ 45 ΚΑΙ ΕΞΗΝΤΑ ΜΕΤΑΛΛΕΥΜΑ — όχι 30 και 10 (§10.1).
; Δύο πράγματα αγοράζουν αυτά τα νούμερα, και τα δύο μετρημένα στο
; tools/balance.py:
;
;   * ΤΗΝ ΕΠΙΒΙΩΣΗ. Ηλιακό (15) για το οξυγόνο της ημέρας, αντλία (22) για το
;     νερό, συλλέκτη (14) για τη νύχτα — ο ήλιος λείπει το 40% του sol (§6.10).
;     Με τα 30 του §10.1 ο παίκτης αγόραζε ΕΝΑ κτίσμα και πέθαινε ως το sol 5.
;     Με 75 χωρούν και τα τρία συν ένα μικρό εργοστάσιο (20): τέσσερα
;     κτίσματα και τέλος.
;   * ΚΑΙ ΤΗΝ ΑΡΧΗ ΤΗΣ ΒΙΟΜΗΧΑΝΙΑΣ. Το μετάλλευμα είναι το έρμα του σκάφους:
;     μετρημένο, ένα μικρό εργοστάσιο το φάγανε όλο ως το sol 4 και έβγαλε 30
;     μέταλλο — δύο μετάλλευμα το ένα — δηλαδή 18 -> 48, που είναι ένα ορυχείο
;     (30) και ρέστα. Χωρίς αυτό η αποικία ζούσε αλλά ΔΕΝ μεγάλωνε ποτέ: καμία
;     μηχανή της δεν φτιάχνει μέταλλο και τα 55 τελείωναν.
;
; Το βιοπλαστικό είναι 45 και όχι 30 επειδή πια το ζητούν ΜΟΝΟ οι θόλοι, και
; ο κύκλος του κλείνει με τρεις: μικρό εργοστάσιο (10), θερμοκήπιο (10) για το
; άμυλο και μεσαίο εργοστάσιο (20), που έχει τέσσερις υποδοχές και άρα παίρνει
; και mach_bioplastic. Με 30 έλειπαν ακριβώς δέκα και ο κύκλος δεν έκλεινε.
;
; ΜΟΝΟ ΟΤΙ ΔΕΝ ΕΙΝΑΙ ΜΗΔΕΝ, ως (διεύθυνση, τιμή) — ως το βήμα 73 ήταν ένας
; πίνακας 14 λέξεων, οι μισές μηδέν, και δέκα εντολές για τα υπόλοιπα.
macro   NG_BYTE adr, val
        assert  ({adr}) >> 8 == G_econ_state >> 8
        db      ({adr}) & 255, {val}
mend
macro   NG_WORD adr, val
        NG_BYTE {adr}, ({val}) & 255
        NG_BYTE ({adr}) + 1, ({val}) >> 8
mend
;
; ΣΤΗΝ ΑΔΕΙΑ ΑΡΧΗ (βήμα 87) το σκάφος φέρνει και την αποικία που ως τότε
; ήταν δωρεάν, σε υλικά: τρεις μικροί θόλοι (36/24) με τη γεννήτρια
; οξυγόνου (8/2), δέκα πλακίδια διαδρόμου (60/30) και το airlock (10/6) —
; 114 μέταλλο και 62 βιοπλαστικό πάνω στα 75 και 45: 189 και 107. Η πίστα
; (45) όχι: χτίζεται όταν ο παίκτης θέλει πλοία. Αυτό το διάλεξε ο χρήστης.
;
; ΚΑΙ 30 ΒΙΟΠΛΑΣΤΙΚΑ ΑΚΟΜΗ (βήμα 133): 137. Τα 107 πήγαιναν στους θόλους και
; στους διαδρόμους (3 το πλακίδιο), και το εργοστάσιο πλαστικού δεν χτιζόταν
; ποτέ — στον παίκτη-σενάριο σε 0 από 12 κόσμους. Οχι περισσότερα: χωρίς το
; νερό το φορτίο είναι 498, και η αποθήκη χωρά 500 (§6.5) — με 140 και πάνω
; το παιχνίδι θα ξεκινούσε με STORAGE FULL, χωρίς κήπους και γεώτρηση.
ng_econ:
        NG_BYTE EC_STOCK + 2 * S_WATER, 60
        NG_BYTE EC_STOCK + 2 * S_FOOD, 100      ; 40 ως το βήμα 120 (§10.1)
        NG_BYTE EC_STOCK + 2 * S_ORE, 60
        NG_BYTE EC_STOCK + 2 * S_METAL, 189
        NG_BYTE EC_STOCK + 2 * S_BIOPL, 137     ; 107 ως το βήμα 132 (§10.1)
        NG_BYTE EC_STOCK + 2 * S_SPARE, 12      ; 4 ως το βήμα 120 (§10.1)
        NG_WORD EC_SOLLEN, 12000
        NG_WORD EC_DAYLEN, 7200
        NG_BYTE EC_DAY, 1
        NG_BYTE EC_POK, 1
        NG_BYTE EC_O2OK, 1
        NG_BYTE EC_ALIVE, 6
        NG_BYTE EC_POPCAP, POP_BASE     ; κανένα Control: η βάση του πληρώματος
        ; ΤΑ ΠΟΣΟΣΤΑ ΤΩΝ ΠΛΟΙΩΝ (βήμα 91): εργάτες 50%, μηχανικοί 10, βιολόγοι
        ; 20, γιατροί 10, φρουροί 10 — από το βήμα 137, η επιλογή του χρήστη.
        ; Ως τότε 20% η καθεμία, και μια αποικία δέκα είχε τέσσερις εργάτες για
        ; το ορυχείο και επτά θέσεις μηχανών, ενώ μηχανικοί, γιατρός και φρουρός
        ; κάθονταν το 96% του χρόνου (tools/play.py, DESIGN §10.1). Ιδια με το
        ; LAND_START του tools/econ.py.
        NG_BYTE EC_LAND + 0, 5
        NG_BYTE EC_LAND + 1, 1
        NG_BYTE EC_LAND + 2, 2
        NG_BYTE EC_LAND + 3, 1
        NG_BYTE EC_LAND + 4, 1
ng_econ_end:
; η αποικία δοκιμών: τα 75 και 45 των βημάτων 31-86, και οι τρεις θόλοι της·
; και από το βήμα 120 οι τέσσερις της, με τα 40 τρόφιμα και τα 4 ανταλλακτικά
; τους, ώστε οι δοκιμές που ξεκινούν από αυτήν να μη μάθουν τίποτα
        NG_BYTE EC_STOCK + 2 * S_METAL, 75
        NG_BYTE EC_STOCK + 2 * S_BIOPL, 45
        NG_BYTE EC_POPCAP, 8
        NG_BYTE EC_STOCK + 2 * S_FOOD, 40
        NG_BYTE EC_STOCK + 2 * S_SPARE, 4
        NG_BYTE EC_ALIVE, 4
ng_econ_col_end:

        ; ΤΟ ΜΠΛΟΚ (βήμα 172): θόλοι, οι 48 δομές, κατοχή, σημάδια, και τα 16
        ; πεδία ως το τέλος της τράπεζας — και το worldinfo πριν, έξω από αυτό
        ; (ως το 171: πράκτορες, 128 ελεύθερα, θόλοι, δομές, κατοχή, worldinfo)
        assert  G_struct_tbl == G_dome_tbl + MAX_DOME * DOME_REC
        assert  G_node_occ == G_struct_tbl + 48 * STRUCT_REC
        assert  G_agent_marks == G_node_occ + 256 && G_agent_fields == G_agent_marks + 256
        assert  G_agent_fields + 16 * 256 == #8000 && G_worldinfo + 4 <= G_dome_tbl
        ; οι διευθύνσεις του src/const.asm: STB_H, STB_C, CT_H
        assert  (G_struct_tbl & 7) == 0 && STB_C + 4 * 47 + 3 <= 255
        assert  ((G_struct_tbl + 48 * STRUCT_REC) & 255) == 0
