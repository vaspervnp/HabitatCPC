; ---------------------------------------------------------------------------
; corner.asm — οι γωνίες των διαδρόμων (βήμα 129, DESIGN §8.4).
;
; Ο παίκτης: «θέλω γωνίες για τους διαδρόμους ώστε να φαίνονται σωστοί, αν δεν
; είναι τελείως διαγώνιοι». Ως το βήμα 128 η στροφή διαγώνιος -> άξονας ήταν
; τα πλακίδια όπως τα βάζει το πλέγμα, το ένα πάνω στο άλλο: ο οριζόντιος
; ξεκινούσε ένα tile πίσω και η ουρά της διαγωνίου κρεμόταν από κάτω του, ο
; κάθετος ξεκινούσε μισό tile πάνω από εκεί που τον έβρισκε η διαγώνιος.
;
; ΤΟ ΣΧΗΜΑ το ορίζει το tools/corner.py: λοξή ένωση, η διαγώνιος ως τη γραμμή
; που διχοτομεί τη γωνία και ο άξονας από εκεί, με το περίγραμμα όπου το σχήμα
; τελειώνει. Ο,τι γράφεται εδώ είναι η φθηνότερη συνταγή που το βγάζει με τα
; πλακίδια που ήδη υπάρχουν, χωρίς κανένα pixel έξω από αυτό:
;
;   προς ΟΡΙΖΟΝΤΙΟ   το τελευταίο διαγώνιο μόνο CN_HROWS γραμμές (ως το κάτω
;                    χείλος της λωρίδας, ή από το πάνω βόρεια), το πρώτο
;                    οριζόντιο καθόλου, και ένα μπάλωμα 1 x 1 (cn_hpat)
;                    — φθηνότερο από τα δύο πλακίδια που αντικαθιστά
;   προς ΚΑΘΕΤΟ      όλα τα διαγώνια, το πρώτο κάθετο καθόλου, και ανάμεσά
;                    τους το σχέδιο της γωνίας, 5 x 8 (cn_vpat). Ενα ακόμη
;                    διαγώνιο κομμένο και ένα μπάλωμα κόστιζαν ~520 µs πάνω
;                    από το βήμα 128· το σχέδιο, λιγότερο από το πλακίδιο
;                    που αντικαθιστά (tests/test_corner.py).
;
; Τα σχέδια (build/corner_spr.asm) ήταν στη δέσμευση b5code της τράπεζας 5,
; που άδειασε όταν το src/bend.asm ήρθε στο b6code· από το βήμα 159 είναι στο
; τέλος της τράπεζας 6 (G_corner_spr), και τη θέση τους στην 5 την πήραν οι 128
; διάδρομοι: νοτιοανατολικά και νοτιοδυτικά, και βόρεια με το κάθετο
; καθρέφτισμα του ob_blit. Οχι με τον οριζόντιο: ως το 158 το flip_mode0 της 6
; δεν φαινόταν όσο η 5 ήταν μέσα, και στο 5 x 8 της κάθετης κόστιζε ~250 µs·
; έμεινε έτσι, το ίδιο κόστος και τα ίδια pixels. Η θέση τους από το cn_pos. Το
; tools/scene.py ζωγραφίζει το ίδιο, και το tests/test_corner.py ελέγχει ότι
; είναι η ένωση για κάθε στροφή.
;
; ΣΤΗ ΜΕΤΡΗΣΗ ΤΟΥ ΕΥΡΕΤΗΡΙΟΥ ΤΙΠΟΤΑ ΔΕΝ ΑΛΛΑΖΕΙ: τα κουτιά των δύο τρεξιμάτων
; ολόκληρα, όπως ως τώρα. Η γωνία πέφτει μέσα τους: το μπάλωμα πάνω στον
; οριζόντιο, το σχέδιο της κάθετης στις γραμμές του πρώτου κάθετου πλακιδίου.
;
; ΣΤΟ b6code: το ob_corr τρέχει με την 6 στο παράθυρο.
; ---------------------------------------------------------------------------

        include "../build/corner_tab.asm"

; cn_pre — από το ob_corr_run, πριν από το πρώτο τρέξιμο ενός διαδρόμου με
; συνέχεια (ο ίσιος δεν έρχεται εδώ: 6 µs φθηνότερος από ό,τι ως το βήμα 128,
; που ρωτούσε το oc_cont μετά το τρέξιμο): το βήμα και το sprite της διαγωνίου
; για το cn_post. Προς οριζόντιο το τελευταίο διαγώνιο είναι της γωνίας: το
; τρέξιμο ένα πλακίδιο λιγότερο.
cn_pre:
        ld      a,(ob_meas)
        or      a
        jr      nz,cnp_meas
        ld      hl,(oc_dx)              ; L = dx, H = dy
        ld      (cn_step),hl
        ld      hl,(ob_src)
        ld      (cn_src),hl
        ld      a,(oc_cr+C_DIR)
        and     2
        ret     z                       ; προς κάθετο: όλα τα διαγώνια
        ld      hl,oc_n
        dec     (hl)
        ret
; ΣΤΗ ΜΕΤΡΗΣΗ ΤΟΥ ΕΥΡΕΤΗΡΙΟΥ τα δύο τρεξίματα ολόκληρα, όπως ως το βήμα 128:
; το cn_pre παίρνει τη θέση του ob_corr_run, και ούτε το cn_post ούτε τα cn_*
; αγγίζονται (tests/test_oibuild.py: καμία άλλη μνήμη).
cnp_meas:
        pop     hl                      ; όχι πίσω στο ob_corr_run
        call    oc_run
        call    oc_bend
        jp      oc_run

; cn_post — από το ob_corr_run, μετά το oc_bend: το ob_x, ob_y είναι το πρώτο
; αξονικό, και από αυτό μετριούνται όλα (cn_lx, cn_ly· το cn_pos από το
; corner.first). Το c_rec είναι η συνέχεια, το oc_n το μήκος της. Η γωνία, το
; αξονικό από το δεύτερο πλακίδιο, και το μπάλωμα — με αυτή τη σειρά, γιατί
; το δεύτερο οριζόντιο σκεπάζει μέρος του κομμένου διαγώνιου και το μπάλωμα
; και τα δύο.
cn_post:
        ld      hl,(ob_x)
        ld      (cn_lx),hl
        ld      hl,(ob_y)
        ld      (cn_ly),hl
        ; --- προς οριζόντιο: το τελευταίο διαγώνιο, κομμένο ---
        ld      a,(c_rec+C_DIR)
        and     2
        jr      z,cnp_axial             ; προς κάθετο: το σχέδιο, μετά
        ; Από το πρώτο οριζόντιο (το oc_bend το βάζει στο x + (dx < 0 ? 4 : 0),
        ; y + 4): x - 4 δυτικά, y - 4 οι πρώτες CN_HROWS γραμμές του, βόρεια οι
        ; τελευταίες, στο y - 4 + 16 - CN_HROWS = y.
        assert  CN_HROWS == 12
        ld      de,(cn_src)
        ld      a,(cn_step+1)           ; dy < 0: βόρεια
        or      a
        jp      m,cnp_n
        ld      bc,-4
        add     hl,bc                   ; HL = ob_y
        ld      (ob_y),hl
        jr      cnp_w
cnp_n:
        ex      de,hl
        ld      bc,(16 - CN_HROWS) * 16 ; 16 bytes η γραμμή (8 x 2, με μάσκα)
        add     hl,bc
        ex      de,hl
cnp_w:
        ld      (ob_src),de
        ld      a,(cn_step)             ; dx < 0: δυτικά
        or      a
        jp      p,cnp_draw
        ld      hl,(ob_x)
        ld      bc,-4
        add     hl,bc
        ld      (ob_x),hl
cnp_draw:
        ld      hl,CN_HROWS * 256 + CORR_D_W
        xor     a                       ; με μάσκα, χωρίς καθρέφτισμα
        call    ob_put
        ld      hl,(cn_lx)              ; πίσω στο πρώτο αξονικό
        ld      (ob_x),hl
        ld      hl,(cn_ly)
        ld      (ob_y),hl
        call    oc_setdir               ; τα δικά του: sprite, διαστάσεις, βήμα
cnp_axial:
        ; --- το αξονικό, από το δεύτερο πλακίδιο ---
        ld      hl,oc_dx
        call    ob_move
        ld      hl,oc_n
        ld      a,(hl)
        or      a                       ; μήκος 0 (δεν το βγάζει το route): όχι 255
        jr      z,cnp_none
        dec     (hl)
        call    oc_run
cnp_none:
        ; --- το μπάλωμα: προσανατολισμός από τα πρόσημα του βήματος ---
        ld      hl,(cn_step)            ; L = dx, H = dy
        xor     a
        bit     7,h
        jr      z,cnp_s
        ld      a,2                     ; βόρεια
cnp_s:
        bit     7,l
        jr      z,cnp_e
        inc     a                       ; δυτικά
cnp_e:
        ld      c,a
        ld      a,(c_rec+C_DIR)
        and     2                       ; 2 οριζόντια, 0 κάθετα
        xor     2
        add     a,a                     ; 0 οριζόντια, 4 κάθετα
        add     a,c
        add     a,a                     ; δύο bytes η θέση
        ld      hl,cn_pos
        call    ob_addu
        ld      a,(hl)
        inc     hl
        push    hl
        ld      hl,(cn_lx)
        call    ob_addsx
        ld      (ob_x),hl
        pop     hl
        ld      a,(hl)
        ld      hl,(cn_ly)
        call    ob_addsx
        ld      (ob_y),hl
        ld      a,(c_rec+C_DIR)
        and     2
        ld      hl,cn_hpat
        ld      de,CN_HH * 256 + CN_HW
        ld      b,CN_HW * CN_HH * 2
        jr      nz,cnp_k
        ld      hl,cn_vpat
        ld      de,CN_VH * 256 + CN_VW
        ld      b,CN_VW * CN_VH * 2
cnp_k:
        bit     0,c
        jr      z,cnp_pat
        ld      a,b
        call    ob_addu                 ; δυτικά: το καθρεφτισμένο, αμέσως μετά
cnp_pat:
        ld      (ob_src),hl
        ex      de,hl
        ld      a,c
        and     2                       ; μόνο το κάθετο καθρέφτισμα, βόρεια
        ld      c,PAGE_B6               ; τα σχέδια στην 6 (βήμα 159· στην 5 ως τότε)
        jp      ob_put_in

cn_step:    dw 0                        ; dx, dy της διαγωνίου
cn_src:     dw 0                        ; το sprite της
cn_lx:      dw 0                        ; το πρώτο αξονικό: από αυτό το κομμένο
cn_ly:      dw 0                        ; διαγώνιο και το μπάλωμα (cn_pos)
