; fit6.asm — το FIT και η μηχανή που βγαίνει, στις ουρές 6-7 των σελίδων πεδίων
; της τράπεζας 6 (βήμα 198, DESIGN §6.9). Τρέχουν με την 6 μέσα: το fs_put από
; το fit_set μετά το fit_slot, το mc_out και από την κατεδάφιση (dm_ovl). Στο
; tests/uitest.asm το B6T_PIECE δεν κάνει τίποτα.

        B6T_PIECE 6

; ---------------------------------------------------------------------------
; mc_out — A = ό,τι βγαίνει από μια υποδοχή, D = η υγεία του: τα μισά της τιμής
; του πίσω (fit_price), όπως από το βήμα 45. ΜΙΑ ΜΗΧΑΝΗ ΠΟΥ ΔΕΝ ΣΤΗΘΗΚΕ (υγεία
; 1-127, βήμα 198): η τιμή της φεύγει από το χρέος όσο εκείνο φτάνει, και ό,τι
; μένει γυρίζει ολόκληρο (db_cut). Αν δεν ήρθε τίποτα, το χρέος την παίρνει
; όλη· αν ήρθαν όλα και κανείς άλλος δεν χρωστά, γυρίζουν όλα· αν χρωστούν
; άλλοι, πάνε σε εκείνους. Από το fs_put και την κατεδάφιση (dm_ovl), με την 6.
; ---------------------------------------------------------------------------
mc_out:
        push    de
        call    fit_price               ; L = μέταλλο, H = βιοπλαστικό
        pop     de
        ld      a,d
        dec     a
        cp      127
        jr      nc,mco_half             ; άδεια, χαλασμένη, δουλεύει: τα μισά
        ld      e,h
        ld      d,0
        ld      h,d
; db_both — HL = μέταλλο, DE = βιοπλαστικό που δεν θα κουβαληθούν πια: πρώτα
; στο χρέος, ό,τι μένει στο απόθεμα. Και από την κατεδάφιση ενός εργοταξίου.
db_both:
        push    de
        ld      de,EC_DEBT
        ld      a,S_METAL
        call    db_back
        pop     hl
        ld      de,EC_DEBT + 2
        ld      a,S_BIOPL
; db_back — A = απόθεμα, DE -> το χρέος του, HL = πόσο: το χρέος παίρνει όσο
; φτάνει, και τα υπόλοιπα στο απόθεμα.
db_back:
        push    af
        call    db_cut
        ex      de,hl
        pop     af
        jp      ec_add_stock
mco_half:
        push    hl
        ld      e,l
        ld      a,S_METAL
        call    mco_st
        pop     de
        ld      e,d
        ld      a,S_BIOPL
mco_st:
        srl     e
        ld      d,0
        jp      ec_add_stock            ; με ταβάνι (src/stock.asm)

        B6T_PIECE 7

; ---------------------------------------------------------------------------
; fs_put — από το fit_set (src/fit.asm): HL -> η υποδοχή, B = το παλιό, C = το
; νέο, (bd_metal) = η τιμή του νέου. Η υγεία (βήμα 99): άδεια 0· ένα φυτό
; δουλεύει αμέσως· μια μηχανή χρωστά τα υλικά της (MACH_OWED), που θα τα
; κουβαλήσουν δύο Supply, και μετά τη στήνει ένας μηχανικός (src/install.asm).
; Η τιμή της μπήκε ήδη στο χρέος (fit_set, βήμα 198). Μετά το παλιό έξω (mc_out).
; ---------------------------------------------------------------------------
fs_put:
        ld      (hl),c
        ld      de,D_HEALTH - D_MACH
        add     hl,de
        ld      d,(hl)                  ; η υγεία του παλιού
        push    de
        push    bc
        ld      a,c
        inc     a                       ; NO_MACH: 0
        jr      z,fsp_hp
        ld      a,(fit_rm)
        cp      R_GREENHS
        ld      a,MACH_HP
        jr      z,fsp_hp                ; φυτό
        ld      a,(fit_d)
        call    mc_order                ; κρατά το HL
        ld      a,MACH_OWED
fsp_hp:
        ld      (hl),a
        pop     af                      ; A = το παλιό
        pop     de                      ; D = η υγεία του
        jp      mc_out

; ---------------------------------------------------------------------------
; db_cut — DE -> ένα χρέος, HL = πόσο: το χρέος χάνει όσο φτάνει, ως το 0, και
; HL = ό,τι περίσσεψε. Για ό,τι δεν θα κουβαληθεί πια: μηχανή που βγαίνει πριν
; στηθεί (mc_out), εργοτάξιο που γκρεμίζεται (dm_ovl). Τράπεζα 6.
; ---------------------------------------------------------------------------
db_cut:
        ex      de,hl
        ld      a,(hl)
        sub     e
        ld      c,a
        inc     hl
        ld      a,(hl)
        sbc     a,d
        jr      c,dbc_lt                ; το χρέος δεν φτάνει
        ld      (hl),a
        dec     hl
        ld      (hl),c
        ld      hl,0                    ; τα πήρε όλα
        ret
dbc_lt:
        ld      (hl),0
        dec     hl
        ld      (hl),0
        ld      h,a
        ld      l,c                     ; χρέος - πόσο < 0
        xor     a
        sub     l
        ld      l,a
        sbc     a,a
        sub     h
        ld      h,a                     ; HL = πόσο - χρέος
        ret
