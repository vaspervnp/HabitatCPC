; walk6.asm — όποιος περπατά έξω, πάνω στο Γ (βήμα 118, DESIGN §8.4).
;
; Ως το βήμα 117 ο περιπατητής πήγαινε στην ευθεία από το μπροστινό σημείο του
; ενός κόμβου ως του άλλου, ενώ το μονοπάτι που ζωγραφίζεται είναι ένα Γ από το
; κεντρικό tile του ενός ως το κεντρικό tile του άλλου (al_walk, lk_draw): ο
; άποικος έκοβε τη γωνία, πάνω από ό,τι βρισκόταν εκεί (§15). Τώρα:
;
;   ΠΟΙΟ ΣΚΕΛΟΣ ΠΡΩΤΑ. Μια δομή θυμάται το σχήμα της σύνδεσής της ως την άγκυρα
;   (LK_OWN, βήμα 102): το bit 7 λέει «πρώτα κατά y», αλλιώς πρώτα κατά x. Από
;   την άγκυρα προς τη δομή, το ανάποδο — το ίδιο Γ περπατημένο από την άλλη
;   άκρη· από τη δομή προς την άγκυρα, αυτό. Οπου δεν κράτησε κανείς τίποτα
;   (η αποικία των δοκιμών, ένα σώσιμο πριν από το βήμα 102), πρώτα κατά x.
;   ΔΥΟ ΔΟΜΕΣ, Η ΓΩΝΙΑ ΕΞΩ ΚΑΙ ΑΠΟ ΤΑ ΔΥΟ ΑΠΟΤΥΠΩΜΑΤΑ: το κομμάτι του Γ που
;   φαίνεται. Η γωνία είναι το κελί (στήλη του ενός κέντρου, σειρά του άλλου)
;   όπου στρίβει το μονοπάτι· το πρώτο σκέλος αρχίζει στο πρώτο κελί έξω από το
;   αποτύπωμα από όπου φεύγει, το δεύτερο τελειώνει στο τελευταίο κελί πριν από
;   το αποτύπωμα όπου φτάνει — από κάτω αυτό είναι το μπροστινό του σημείο.
;   Με progress 0 στέκεται ακόμη στο μπροστινό σημείο από όπου φεύγει.
;   Η ΓΩΝΙΑ ΜΕΣΑ ΣΕ ΑΠΟΤΥΠΩΜΑ: το ένα σκέλος είναι κρυμμένο κάτω από τη δομή,
;   και το μονοπάτι που φαίνεται είναι σχεδόν ευθεία. Στη σειρά ενός
;   αποτυπώματος (οι δύο δίπλα-δίπλα): μόνο το x κινείται, στη σειρά ay· στη
;   στήλη του (η μία πάνω από την άλλη): μόνο το y, στη στήλη ax. Το Γ θα
;   ξόδευε το μισό ταξίδι σε ένα σκέλος λίγων κελιών, και η γωνία του
;   μονοπατιού θα τον άφηνε στη σκεπή. Στο τέλος της ακμής στέκεται στη θέση
;   του, όπως πάντα. Ελέγχεται πρώτα η σειρά.
;   ΕΝΑΣ ΘΟΛΟΣ στη μία άκρη: η σύνδεση εδάφους του δεν ζωγραφίζεται
;   (src/commit.asm). Ενα Γ πρώτα κατά x, από μπροστινό σε μπροστινό σημείο.
;   ΤΟ ΠΡΩΤΟ ΜΙΣΟ ΤΟΥ progress ΤΟ ΠΡΩΤΟ ΣΚΕΛΟΣ, το δεύτερο το δεύτερο: σε κάθε
;   μισό κινείται ένας άξονας μόνο, ένας πολλαπλασιασμός (fw_axis) αντί για
;   τους δύο της ευθείας. Η ταχύτητα δεν ήταν ποτέ σταθερή — μια ακμή παίρνει
;   τον ίδιο χρόνο όποιο κι αν είναι το μήκος της (§8.4) — και τώρα αλλάζει
;   και στη γωνία, όταν τα σκέλη είναι άνισα.
;   ΜΠΡΟΣΤΙΝΑ ΣΗΜΕΙΑ ΣΤΗΝ ΙΔΙΑ ΣΤΗΛΗ Ή ΣΕΙΡΑ: η ευθεία, όπως ως τώρα. Κι
;   αυτή κινεί έναν άξονα μόνο.
;
; Η ΣΤΗΛΗ: πάνω στα σκέλη του μονοπατιού το cx, όπου είναι τα tiles του — το
; κεντρικό tile είναι το cx >> 1 (al_node), η στήλη cx είναι πάντα μισό του,
; ενώ η cx - 1 είναι το διπλανό tile όταν το πλάτος είναι ζυγό. Αλλού — στο
; μπροστινό σημείο, στην ευθεία, στον θόλο, με τη γωνία μέσα σε αποτύπωμα — η
; στήλη της θέσης 0, cx - 1, όπως ως το βήμα 117: το cx στο μπροστινό σημείο
; είναι το κελί της θέσης 4, και όποιος φεύγει ή φτάνει θα πατούσε όποιον
; περιμένει εκεί. Το fw_walk δίνει ήδη τα x μείον 1· οι ουρές των σκελών
; προσθέτουν το 1 (οι έλεγχοι συγκρίνουν μόνο διαφορές).
;
; ΤΑ ΑΠΟΤΥΠΩΜΑΤΑ σε μισά tiles: στήλες cx - w ως cx + w - 1, σειρές cy - h ως
; cy + h - 1, και το μπροστινό σημείο (cx, cy + h). Οι δομές είναι τετράγωνες
; (w = h, tests/test_figure.py): το μισό ύψος του fw_xy είναι και το μισό
; πλάτος, χωρίς δεύτερη ανάγνωση του struct_dims.
;
; ΣΤΟ b6code: το fg_want τρέχει πάντα με την 6 μέσα. Το fw_axis είναι στην
; τράπεζα 2 και δεν σελιδοποιεί.

; ---------------------------------------------------------------------------
; fw_leg — C = από πού (P), B = το μισό του ha, D = ax - 1, E = ay (το
; μπροστινό του σημείο, προσημασμένο, στη στήλη της θέσης 0)· (fw_q) = πού (Q),
; (fw_hb) = το μισό του, (fw_b) = by, bx - 1· (fw_p) = progress -> ό,τι δίνει το fw_out (src/figure.asm):
; D, E + 128, A = (fw_f). Το fw_walk έρχεται εδώ με jp, και οι ουρές κάνουν
; οι ίδιες το fw_out.
; ---------------------------------------------------------------------------
fw_leg:
        ld      hl,(fw_b)               ; L = by, H = bx
        ld      a,d
        cp      h
        jr      z,fwl_ly                ; ίδια στήλη: η ευθεία, μόνο το y
        ld      a,e
        cp      l
        jr      z,fwl_lx                ; ίδια σειρά: η ευθεία, μόνο το x
        ld      a,(fw_q)
        ld      l,a                     ; L = Q
        and     c
        and     64                      ; και οι δύο δομές (64-95);
        jr      z,fwl_xr                ; ένας θόλος: Γ στα μπροστινά σημεία
        ld      h,NODEPG
        set     5,l                     ; LK_OWN + Q
        ld      a,c
        xor     (hl)
        and     #FF - #80 - LKO_GROUND
        jr      z,fwl_qp                ; το Q κρέμεται από το P
        ld      a,l                     ; Q + 32: το bit 5 δεν μετρά
        ld      l,c
        set     5,l                     ; LK_OWN + P
        xor     (hl)
        and     #FF - #80 - LKO_GROUND
        ld      a,(hl)
        jr      z,fwl_own               ; το P κρέμεται από το Q: το δικό του Γ
        ld      hl,(fw_b)               ; κανένας από τους δύο: πρώτα κατά x
        jr      fwl_px
fwl_qp:
        ld      a,(hl)
        cpl                             ; το Γ του Q από την άλλη άκρη
fwl_own:
        rla                             ; CY: πρώτα κατά y
        ld      hl,(fw_b)
        jp      c,fwl_py
        jr      fwl_px
        ; --- ΕΝΑΣ ΘΟΛΟΣ: Γ στα μπροστινά σημεία, με το HL ξαναδιαβασμένο ---
fwl_xr:
        ld      hl,(fw_b)
fwl_x:
        ld      a,(fw_p)
        add     a,a                     ; 2p, και CY: το δεύτερο μισό
        ld      c,a
        jr      nc,fwl_mx               ; το πρώτο: το x, στη σειρά ay
        ld      d,h                     ; το δεύτερο: το y, στη στήλη bx
        jr      fwl_my
        ; --- ΕΝΑΣ ΑΞΟΝΑΣ (ευθεία, ή η γωνία μέσα σε αποτύπωμα: fwl_lyr, fwl_lxr) ---
fwl_lyr:
        ld      hl,(fw_b)
fwl_ly:
        ld      a,(fw_p)
        ld      c,a
fwl_my:
        ld      a,l
        call    fw_axis                 ; y = E + (L - E) * C / 256
        xor     128                     ; το fw_out εδώ: 5 us λιγότερα
        ld      e,a
        ld      a,d
        xor     128
        ld      d,a
        ld      a,(fw_f)
        ret
fwl_lxr:
        ld      hl,(fw_b)
fwl_lx:
        ld      a,(fw_p)
        ld      c,a
fwl_mx:
        ld      b,e
        ld      e,d
        ld      a,h
        call    fw_axis                 ; x = D + (H - D) * C / 256
fwl_out:
        xor     128
        ld      d,a
        ld      a,b
        xor     128
        ld      e,a
        ld      a,(fw_f)
        ret
        ; --- ΠΡΩΤΑ ΚΑΤΑ x: η γωνία (bx, ay - ha), η σειρά του κέντρου του P ---
fwl_px:
        ld      a,e
        sub     b
        ld      c,a                     ; C = ay - ha
        sub     l
        jp      p,fpx_c                 ; κάτω από το Q: το σκέλος ως το by (L)
        ld      a,(fw_hb)
        add     a,a
        cpl
        add     a,l
        ld      l,a                     ; πάνω από το Q: ως το by - 2hb - 1
        sub     c
        jp      m,fwl_lxr               ; η σειρά μέσα στο Q: μόνο το x
fpx_c:
        ld      a,h
        sub     d                       ; bx - ax
        ld      a,d
        jp      m,fpx_w
        add     a,b                     ; από το ax + ha, ανατολικά
        ld      b,a
        ld      a,h
        sub     b
        jp      m,fwl_lyr               ; η στήλη bx μέσα στο P: μόνο το y
        jr      fpx_go
fpx_w:
        sub     b
        dec     a                       ; από το ax - ha - 1, δυτικά
        ld      b,a
        sub     h
        jp      m,fwl_lyr
fpx_go:
        ld      a,(fw_p)
        add     a,a
        jr      c,fpx_2
        jp      z,fw_out                ; progress 0: στο μπροστινό σημείο
        ld      e,b                     ; x από το x0 ως το bx,
        ld      b,c                     ; στη σειρά της γωνίας
        ld      c,a
        ld      a,h
        call    fw_axis
        inc     a                       ; η στήλη του μονοπατιού
        jr      fwl_out
fpx_2:
        ld      e,c                     ; y από τη γωνία ως το L,
        ld      c,a
        ld      d,h                     ; στη στήλη bx
        inc     d
        jr      fwl_my
        ; --- ΠΡΩΤΑ ΚΑΤΑ y: η γωνία (ax, by - hb), η σειρά του κέντρου του Q ---
fwl_py:
        ld      a,(fw_hb)
        ld      c,a                     ; C = hb
        ld      a,l
        sub     c
        ld      l,a                     ; L = by - hb
        sub     e
        jp      p,fpy_dn                ; κάτω από το P: το σκέλος από το ay
        ld      a,b
        add     a,a
        cpl
        add     a,e
        ld      b,a                     ; πάνω από το P: από το ay - 2ha - 1
        sub     l
        jp      m,fwl_lxr               ; η σειρά μέσα στο P: μόνο το x
        jr      fpy_c
fpy_dn:
        ld      b,e                     ; B = y0
fpy_c:
        ld      a,d
        sub     h                       ; ax - bx
        ld      a,h
        jp      m,fpy_e
        add     a,c                     ; ως το bx + hb, δυτικά
        ld      h,a
        ld      a,d
        sub     h
        jp      m,fwl_lyr               ; η στήλη ax μέσα στο Q: μόνο το y
        jr      fpy_go
fpy_e:
        sub     c
        dec     a                       ; ως το bx - hb - 1, ανατολικά
        ld      h,a
        sub     d
        jp      m,fwl_lyr
fpy_go:
        ld      a,(fw_p)
        add     a,a
        jr      c,fpy_2
        jp      z,fw_out                ; progress 0: στο μπροστινό σημείο
        ld      c,a
        ld      e,b                     ; y από το y0 ως τη γωνία, στη στήλη ax
        inc     d
        jp      fwl_my
fpy_2:
        ld      c,a
        ld      b,l                     ; x από το ax ως το x1, στη σειρά της
        ld      e,d                     ; γωνίας
        ld      a,h
        call    fw_axis
        inc     a
        jp      fwl_out

fw_q:       db 0                        ; πού πηγαίνει (fg_want)
fw_hb:      db 0                        ; και το μισό ύψος του (fw_xy)

        assert  MAX_DOME == 64 && LKO_GROUND == #20 && MAX_DOME + MAX_STRUCT <= #60

; ---------------------------------------------------------------------------
; fg_ord — μετά το dha_mv του dh_agent (src/figure.asm, βήμα 134): μία εγγραφή
; έφυγε από τη λίστα των φιγουρών και η τελευταία πήρε τη θέση της. Τέσσερις
; φορές +64: L = η τρύπα, E = πού ήταν η τελευταία, H = D = η σελίδα της
; λίστας, τράπεζα 6. Οσες ήταν ανάμεσα έχουν τώρα τη μετακινημένη πριν από
; αυτές, και η πλήρης σχεδίαση (ob_draw_all) τις ζωγραφίζει από πάνω της. Αν
; μία πατά το ίδιο κελί: fg_nx, fg_ny = το κελί και fg_nf = 1, και το
; dha_erase το δίνει στο fg_paint, που το ζωγραφίζει με τη νέα σειρά.
; Χαλάει AF, BC, DE, HL.
; ---------------------------------------------------------------------------
fg_ord:
        ld      a,e
        sub     l
        ret     z                       ; έφυγε η ίδια η τελευταία
        dec     a
        ret     z                       ; καμία ανάμεσα
        ld      c,a
        ld      b,0                     ; BC = όσες ανάμεσα
        ld      a,l
        add     a,FG_UY
        ld      e,a                     ; DE -> το uy της μετακινημένης
        ld      a,(hl)                  ; A = το ux της
        inc     l
fgo_sh:
        cpir
        ret     nz
        dec     l
        set     6,l                     ; HL -> το uy αυτής που βρέθηκε
        push    af                      ; και το P/V του cpir: έμειναν κι άλλες
        ld      a,(de)
        cp      (hl)
        jr      z,fgo_rep
        res     6,l
        inc     l
        pop     af
        jp      pe,fgo_sh
        ret
fgo_rep:
        pop     af
        ld      (fg_nx),a
        ld      a,(de)
        ld      (fg_ny),a
        ld      a,1
        ld      (fg_nf),a
        ret
