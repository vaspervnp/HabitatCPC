; drill.asm — η γεώτρηση (βήμα 94, DESIGN §6.7): το ορυχείο θέλει ανθρώπους.
;
; Ως το βήμα 93 ένα ορυχείο με ρεύμα έβγαζε 2 μετάλλευμα ανά κύκλο ροής χωρίς
; κανέναν, και η εργασία Drill υπήρχε μόνο στους πίνακες (job_roles: εργάτης
; και ρομπότ γεώτρησης· job_prio: 4) — δεν τη δημοσίευε τίποτα. Ο κανόνας
; είναι του Planetbase, όπως τον ζήτησε ο παίκτης:
;
;   - ΩΣ ΤΡΕΙΣ ΣΕ ΚΑΘΕ ΟΡΥΧΕΙΟ (MINE_OPS), εργάτες ή ρομπότ γεώτρησης. Κανείς:
;     τίποτα. Ενας: 2 ανά κύκλο, όσο έβγαζε ως τώρα μόνο του. Δύο: 3. Τρεις:
;     4 — το 100, 150 και 200% του Planetbase (src/flow.asm, ef_lp).
;   - ΟΣΟΙ ΣΚΑΒΟΥΝ μετριούνται στο έβδομο byte της εγγραφής (ST_OPS), που ως
;     τώρα το είχαν μόνο τα airlock (ST_JOINED). Ανεβαίνει όταν φτάσει κάποιος
;     με Drill (ja_oper, src/jobs.asm) και κατεβαίνει όταν φύγει ή πεθάνει,
;     όπως οι χειριστές ενός θόλου (op_ptr). Το bit 7 του ίδιου byte λέει «η
;     Drill του υπάρχει ήδη»: το βάζει το dr_post, το σβήνει η άφιξη.
;   - ΟΙ ΑΝΘΡΩΠΟΙ ΣΚΑΒΟΥΝ ΜΕ ΔΙΑΚΟΠΕΣ: το ορυχείο είναι έξω, και η στολή
;     τους γυρίζει να γεμίσουν (src/suit.asm). Τα ρομπότ μένουν.
;   - ΤΑ ΝΕΑ ΡΟΜΠΟΤ ΕΙΝΑΙ ΓΕΩΤΡΥΠΑΝΑ όσο τα ορυχεία έχουν θέσεις χωρίς
;     γεωτρύπανο (dr_need, src/bots.asm).
;
; ΣΤΗΝ ΤΡΑΠΕΖΑ 2, που φαίνεται πάντα: το dr_post το καλεί η θέση 12 μέσα από
; το b6code (src/flow.asm), το jb_open η θέση 13 (src/jobs.asm). Το dr_need,
; που διαλέγει το είδος του ρομπότ, ζει με τα ρομπότ στο b6code (src/bots.asm).
; Το σώμα του dr_post είναι από το βήμα 95 το st_post (src/haul.asm), κοινό με
; τη Haul.

MINE_OPS    equ 3

        assert  DRILL_LOW < 3 && DRILL_PRIO == 4    ; κάτω από κάθε room_prio
        assert  ST_DLOW != 6 && ST_DLOW != 7 && ST_DLOW > 3   ; όχι Haul, Drill, μισό, δωρεάν

        assert  ST_OPS == 6 && STRUCT_REC == 8 && (G_struct_tbl & 7) == 0
        assert  MAX_STRUCT <= 48

; ---------------------------------------------------------------------------
; dr_post — IX -> ένα ορυχείο έτοιμο, με λιγότερους από MINE_OPS και χωρίς
; το bit 7: μια εργασία Drill γι' αυτό, αν δεν υπάρχει ήδη, στην πρώτη ελεύθερη
; θέση του πίνακα, και το bit 7 του ST_OPS ως να φτάσει κάποιος (st_post, src/
; haul.asm). Από το
; σάρωμα των δομών της θέσης 12, μία φορά ανά κύκλο ροής (64 περιστροφές, και
; αμέσως όταν τελειώσει ένα κτίσμα): όχι από τη θέση 13, που είναι η βαρύτερη
; του τροχού (§7.2) και θα πλήρωνε τον έλεγχο σε κάθε περιστροφή.
;
; ΤΟ BIT 7 ΚΡΑΤΑ ΤΟ ΣΑΡΩΜΑ ΦΘΗΝΟ. Το πέρασμα των 32 εργασιών (jp_have) κοστίζει
; ~900 us, και ένα ορυχείο με έναν εργάτη το πλήρωνε σε κάθε κύκλο για να
; βρει την εργασία του ήδη εκεί: τρία ορυχεία πήγαιναν τον κύκλο από 2.065 σε
; 3.996 us. Μια εργασία Drill φεύγει από τον πίνακα μόνο όταν φτάσει κάποιος
; (ja_done, μέσα από το ja_oper που σβήνει το bit), οπότε το bit δεν λέει ποτέ
; ψέματα. Με τον πίνακα γεμάτο δεν μπαίνει: ξανά τον επόμενο κύκλο. Κρατά τον
; IX.
;
; Ο ΔΕΥΤΕΡΟΣ ΚΑΙ Ο ΤΡΙΤΟΣ ΚΑΤΩ ΑΠΟ ΤΙΣ ΜΗΧΑΝΕΣ (βήμα 126, η επιλογή του
; χρήστη). Με έναν εργάτη ήδη στο ορυχείο η Drill δημοσιεύεται με DRILL_LOW
; (2), κάτω από κάθε Operate (room_prio, 3 και πάνω), και το bit ST_DLOW το
; λέει. Ως τότε όλες είχαν 4, πάνω από το Operate του εργοστασίου (3): οι
; έξι του σκάφους έστελναν δύο στο ορυχείο, ένα στο κυλικείο κι ένα στο
; θερμοκήπιο, και η μηχανή METAL έμενε χωρίς χειριστή στο 75% των δειγμάτων
; του tools/play.py με το μετάλλευμα να μαζεύεται (DESIGN §6.7). Ενας που
; σκάβει σε φλέβα δίνει όσο τρώει μία μηχανή METAL (§6.5). Το bit μπαίνει
; μόνο όταν η εργασία μπήκε (το C του st_post)· αν αδειάσει το ορυχείο πριν
; έρθει κάποιος, ο κύκλος ροής την ξαναπηγαίνει στο 4 (dr_raise, src/flow.asm).
; ---------------------------------------------------------------------------
dr_post:
        ld      a,(ix+ST_OPS)
        and     MINE_OPS                ; όσοι σκάβουν ήδη
        ld      a,DRILL_PRIO
        ld      c,#80                   ; το bit 7 του ST_OPS
        jr      z,drp_p
        ld      a,DRILL_LOW
        ld      c,#80 | (1 << ST_DLOW)
drp_p:  ld      (job_prio + J_DRILL),a  ; το jp_have τη διαβάζει από εκεί
        ld      a,J_DRILL
        ; και κατευθείαν στο st_post

; ---------------------------------------------------------------------------
; st_post — A = είδος, C = τα bits του ST_OPS που λένε «υπάρχει», IX -> η δομή:
; μια εργασία του είδους για τον κόμβο της (64 + δομή), αν δεν υπάρχει ήδη,
; στην πρώτη ελεύθερη θέση (jp_have, src/jobs.asm), και το bit. Με τον πίνακα
; γεμάτο τίποτα, ούτε το bit: ξανά τον επόμενο κύκλο. Η Drill (dr_post, src/
; drill.asm, bit 7) και η Haul (hl_pile, src/haul.asm, bit 6). Κρατά τον IX· χαλάει AF,
; BC, DE, HL.
; ---------------------------------------------------------------------------
st_post:
        ld      (jb_kind2),a
        ld      a,ixh
        rra                             ; CY: η δεύτερη σελίδα, οι δομές 16-47
        ld      a,ixl
        rra
        rra
        rra                             ; 32 x CY + L / 8 (βήμα 154, src/const.asm)
        add     a,MAX_DOME - ((G_struct_tbl & 255) >> 3)    ; ο κόμβος της
        ld      (jb_d),a
        push    bc
        call    jp_hava                 ; το διπλότυπο, η θέση, η προτεραιότητα·
                                        ; με τον κόμβο στον A, χωρίς να τον ξαναδιαβάσει:
                                        ; τα 4 us πληρώνουν τα 3 του ixh (βήμα 154)
        pop     bc
        ld      a,h
        or      l
        ret     z                       ; HL = 0: ο πίνακας γέμισε
        ld      a,(ix+ST_OPS)
        or      c
        ld      (ix+ST_OPS),a
        ret


; ---------------------------------------------------------------------------
; jb_open — η μάσκα των ρόλων (job_roles) που έχουν αδιάθετη εργασία, στο
; jb_om και στον A, Z αν καμία. Μέρος της ανάθεσης (jb_assign, src/jobs.asm)·
; εδώ γιατί η τράπεζα 0 είχε 32 bytes ως το πάτωμα των δοκιμών.
;
; ΓΙΑΤΙ (βήμα 94): η ανάθεση έτρεχε το jb_best — 32 εγγραφές, ~1 ms — για
; κάθε αδρανή από τους 32 που κοιτάζει, αρκεί να υπήρχε ΜΙΑ αδιάθετη εργασία,
; ακόμη κι αν δεν ήταν για τον ρόλο κανενός τους. Μια Drill μένει ανοιχτή όσο
; το ορυχείο έχει θέση και δεν έρχεται εργάτης, και η θέση 13 πήγαινε 20-40 ms
; σχεδόν σε κάθε περιστροφή (tests/test_sim.py: 70 -> 100 frames στα 640
; ticks της ταυτότητας). Με τη μάσκα, ένας αδρανής χωρίς ταίρι κοστίζει ένα
; and, και το jb_best τρέχει μόνο για όποιον θα βρει κάτι: τα αποτελέσματα
; ίδια, γιατί το jb_best δεν απορρίπτει τίποτα άλλο από τον ρόλο.
;
; Στην αρχή της ανάθεσης, όσο κόστιζε και το «καμία;» που αντικατέστησε όταν
; δεν υπάρχει καμία (εκείνο σταματούσε στην πρώτη αδιάθετη), και ξανά μετά
; από κάθε ανάθεση (jb_assign). Χαλάει BC, DE, HL.
; ---------------------------------------------------------------------------
jb_open:
        ld      hl,G_job_tbl
        ld      de,JOB_REC
        ld      bc,MAX_JOB << 8         ; C = η μάσκα
jbo_lp:
        ld      a,(hl)
        inc     a                       ; NO_JOB
        jr      z,jbo_n
        inc     hl
        inc     hl
        ld      a,(hl)                  ; ο πράκτορας της
        dec     hl
        dec     hl
        inc     a
        jr      nz,jbo_n                ; ήδη ανατεθειμένη
        push    hl
        ld      a,(hl)                  ; το είδος
        ld      hl,job_roles            ; 16 bit: ο πίνακας περνά από σελίδα
        add     a,l
        ld      l,a
        adc     a,h
        sub     l
        ld      h,a
        ld      a,c
        or      (hl)
        ld      c,a
        pop     hl
jbo_n:
        add     hl,de                   ; το DE μένει JOB_REC: 10 T ανά εγγραφή
        djnz    jbo_lp
        ld      a,c
        ld      (jb_om),a
        or      a
        ret
jb_om:      db 0
