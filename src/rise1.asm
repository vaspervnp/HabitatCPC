; ---------------------------------------------------------------------------
; rise1.asm — οι σειρές που φάνηκαν με ένα φορτίο, στη λίστα αλλαγών (βήμα 200,
; DESIGN §6.9). ΣΤΟ OV_R1, και τρέχει εκεί, με την 1 στο παράθυρο, όπως οι
; χειριστές της κατεδάφισης (src/dm_hand.asm): ο χειριστής του DK_RECT έρχεται
; εδώ όταν το ty του είναι RISE_TY.
;
; ΤΟ ΚΤΙΡΙΟ ΥΨΩΝΕΤΑΙ ΑΠΟ ΚΑΤΩ (ο παίκτης: «μέχρι να πάνε όλα να φαίνεται
; γραμμή παρά γραμμή το κτήριο»). Ενα εργοτάξιο που χρωστά υλικά δείχνει τις H
; x p / 256 κάτω γραμμές του πλαισίου του (ob_rise, src/rise0.asm), όπου H = 16
; x το ύψος του σε tiles και p η ακεραιότητά του, που όσο έρχονται τα φορτία
; είναι το μερίδιο που έφτασε (sp_dlv, src/rise6.asm). Με το τελευταίο φορτίο
; φαίνεται ολόκληρο. Οι γραμμές που μόλις φάνηκαν πέφτουν σε μία ή δύο σειρές
; tiles του αποτυπώματός του, που ξαναζωγραφίζονται όπως ένα ορθογώνιο της
; κατεδάφισης: έδαφος, και ό,τι το πατά.
;
; ΕΔΩ ΚΑΙ ΟΧΙ ΣΤΟΝ ΤΡΟΧΟ: το al_node και τα δύο ob_mul ήταν ~500 us στη θέση 13
; (tests/test_install.py). Ο τροχός βάζει μόνο ένα DK_RSIZE με την πρόοδο, μετά
; και πριν, και ένα DK_RECT με τον κόμβο (sdl_view, src/rise0.asm).
; ---------------------------------------------------------------------------

; dh_rise — από το DH_RECT, με HL = (dt_a): L = ο κόμβος. Το DK_RSIZE πριν από
; αυτό έγραψε στο vr_w την πρόοδο μετά από το φορτίο (0: το τελευταίο,
; ολόκληρο) και στο vr_h την πρόοδο πριν. Με την 1 μέσα, και πίσω με την 1.
;
; Η σειρά μιας γραμμής t του πλαισίου (0 η πάνω) είναι al_ry + (t + o) / 16.
; ΤΟ o: ΤΟ ΠΛΑΙΣΙΟ ΜΙΑΣ ΔΟΜΗΣ ΔΕΝ ΑΡΧΙΖΕΙ ΠΑΝΤΑ ΣΕ ΟΡΙΟ TILE. Το κέντρο του είναι
; στο cy, σε μισά tiles, και μια δομή με ύψος περιττό σε tiles και cy ζυγό (ή
; ανάποδα) αρχίζει στη μέση της σειράς al_ry (o = 8) και πιάνει και μία σειρά
; κάτω από το αποτύπωμα· το ίδιο κατά x με το cx, μία στήλη δεξιά. Το cx και το
; cy είναι στην 6, και εδώ δεν φαίνονται: για μια δομή το ορθογώνιο πιάνει και
; τις δύο περιπτώσεις — η πρώτη σειρά με o = 0, η τελευταία με o = 8, και μία
; στήλη ακόμη. Ενας θόλος έχει πλευρά και κέντρο ζυγά, πάντα σε όριο: ακριβώς.
dh_rise:
        ld      a,l
        call    al_node                 ; src/link.asm: al_rx, al_ry, al_rw, al_rh
        ret     c                       ; άδεια θέση: γκρεμίστηκε στο μεταξύ
        ld      de,(vr_w)               ; E = μετά, D = πριν
        ld      a,(dt_a)
        cp      MAX_DOME
        sbc     a,a                     ; #FF θόλος
        cpl
        and     8
        ld      b,a                     ; o: 0 θόλος, 8 δομή
        ld      a,(al_rh)
        add     a,a
        add     a,a
        add     a,a
        add     a,a
        ld      c,a                     ; H, οι γραμμές του πλαισίου (ως 128)
        ; Η πρώτη σειρά: της πάνω γραμμής που φαίνεται τώρα, t(E), όπου t = H -
        ; H x p / 256 οι γραμμές που κρύβονται· με το τελευταίο φορτίο η 0.
        ld      a,e
        or      a
        jr      z,dhr_n
        call    sdr_t
dhr_n:
        call    sdr_row
        push    af
        ; Η τελευταία: της πάνω γραμμής που φαινόταν, t(D) - 1, με το o. Το t(D)
        ; δεν είναι ποτέ 0 (το D είναι κάτω από 255).
        ld      a,d
        call    sdr_t
        dec     a
        add     a,b
        call    sdr_row
        pop     hl                      ; H = η πρώτη
        sub     h
        ret     c                       ; τίποτα καινούργιο σε αυτό το φορτίο
        inc     a
        ld      (vr_h),a                ; πόσες σειρές
        ld      a,b
        rrca
        rrca
        rrca                            ; 1 για τη στήλη μιας δομής
        ld      b,a
        ld      a,(al_rw)
        add     a,b
        ld      (vr_w),a
        ld      a,(al_ry)
        add     a,h
        ld      h,a                     ; η πρώτη σειρά του κόσμου
        ld      a,(al_rx)
        ld      l,a
        ld      (vr_tx),hl              ; vr_tx, vr_ty
        jp      dhr_go                  ; src/dm_hand.asm: όπως ένα ορθογώνιο της κατεδάφισης

; sdr_t — A = πρόοδος, C = H -> A = H - H x A / 256, οι γραμμές που κρύβονται
; από πάνω (το ίδιο ob_mul με το ob_rise). Κρατά BC, DE.
sdr_t:
        push    bc
        push    de
        call    ob_mul                  ; H = οι γραμμές που φαίνονται
        pop     de
        pop     bc
        ld      a,c
        sub     h
        ret

; sdr_row — A = γραμμή του πλαισίου (με το o) -> A = η σειρά της από το al_ry.
sdr_row:
        rrca
        rrca
        rrca
        rrca
        and     15
        ret
