; reserve.asm — το αποθεματικό των μηχανών (βήμα 184, DESIGN §6.5).
;
; Η ΑΠΟΦΑΣΗ ΤΟΥ ΧΡΗΣΤΗ: «τα ίδια τα mines να έχουν χωρητικότητα 6 ώστε όταν
; χρησιμοποιώ από αυτά να ξαναγεμίζουν», «τα μηχανήματα έχουν επίσης
; χωρητικότητα 3». Αποθεματικό πέρα από την αποθήκη, σε μονάδες, και μόνο όπου
; ως το 183 μια γεμάτη αποθήκη σταματούσε τη μηχανή (MF_ADDS: σήμερα μόνο το
; VITROMEAT· οι μετατροπές δεν τη γεμίζουν και συνεχίζουν, βήμα 124). Το ορυχείο
; είναι στο src/haul.asm.
;
;   - ΜΕ ΓΕΜΑΤΗ ΑΠΟΘΗΚΗ η μηχανή δεν σταματά: βγάζει στο δικό της, ως RSV_MAX,
;     και ό,τι περισσεύει από τον τελευταίο γύρο χάνεται, όπως στον σωρό του
;     ορυχείου. Γεμάτο, σταματά όπως ως το 183 — ούτε τρώει ούτε ζητά ρεύμα.
;   - ΜΕ ΧΩΡΟ, το αποθεματικό μπαίνει στην αποθήκη στην επόμενη επίσκεψη της
;     μηχανής (ec_dr1), και ξαναγεμίζει όταν ξαναγεμίσει η αποθήκη.
;
; ΣΤΗΝ ΥΓΕΙΑ ΤΗΣ, ΧΩΡΙΣ ΝΕΟ BYTE: μια μηχανή που δουλεύει έχει MACH_HP (200) —
; το bit 7 είναι το μόνο που κοιτάζουν η παραγωγή, ο χειριστής, η βλάβη και τα
; σήματα — και τα bits 4-5 του είναι μηδέν. Με αποθεματικό r είναι
; MACH_HP + 16 r: 216, 232, 248. Τα κάτω δύο bits, που λένε τι χρωστά μια
; καινούργια (src/install.asm), μένουν μηδέν. Μια βλάβη (υγεία 0) το χάνει, όπως
; και μια κατεδάφιση· το σώσιμο το κρατά.
;
; ΤΟ ΓΕΜΙΣΜΑ ΣΤΗΝ ΤΡΑΠΕΖΑ 0, μετά το erm_inf που πέφτει μέσα του (erv_fill,
; src/econ.asm)· ΤΟ ΑΔΕΙΑΣΜΑ ΕΔΩ, στη σελίδα 2, που φαίνεται πάντα. Η τράπεζα
; 0 είχε 78 bytes και η σελίδα 2 42, και χρειάστηκαν και οι δύο.

        assert  (MACH_HP & #30) == 0 && (MACH_HP & 128)
        ; το πρώτο πάνω από το γεμάτο περνά το 255: το erv_fill το ξέρει από το CY
        assert  MACH_HP + 16 * RSV_MAX <= 255 && MACH_HP + 16 * RSV_MAX + 16 > 255
        assert  P_ALL == 1 && D_HEALTH - D_MACH == 8
        assert  EC_RSV < G_node_occ + 255       ; το 255 είναι του fo_after

; ---------------------------------------------------------------------------
; ec_dr1 — το erd_call (src/econ.asm) για έναν κύκλο ροής μετά από αποθεματικά
; (st_need): πριν τρέξει η μηχανή, το αποθεματικό της στην αποθήκη. HL -> η
; υγεία της (το bit 7: δουλεύει), A = η μηχανή ή το φυτό. Ενα φυτό έχει MACH_HP
; ή 0 (src/fit.asm): περνά όπως μια μηχανή χωρίς αποθεματικό. ΤΟ BIT 5 ΦΤΑΝΕΙ:
; το VITROMEAT βγάζει RSV_Q = 2 τον γύρο, άρα ένα αποθεματικό είναι 0, 2 ή 3
; (232, 248), και το 200 δεν το έχει (9 us με «sub MACH_HP», 17 η πρώτη γραφή).
        assert  RSV_Q >= 2 && RSV_Q <= RSV_MAX && (MACH_HP & #20) == 0
        ; και το «bit 4» του erv_fill (src/econ.asm): γεμάτο είναι μόνο το 3
        assert  RSV_Q == 2 && RSV_MAX == 3 && (MACH_HP & #10) == 0
; ---------------------------------------------------------------------------
ec_dr1:
        bit     5,(hl)
        jp      z,ec_run_one            ; κανένα: 6 us, όσο κοστίζει ο κύκλος ανά υποδοχή
        push    af
        ld      a,(hl)
        ld      (hl),MACH_HP
        sub     MACH_HP
        rrca
        rrca
        rrca
        rrca                            ; το αποθεματικό, 2 ή 3
        ld      e,a
        ld      d,0
        ld      a,S_MEAT                ; η μόνη μηχανή με αποθεματικό (tools/econ.py)
        call    ec_make                 ; src/stock.asm
        pop     af
        jp      ec_run_one
