; graph.asm — ο γράφος κόμβων και οι δύο πίνακες δρομολόγησης (§6.2, §6.4)
;
; Μία BFS ανά πηγή, 96 πηγές, δύο σειρές των 128 bytes η καθεμία:
;
;       DIST[from][to]      άλματα, 255 = απρόσιτος                 (τράπεζα 1)
;       NEXTHOP[from][to]   ο επόμενος κόμβος, 255 = απρόσιτος      (τράπεζα 5)
;
; Και οι δύο σειρές βγαίνουν από την ΙΔΙΑ διάσχιση: όταν η BFS φτάνει πρώτη
; φορά σε γείτονα της πηγής, ο πρώτος κόμβος της διαδρομής είναι ο ίδιος ο
; γείτονας· κάθε άλλος κόμβος τον κληρονομεί από εκείνον που τον ανακάλυψε.
; Χωρίς δεύτερο πέρασμα, χωρίς αποθήκευση διαδρομών.
;
; ΓΙΑΤΙ ΕΙΝΑΙ ΔΙΑΚΟΠΤΟΜΕΝΗ. Μια ολόκληρη πηγή κοστίζει περισσότερο από ένα
; frame. Ο κανόνας 1 του §7.1 λέει ότι κανένα πέρασμα δεν κάνει απεριόριστη
; δουλειά σε ένα frame, οπότε η BFS κόβεται σε **κόμβους**: το rt_slice
; επεκτείνει ως B κόμβους και γυρίζει. Η κατάσταση είναι τέσσερα bytes.
;
; ΓΙΑΤΙ Ο ΠΑΓΚΟΣ ΕΙΝΑΙ ΣΤΗΝ ΤΡΑΠΕΖΑ 2. Η έξοδος γράφεται στις τράπεζες 1 και
; 5, δηλαδή το παράθυρο &4000 αλλάζει μέσα στη ρουτίνα — δύο φορές ανά πηγή.
; Οτιδήποτε διαβάζει η BFS πρέπει να είναι εκτός παραθύρου, και η τράπεζα 2
; είναι πάντα ορατή.

ROWPG       equ G_rt_row >> 8
NODEPG      equ G_rt_nodes >> 8

RT_DIST     equ G_rt_row                ; [0..127]
RT_NEXT     equ G_rt_row + 128          ; [128..255]
NODE_DEG    equ G_rt_nodes              ; [0..127]
RT_QUEUE    equ G_rt_nodes + 128        ; [128..255]

RT_UNREACH  equ 255
RT_RESET    equ 109                     ; 112 + 14k µs έναντι 1.644 του ldir
RT_NODES    equ MAX_NODE                ; 96 — δες const.asm

; ---------------------------------------------------------------------------
; rt_mark — «ο γράφος άλλαξε»: διάδρομος χτίστηκε, γκρεμίστηκε, ή νέο παιχνίδι.
;
; Εδώ και όχι στο wheel.asm, όπου ήταν: το build mode πρέπει να το καλεί και το
; build mode δεν ξέρει τίποτε για τον τροχό — το tests/uitest.asm δεν τον
; συνδέει καν. Το rt_begin μόνο του ΔΕΝ αρκεί: μηδενίζει τον μετρητή πηγών,
; αλλά αυτό που κάνει τον τροχό να τρέξει την ανοικοδόμηση είναι το rt_dirty.
; ---------------------------------------------------------------------------
rt_mark:
        ld      a,1
        ld      (rt_dirty),a
        ; και συνεχίζει στο rt_begin

; ---------------------------------------------------------------------------
; rt_begin — ξεκινά πλήρη ανοικοδόμηση από την πηγή 0.
;
; Τρέχουν ΚΑΙ ΟΙ 96 πηγές, ακόμη κι αν η αποικία έχει δέκα κόμβους. Ένας
; κόμβος που δεν υπάρχει είναι απλώς απομονωμένος, οπότε η σειρά του βγαίνει
; σωστή από μόνη της. Το κέρδος είναι ότι δεν χρειάζεται πέρασμα αρχικοποίησης
; 32 KB, και ότι οι πίνακες δεν έχουν ποτέ μπαγιάτικες σειρές.
; ---------------------------------------------------------------------------
rt_begin:
        xor     a
        ld      (rt_src),a
        ld      hl,128                  ; tail = 128 + 0: «δεν ξέρω τι έχει η
        ld      (rt_tail),hl            ; σειρά», και φάση 0 (rt_open)
        ret

; ---------------------------------------------------------------------------
; rt_slice — ως B επεκτάσεις κόμβων. Επιστρέφει Cy=1 όταν τελείωσαν και οι 96.
;
; Ενας «κόμβος» εδώ είναι μία αφαίρεση από την ουρά μαζί με τους ως 8 γείτονές
; του. Το άνοιγμα (καθάρισμα σειράς) και το κλείσιμο (δύο αντιγραφές των 128
; bytes) μετράνε το καθένα σαν ένας κόμβος — είναι μεγαλύτερα, αλλά σταθερά.
; ---------------------------------------------------------------------------
rt_slice:
        ld      a,(rt_phase)
        or      a
        jr      nz,rts_expand
rts_open:
        call    rt_open
        dec     b
        ret     z                       ; Cy=0 από το rt_open
rts_expand:
        ; --- rt_node: μία αφαίρεση από την ουρά (μέσα στο rt_slice από το
        ; βήμα 103: ένα call, ένα ret και ένα jr λιγότερα ανά κόμβο) ---
        ld      hl,(rt_head)            ; L = head, H = tail
        ld      a,l
        cp      h
        jr      z,rts_empty             ; άδεια: κλείσιμο και επόμενη πηγή
        push    bc
        inc     a
        ld      (rt_head),a

; --- (το rt_node, μέσα στο rt_slice: η ουρά γράφεται από το HL' — κανείς
; άλλος δεν αγγίζει τους σκιώδεις καταχωρητές. Οι αποστάσεις δεν χρειάζονται
; ταβάνι: η BFS σε ως 128 κόμβους δεν ξεπερνά τα 127 άλματα, άρα το dist+1
; δεν φτάνει ποτέ το 255.) ---
        ld      h,NODEPG
        ld      l,(hl)                  ; L = u
        ld      b,(hl)                  ; B = deg[u]
        inc     b
        dec     b
        jr      z,rtn_out               ; μοναχικός κόμβος

        ld      h,ROWPG
        ld      c,(hl)
        inc     c                       ; C = η απόσταση των γειτόνων

        ; --- IXL = ο πρώτος κόμβος της διαδρομής, IXH = η πηγή ---
        ; Το next[u] είναι η πηγή μόνο όταν u = πηγή (το rt_open το βάζει
        ; εκεί): τότε ο πρώτος κόμβος είναι ο ίδιος ο γείτονας.
        set     7,l
        ld      a,(hl)                  ; next[u]
        res     7,l
        ld      ixl,a
        ld      a,(rt_src)
        ld      ixh,a

        ; --- DE = G_node_adj + u*8 = (G_node_adj/8 + u) * 8 (assert) ---
        ld      a,l
        add     a,(G_node_adj >> 3) & 255
        ld      l,a
        ld      h,G_node_adj >> 11
        add     hl,hl
        add     hl,hl
        add     hl,hl
        ex      de,hl

        ld      h,ROWPG                 ; μένει σταθερό σε όλον τον βρόχο
        exx
        ld      hl,(rt_tail)            ; HL' = RT_QUEUE + tail
        exx
        ; --- ο καυτός βρόχος: ως 8 γείτονες, 1.024 ανά πηγή ---
rtn_nb:
        ld      a,(de)                  ; v
        inc     e                       ; η γραμμή των 8 δεν περνά σελίδα
        ld      l,a
        ld      a,(hl)                  ; dist[v]
        inc     a                       ; 255 -> 0
        jr      nz,rtn_skip             ; τον ξέρουμε ήδη
        ld      (hl),c                  ; dist[v] = d
        ld      a,l
        exx
        ld      (hl),a                  ; στην ουρά
        inc     l
        exx
        ld      a,ixl
        cp      ixh
        jr      nz,rtn_have
        ld      a,l                     ; γείτονας της πηγής: ο ίδιος ο v
rtn_have:
        set     7,l
        ld      (hl),a                  ; next[v]
rtn_skip:
        djnz    rtn_nb
        exx
        ld      (rt_tail),hl            ; και το NODEPG πίσω στο rt_phase
        exx
rtn_out:
        pop     bc
        djnz    rts_expand
        or      a
        ret                             ; Cy=0 — μένει δουλειά
rts_empty:
        ; η ουρά άδειασε: κλείσιμο και επόμενη πηγή
        call    rt_flush
        ld      hl,rt_src
        inc     (hl)
        ld      a,(hl)
        dec     hl
        cp      (hl)                    ; rt_n
        ccf
        ret     c                       ; Cy=1 — και οι 96 έτοιμες
        xor     a
        ld      (rt_phase),a
        djnz    rts_open
        ret                             ; Cy=0 από το xor — μένει δουλειά

; ---------------------------------------------------------------------------
; rt_open — καθαρίζει τη σειρά και βάζει την πηγή στην ουρά.
;
; ΚΑΘΑΡΙΖΕΙ ΜΟΝΟ ΟΣΑ ΕΓΡΑΨΕ Η ΠΡΟΗΓΟΥΜΕΝΗ ΠΗΓΗ. Η BFS γράφει dist και next
; μόνο σε όσους κόμβους βάζει στην ουρά, άρα η σειρά είναι 255 παντού εκτός
; από τα queue[0..k) — και αυτό ισχύει και στη μέση μιας πηγής. Μια μοναχική
; πηγή (k = 1) ανοίγει έτσι σε μερικά µs αντί για 1,6 ms, και μια νέα αποικία
; είναι ως επί το πλείστον μοναχικές πηγές: το rt_n είναι πάντα 96 (βήμα 63).
; Το ldir μένει για k = 0, που το rt_begin σημαίνει «άγνωστη σειρά» (νέο
; παιχνίδι, φόρτωμα), και για k > RT_RESET, όπου είναι φθηνότερο.
;
; Οι δείκτες της ουράς κρατιούνται ως 128 + k, δηλαδή είναι ήδη το κάτω byte
; της θέσης στο RT_QUEUE. Το rt_phase γίνεται NODEPG: έτσι η λέξη
; (rt_tail, rt_phase) είναι η διεύθυνση της ουράς και το rt_node τη φορτώνει
; ολόκληρη. Το 128ο στοιχείο πάει τον δείκτη στο 256 = 0· και οι δύο
; τυλίγονται ίδια, οπότε η σύγκριση «άδεια» μένει σωστή.
; ---------------------------------------------------------------------------
rt_open:
        push    bc                      ; το ldir τρώει το BC — και μαζί του τον
        ld      hl,G_rt_row             ; προϋπολογισμό της φέτας
        ld      c,RT_UNREACH
        ld      a,(rt_tail)
        add     a,127                   ; k - 1, και 255 για το k = 0
        cp      RT_RESET
        jr      nc,rto_all
        inc     a
        ld      b,a                     ; k
        ld      de,RT_QUEUE
rto_lp:
        ld      a,(de)                  ; v
        inc     e
        ld      l,a
        ld      (hl),c                  ; dist[v]
        set     7,l
        ld      (hl),c                  ; next[v]
        djnz    rto_lp
        jr      rto_src
rto_all:
        ld      (hl),c
        ld      d,h
        ld      e,l
        inc     de
        ld      bc,255
        ldir                            ; 256 bytes σε 255· το H μένει ROWPG
rto_src:
        ld      a,(rt_src)
        ld      l,a
        ld      (hl),0                  ; dist[src] = 0
        set     7,l
        ld      (hl),a                  ; next[src] = ο εαυτός
        ld      (RT_QUEUE),a
        ld      hl,129 * 256 + 128
        ld      (rt_head),hl            ; head = 0, tail = 1
        ld      a,NODEPG
        ld      (rt_phase),a
        or      a                       ; Cy=0: με αυτό γυρίζει το rt_slice
        pop     bc
        ret


; ---------------------------------------------------------------------------
; rt_flush — η έτοιμη σειρά στις δύο τράπεζες.
;
; Η γραμμή της πηγής s κάθεται στο &4000 + s*128 και στις δύο, και γράφονται
; οι 96 στήλες της, όσοι οι κόμβοι. Πρώτα η 5,
; ώστε η 1 — η προεπιλογή — να είναι αυτή που μένει στο παράθυρο.
; ---------------------------------------------------------------------------
rt_flush:
        push    bc
        ld      a,(rt_src)
        add     a,#80
        rra
        ld      d,a                     ; #40 + s/2
        sbc     a,a
        and     #80
        ld      e,a                     ; (s & 1) * 128

        ld      bc,GA_PORT + PAGE_B5
        out     (c),c
        ld      hl,RT_NEXT
        push    de
        ld      bc,RT_NODES             ; 96, όχι 128 (βήμα 101): οι στήλες
        ldir                            ; 96-127 είναι του ov_run (demolish.asm)
        pop     de

        ld      l,b                     ; HL = RT_DIST: το B είναι 0 μετά το ldir
        ld      bc,GA_PORT + PAGE_B1
        out     (c),c
        ld      bc,RT_NODES
        ldir
        pop     bc
        ret

        assert  (G_rt_row & 255) == 0 && (G_rt_nodes & 255) == 0
        assert  (G_node_adj & 7) == 0 && ((G_node_adj >> 3) & 255) + 128 <= 256
        assert  NODEPG != 0 && RT_NODES <= 128

rt_n:       db RT_NODES             ; ανώτατο id + 1 — βλ. rt_begin
rt_src:     db 0
rt_head:    db 0                    ; 128 + k, όπως και το rt_tail
rt_tail:    db 0
rt_phase:   db 0                    ; 0 = άνοιγμα, NODEPG = επέκταση
rt_dirty:   db 0

        assert  rt_src == rt_n + 1                  ; το rt_slice: dec hl · cp (hl)
        assert  rt_tail == rt_head + 1 && rt_phase == rt_tail + 1
