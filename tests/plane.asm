; plane.asm — δειγματοληψία του επιπέδου κόσμου από ΤΡΕΧΟΝ παιχνίδι.
;
; Το read_ram του εξομοιωτή βλέπει μόνο τα βασικά 64 KB, και το επίπεδο ζει
; στην τράπεζα 4. Αυτό μπαίνει στο #3EC0 — πάνω από τον κώδικα του παιχνιδιού
; και κάτω από το παράθυρο — παίρνει 256 δείγματα ανά 64 bytes (όλο το επίπεδο)
; και τα αφήνει στο #3F00, όπου τα διαβάζει η δοκιμή.
;
; ΗΤΑΝ ΣΤΟ #3E00 ΩΣ ΤΟ ΒΗΜΑ 31, δηλαδή κρατούσε 512 bytes της τράπεζας 0 για
; σαράντα: ο κώδικας είναι 33 bytes και ο buffer 256. Στο #3EC0 κρατά 320, και
; το πάτωμα το επιβάλλει πια το tools/mkdsk.py (TEST_FLOOR) — γιατί όταν ο
; κώδικας του παιχνιδιού έφτασε ως εδώ, η δοκιμή έσβηνε ό,τι πήγαινε να
; δοκιμάσει και κατηγορούσε τον δίσκο.
;
; Είναι η ίδια τρύπα όπου ο φορτωτής αφήνει το επίμετρό του (§13.1): νεκρός
; κώδικας από τη στιγμή που ξεκινά το παιχνίδι.

        org     #3EC0

        di
        ld      bc,#7FC4                ; τράπεζα 4: το επίπεδο
        out     (c),c
        ld      hl,#4000
        ld      de,#3F00
        ld      b,0
pl_lp:
        ld      a,(hl)
        ld      (de),a
        inc     de
        ld      a,l
        add     a,64
        ld      l,a
        jr      nc,pl_no
        inc     h
pl_no:
        djnz    pl_lp
        ld      bc,#7FC0
        out     (c),c
pl_hang:
        jr      pl_hang

        save    "../build/plane.bin", #3EC0, $ - #3EC0
