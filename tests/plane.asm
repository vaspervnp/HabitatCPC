; plane.asm — δειγματοληψία του επιπέδου κόσμου από ΤΡΕΧΟΝ παιχνίδι.
;
; Το read_ram του εξομοιωτή βλέπει μόνο τα βασικά 64 KB, και το επίπεδο ζει
; στην τράπεζα 4. Αυτό μπαίνει στο #3E00 — πάνω από τον κώδικα του παιχνιδιού
; και κάτω από το παράθυρο — παίρνει 256 δείγματα ανά 64 bytes (όλο το επίπεδο)
; και τα αφήνει στο #3F00, όπου τα διαβάζει η δοκιμή.
;
; Το #3E00 είναι η ίδια τρύπα όπου ο φορτωτής αφήνει το επίμετρό του (§13.1):
; νεκρός κώδικας από τη στιγμή που ξεκινά το παιχνίδι. Αν ο κώδικας της
; τράπεζας 0 φτάσει ως εκεί, σπάνε ΚΑΙ τα δύο — γι' αυτό το tools/mkdsk.py το
; ελέγχει σε κάθε build.

        org     #3E00

        di
        ld      bc,#7FC4                ; τράπεζα 4: το επίπεδο
        out     (c),c
        ld      hl,#4000
        ld      de,#3F00
        ld      b,0
pl_lp:
        ld      a,(hl)
        ld      (de),a
        inc     de
        ld      a,l
        add     a,64
        ld      l,a
        jr      nc,pl_no
        inc     h
pl_no:
        djnz    pl_lp
        ld      bc,#7FC0
        out     (c),c
pl_hang:
        jr      pl_hang

        save    "../build/plane.bin", #3E00, $ - #3E00
