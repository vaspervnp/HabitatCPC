; plane.asm — δειγματοληψία του επιπέδου κόσμου από ΤΡΕΧΟΝ παιχνίδι.
;
; Το read_ram του εξομοιωτή βλέπει μόνο τα βασικά 64 KB, και το επίπεδο ζει
; στην τράπεζα 4. Αυτό μπαίνει στο #3800 — πάνω από τον κώδικα του παιχνιδιού
; και κάτω από το παράθυρο — παίρνει 256 δείγματα ανά 64 bytes (όλο το επίπεδο)
; και τα αφήνει στο #3900, όπου τα διαβάζει η δοκιμή.

        org     #3800

        di
        ld      bc,#7FC4                ; τράπεζα 4: το επίπεδο
        out     (c),c
        ld      hl,#4000
        ld      de,#3900
        ld      b,0
pl_lp:
        ld      a,(hl)
        ld      (de),a
        inc     de
        ld      a,l
        add     a,64
        ld      l,a
        jr      nc,pl_no
        inc     h
pl_no:
        djnz    pl_lp
        ld      bc,#7FC0
        out     (c),c
pl_hang:
        jr      pl_hang

        save    "../build/plane.bin", #3800, $ - #3800
